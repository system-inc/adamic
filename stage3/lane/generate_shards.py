#!/usr/bin/env python3
"""Generate the Go shard declarations from the complete version-1 manifest."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

LANE = Path(__file__).resolve().parent


def render(path):
    data = path.read_bytes()
    manifest = json.loads(data)
    units = manifest.get('units', [])
    if manifest.get('version') != 1 or not units:
        raise ValueError('expected nonempty version 1 units')
    names, functions = set(), set()
    lines = ['// Code generated by generate_shards.py; DO NOT EDIT.',
             '// Manifest sha256: ' + hashlib.sha256(data).hexdigest(),
             'package lane', '', 'import "testing"', '']
    for unit in units:
        name = unit['name']
        function = 'TestShard_' + ''.join(part[:1].upper() + part[1:] for part in name.split('-'))
        if name in names or function in functions or not re.fullmatch(r'TestShard_[A-Za-z0-9_]+', function):
            raise ValueError('duplicate or invalid Go shard name: ' + name)
        if not unit.get('command') or set(unit['expect']) != {'pass', 'fail', 'skip'}:
            raise ValueError('invalid unit: ' + name)
        names.add(name); functions.add(function)
        lines += [f'func {function}(t *testing.T) {{', 't.Parallel()',
                  f'runManifestShard(t, {json.dumps(name)})', '}', '']
    return subprocess.check_output(['gofmt'], input='\n'.join(lines).encode(), timeout=10)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--manifest', type=Path, default=LANE / 'shards.json')
    parser.add_argument('--output', type=Path, default=LANE / 'shards_generated_test.go')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    wanted = render(args.manifest)
    if args.check:
        if args.output.read_bytes() != wanted:
            raise SystemExit('generated shard declarations differ from shards.json; run generate_shards.py')
    else:
        args.output.write_bytes(wanted)
