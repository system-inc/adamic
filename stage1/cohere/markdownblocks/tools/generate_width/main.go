// Generate finite emoji matcher instructions from cohere's pinned width data.
package main

import (
	"bytes"
	"crypto/sha256"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"os/exec"
	"path/filepath"
	"regexp/syntax"
	"sort"
	"strconv"
	"strings"
)

func main() {
	source := flag.String("source", "cohere/internal/format/doc/string_width_generated.go", "pinned Go tables")
	output := flag.String("output", "stage1/cohere/markdownblocks/widthTables.ts", "native tables")
	formatter := flag.String("formatter", "/tmp/cssstrings-cohere", "cohere executable for generated source formatting")
	check := flag.Bool("check", false, "verify generated bytes")
	flag.Parse()
	raw, readError := os.ReadFile(*source)
	must(readError)
	tree, parseFileError := parser.ParseFile(token.NewFileSet(), *source, raw, 0)
	must(parseFileError)
	constants := map[string]string{}
	var ranges [][2]int
	ast.Inspect(tree, func(node ast.Node) bool {
		spec, ok := node.(*ast.ValueSpec)
		if !ok || len(spec.Names) != 1 {
			return true
		}
		name := spec.Names[0].Name
		if name == "wideRanges" {
			for _, elt := range spec.Values[0].(*ast.CompositeLit).Elts {
				pair := elt.(*ast.CompositeLit)
				var r [2]int
				for index, x := range pair.Elts {
					value, parseError := strconv.ParseInt(x.(*ast.BasicLit).Value, 0, 32)
					must(parseError)
					r[index] = int(value)
				}
				ranges = append(ranges, r)
			}
		} else if name == "emojiPatternSource" || name == "narrowEmojiPatternSource" {
			value, unquoteError := strconv.Unquote(spec.Values[0].(*ast.BasicLit).Value)
			must(unquoteError)
			constants[name] = value
		}
		return true
	})
	if len(ranges) == 0 || len(constants) != 2 {
		panic("missing pinned tables")
	}
	var buffer bytes.Buffer
	var runeData bytes.Buffer
	var names []string
	fmt.Fprintf(
		&buffer,
		"// Generated from cohere StringWidth data, SHA256 %x.\n// emoji-regex 10.6.0; get-east-asian-width 1.6.0; narrow-emojis 0.0.3.\n// Regenerate: go run ./stage1/cohere/markdownblocks/tools/generate_width\nexport interface WidthInstructionInterface {\n    readonly kind: string;\n    readonly out: number;\n    readonly alternate: number;\n    readonly assertion: number;\n    readonly ranges: readonly number[];\n}\n",
		sha256.Sum256(raw),
	)
	emitRanges := func(name string, pairs [][2]int) {
		fmt.Fprintf(&buffer, "export const %s: readonly number[] = [\n", name)
		for _, pair := range pairs {
			fmt.Fprintf(&buffer, "    %d, %d,\n", pair[0], pair[1])
		}
		fmt.Fprintln(&buffer, "];")
	}
	emitRanges("wideRanges", ranges)
	for _, item := range []struct{ name, constant string }{
		{"emoji", "emojiPatternSource"},
		{"narrow", "narrowEmojiPatternSource"},
	} {
		re, parseError := syntax.Parse(constants[item.constant], syntax.Perl)
		must(parseError)
		prog, compileError := syntax.Compile(re.Simplify())
		must(compileError)
		fmt.Fprintf(
			&buffer,
			"export const %sStart = %d;\nexport const %sInstructions: readonly WidthInstructionInterface[] = [\n",
			item.name,
			prog.Start,
			item.name,
		)
		for _, inst := range prog.Inst {
			kind := ""
			rs := []rune{}
			switch inst.Op {
			case syntax.InstAlt:
				kind = "a"
			case syntax.InstRune, syntax.InstRune1:
				if inst.Arg != 0 {
					panic("fold case not supported")
				}
				kind = "r"
				rs = inst.Rune
				if len(rs) == 1 {
					rs = []rune{rs[0], rs[0]}
				}
			case syntax.InstNop:
				kind = "n"
			case syntax.InstMatch:
				kind = "m"
			case syntax.InstFail:
				kind = "f"
			case syntax.InstEmptyWidth:
				if syntax.EmptyOp(inst.Arg) & ^(syntax.EmptyBeginText|syntax.EmptyEndText) != 0 {
					panic("unsupported assertion")
				}
				kind = "e"
			default:
				panic(fmt.Sprintf("unsupported %s", inst.Op))
			}
			fmt.Fprintf(
				&buffer,
				"    { kind: '%s', out: %d, alternate: %d, assertion: %d, ranges: ",
				kind,
				inst.Out,
				inst.Arg,
				inst.Arg,
			)
			target := &buffer
			if len(rs) > 10 {
				name := fmt.Sprintf("widthRunes%d", len(names))
				names = append(names, name)
				fmt.Fprintf(&buffer, "%s },\n", name)
				fmt.Fprintf(&runeData, "export const %s: readonly number[] = ", name)
				target = &runeData
			}
			target.WriteString("[")
			for index, character := range rs {
				if index > 0 {
					target.WriteString(", ")
				}
				fmt.Fprint(target, int(character))
			}
			if target == &buffer {
				target.WriteString("] },\n")
			} else {
				target.WriteString("];\n")
			}

		}
		fmt.Fprintln(&buffer, "];")
		if item.name == "emoji" {
			var starters [][2]int
			seen := map[uint32]bool{}
			var walk func(uint32)
			walk = func(id uint32) {
				if seen[id] {
					return
				}
				seen[id] = true
				inst := prog.Inst[id]
				switch inst.Op {
				case syntax.InstAlt:
					walk(inst.Out)
					walk(inst.Arg)
				case syntax.InstNop, syntax.InstEmptyWidth:
					walk(inst.Out)
				case syntax.InstRune, syntax.InstRune1:
					if len(inst.Rune) == 1 {
						starters = append(starters, [2]int{int(inst.Rune[0]), int(inst.Rune[0])})
					} else {
						for index := 0; index < len(inst.Rune); index += 2 {
							starters = append(starters, [2]int{int(inst.Rune[index]), int(inst.Rune[index+1])})
						}
					}
				case syntax.InstFail:
				default:
					panic("emoji must not match empty")
				}
			}
			walk(uint32(prog.Start))
			sort.Slice(starters, func(left, right int) bool { return starters[left][0] < starters[right][0] })
			var merged [][2]int
			for _, starter := range starters {
				if len(merged) > 0 && starter[0] <= merged[len(merged)-1][1]+1 {
					if starter[1] > merged[len(merged)-1][1] {
						merged[len(merged)-1][1] = starter[1]
					}
				} else {
					merged = append(merged, starter)
				}
			}
			emitRanges("emojiStarts", merged)
		}
	}
	table := []byte("import { " + strings.Join(names, ", ") + " } from './widthRuneRanges.ts';\n" + buffer.String())
	for _, item := range []struct {
		path string
		data []byte
	}{{*output, table}, {
		filepath.Join(filepath.Dir(*output), "widthRuneRanges.ts"),
		[]byte("// Generated rune classes used by the finite emoji matchers.\n" + runeData.String()),
	}} {
		temporary, temporaryFileError := os.CreateTemp("", "adamic-width-*.ts")
		must(temporaryFileError)
		defer os.Remove(temporary.Name())
		_, writeError := temporary.Write(item.data)
		must(writeError)
		must(temporary.Close())
		formatted, combinedOutputError := exec.Command(
			*formatter,
			"--no-cache",
			"--fix",
			temporary.Name(),
		).CombinedOutput()
		if combinedOutputError != nil {
			panic(fmt.Sprintf("formatter: %v %s", combinedOutputError, formatted))
		}
		result, readError := os.ReadFile(temporary.Name())
		must(readError)
		if *check {
			actual, readError := os.ReadFile(item.path)
			must(readError)
			if !bytes.Equal(actual, result) {
				panic("generated tables changed")
			}
		} else {
			must(os.WriteFile(item.path, result, 0644))
		}
	}
}
func must(sourceError error) {
	if sourceError != nil {
		panic(sourceError)
	}
}
