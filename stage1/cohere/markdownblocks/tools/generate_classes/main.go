// Capture cohere's pinned prose classes as native numeric range data.
package main

import (
	"bytes"
	"crypto/sha256"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"os/exec"
	"strconv"
)

func main() {
	source := flag.String("source", "cohere/internal/format/markdown/classes_generated.go", "pinned Go classes")
	output := flag.String("output", "stage1/cohere/markdownblocks/textClasses.ts", "native data")
	formatter := flag.String("formatter", "/tmp/cssstrings-cohere", "cohere formatter executable")
	check := flag.Bool("check", false, "compare generated bytes")
	flag.Parse()
	raw, readError := os.ReadFile(*source)
	must(readError)
	tree, parseFileError := parser.ParseFile(token.NewFileSet(), *source, raw, 0)
	must(parseFileError)
	var buffer bytes.Buffer
	fmt.Fprintf(
		&buffer,
		"// Pinned cohere prose classes, source SHA256 %x.\n// Regenerate: go run ./stage1/cohere/markdownblocks/tools/generate_classes\n",
		sha256.Sum256(raw),
	)
	count := 0
	ast.Inspect(tree, func(node ast.Node) bool {
		spec, ok := node.(*ast.ValueSpec)
		if !ok {
			return true
		}
		if len(spec.Names) != 1 || len(spec.Values) != 1 {
			panic("unexpected class declaration")
		}
		name := spec.Names[0].Name
		value, ok := spec.Values[0].(*ast.CompositeLit)
		if !ok {
			panic("expected literal ranges")
		}
		count++
		fmt.Fprintf(&buffer, "export const %s: readonly number[] = [\n", name)
		for _, element := range value.Elts {
			pair := element.(*ast.CompositeLit)
			if len(pair.Elts) != 2 {
				panic("expected range pair")
			}
			for _, point := range pair.Elts {
				value, parseError := strconv.ParseInt(point.(*ast.BasicLit).Value, 0, 32)
				must(parseError)
				fmt.Fprintf(&buffer, "    %d,\n", value)
			}
		}
		fmt.Fprintln(&buffer, "];")
		return false
	})
	if count != 5 {
		panic("expected five classes")
	}
	temporary, temporaryFileError := os.CreateTemp("", "adamic-text-classes-*.ts")
	must(temporaryFileError)
	defer os.Remove(temporary.Name())
	_, writeError := temporary.Write(buffer.Bytes())
	must(writeError)
	must(temporary.Close())
	out, combinedOutputError := exec.Command(*formatter, "--no-cache", "--fix", temporary.Name()).CombinedOutput()
	if combinedOutputError != nil {
		panic(fmt.Sprintf("cohere: %v %s", combinedOutputError, out))
	}
	result, readError := os.ReadFile(temporary.Name())
	must(readError)
	if *check {
		actual, readError := os.ReadFile(*output)
		must(readError)
		if !bytes.Equal(actual, result) {
			panic("generated classes changed")
		}
	} else {
		must(os.WriteFile(*output, result, 0644))
	}
}
func must(sourceError error) {
	if sourceError != nil {
		panic(sourceError)
	}
}
