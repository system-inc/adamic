//go:build lintoracle

package main

import (
	"encoding/json"
	"github.com/system-inc/cohere/internal/lint/rule"
	rules "github.com/system-inc/cohere/internal/lint/rules/react"
)

func oracleWave22SortDefaultProps() rule.Rule { return rules.SortDefaultProps }
func oracleWave22SortDefaultPropsOptions(fields []string) any {
	options := rules.DefaultSortDefaultPropsOptions()
	if len(fields) > 5 && fields[5] != "" {
		if err := json.Unmarshal([]byte(fields[5]), &options); err != nil {
			panic(err)
		}
	}
	return options
}
