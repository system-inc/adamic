"""Generate supplemental Object integrity units without renumbering the core corpus."""
import hashlib
import json
import re
import subprocess


def generate(root, families):
    manifest = []
    sources = sorted((root / 'internal/oracle/testdata/object_integrity').glob('*.a'))
    for package in ['flow', 'fresh']:
        text = '// Code generated by review/test-split-flow/generate.py; DO NOT EDIT.\n'
        text += 'package ' + ('flow' if package == 'flow' else 'fresh_test') + '\n\nimport "testing"\n\n'
        kinds = families if package == 'flow' else [('Writes', 'checkFreshProgram')]
        for source in sources:
            relative = '../oracle/testdata/object_integrity/' + source.name
            label = re.sub('[^A-Za-z0-9]', '_', relative)
            digest = hashlib.sha256(relative.encode()).hexdigest()[:12]
            name = ('TestFlowProgram_' if package == 'flow' else 'TestFreshWrites_') + label + '_' + digest
            helper = 'checkAllFlowProgram' if package == 'flow' else 'checkFreshProgram'
            text += 'func ' + name + '(t *testing.T) {\n\tt.Parallel()\n\tbegin' + package.title() + 'Unit(t)\n\t' + helper + '(t, ' + json.dumps(relative) + ')\n}\n\n'
            for kind, _ in kinds:
                manifest.append({'package': package, 'family': kind, 'test': name,
                                 'program': str(source.relative_to(root)), 'path': relative,
                                 'sha256': hashlib.sha256(source.read_bytes()).hexdigest()})
        formatted = subprocess.run(['gofmt'], input=text, capture_output=True, text=True, check=True).stdout
        (root / 'internal' / package / 'corpus_object_integrity_units_test.go').write_text(formatted)
    return manifest
