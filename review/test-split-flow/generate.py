#!/usr/bin/env python3
"""Generate directly selectable tests for the original program globs."""
import glob
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess

root = Path(__file__).resolve().parents[2]
patterns = ['dedication/dedication.a', 'internal/load/testdata/0.1/compile/*.ts',
            'internal/load/testdata/0.1/compile/07_modules/main.ts', 'internal/oracle/testdata/*.a',
            'internal/oracle/testdata/*.ts', 'internal/oracle/testdata/modules/main.a', 'internal/flow/testdata/*.a']
excluded = {'killed_after_output.a', 'size_class_churn.a', 'bitwise_sweep.a',
            'typed_arrays_primes_large.a', 'normalize_coverage_long.a'}
# Read the explicit lists from the corpus owner so generation follows main's exclusions.
flow_source = (root / 'internal/flow/flow_test.go').read_text()
flow_excluded = set()
for helper in ['refusedConstructorFixture', 'refusedGettersCensusFixture', 'uninstrumentedAsyncFixture']:
    function = re.search(r'func ' + helper + r'\(path string\) bool \{(.*?)\n\}', flow_source, re.S)
    assert function, 'missing flow exclusion helper: ' + helper
    switch = re.fullmatch(r'\s*switch filepath.Base\(path\) \{\s*case (.*?)\s*:\s*return true\s*\}\s*return false\s*', function[1], re.S)
    assert switch, 'flow exclusion helper changed shape: ' + helper
    names = re.findall(r'"([^"\n]+)"', switch[1])
    assert names and re.sub(r'"[^"\n]+"|[\s,]', '', switch[1]) == '', 'unparsed flow exclusions'
    flow_excluded.update(names)

# Boundary witnesses return their exact refusal instead of a boolean.
helper = 'runtimeBoundaryLoweringReason'
function = re.search(r'func ' + helper + r'\(path string\) string \{(.*?)\n\}', flow_source, re.S)
assert function, 'missing flow exclusion helper: ' + helper
switch = re.fullmatch(r'\s*switch filepath.Base\(path\) \{(.*?)\}\s*return ""\s*', function[1], re.S)
assert switch, 'flow exclusion helper changed shape: ' + helper
arm = re.compile(r'\s*case ((?:"[^"\n]+"[\s,]*)+):\s*return ("(?:[^"\\\n]|\\.)*")\s*')
cases = list(arm.finditer(switch[1]))
assert cases, 'missing boundary cases: ' + helper
assert arm.sub('', switch[1]).strip() == '', 'unparsed flow exclusions: ' + helper
for case in cases:
    assert json.loads(case[2]), 'empty boundary refusal: ' + helper
    flow_excluded.update(re.findall(r'"([^"\n]+)"', case[1]))

# Mirrors flow_test.go's programs(): its deliberate .a refusal controls are excluded too.
def refused(name):
    if name.endswith('.a') and (name.startswith('non_null_refuse_') or name.startswith('non_null_possible_')):
        return True
    return name in flow_excluded

families = [('SingleAssignment', 'checkSingleAssignmentProgram'), ('MutationRanges', 'checkMutationRangesProgram'), ('GraphPaths', 'checkGraphPathsProgram'), ('Liveness', 'checkLivenessProgram')]
manifest = []
for package in ['flow', 'fresh']:
    # Dedicated units append their own registrations; preserve their ownership.
    owned = set()
    for owner in sorted((root / 'internal' / package).glob('*_units_test.go')):
        if owner.name == 'corpus_units_test.go':
            continue
        owned.update(re.findall(package + r'CorpusPaths = append\(' + package + r'CorpusPaths, "([^"]+)"\)', owner.read_text()))
    paths = []
    for pattern in patterns:
        for path in sorted(glob.glob(str(root / pattern))):
            source = Path(path)
            # flow's programs() globs the non-null .ts controls too; fresh's doesn't.
            if package == 'fresh' and source.suffix == '.ts' and source.name.startswith('non_null'):
                continue
            if package == 'flow' and (source.name in excluded or refused(source.name)):
                continue
            relative = Path(os.path.relpath(source, root / 'internal' / package)).as_posix()
            if relative in owned:
                continue
            paths.append(relative)
    assert len(paths) == len(set(paths))
    kinds = families if package == 'flow' else [('Writes', 'checkFreshProgram')]
    rows = []
    for kind, helper in kinds:
        group = []
        for relative in paths:
            label = re.sub('[^A-Za-z0-9]', '_', relative)
            digest = hashlib.sha256(relative.encode()).hexdigest()[:12]
            name = 'Test' + package.title() + kind + '_' + label + '_' + digest
            if package == 'flow' and relative != '../oracle/testdata/timsort.a':
                name = 'TestFlowProgram_' + label + '_' + digest
            group.append((relative, name, helper))
            source = (root / 'internal' / package / relative).resolve()
            manifest.append({'package':package,'family':kind,'test':name,'program':str(source.relative_to(root)),
                             'path':relative,'sha256':hashlib.sha256(source.read_bytes()).hexdigest()})
        rows.append(group)
    text = '// Code generated by review/test-split-flow/generate.py; DO NOT EDIT.\n'
    text += 'package ' + ('flow' if package == 'flow' else 'fresh_test') + '\n\nimport "testing"\n\n'
    text += 'var ' + package + 'CorpusPaths = []string{\n'
    text += ''.join('\t' + json.dumps(path) + ',\n' for path in paths) + '}\n\n'
    text += 'var ' + package + 'CorpusTests = [][]func(*testing.T){\n'
    for group in rows:
        text += '\t{\n' + ''.join('\t\t' + name + ',\n' for _,name,_ in group) + '\t},\n'
    text += '}\n\n'
    for group in rows:
        for index, (relative,name,helper) in enumerate(group):
            if package == "flow" and relative != "../oracle/testdata/timsort.a":
                name = "TestFlowProgram_" + re.sub("[^A-Za-z0-9]", "_", relative) + "_" + hashlib.sha256(relative.encode()).hexdigest()[:12]
                if group != rows[0]:
                    continue
                helper = "checkAllFlowProgram"
            text += 'func ' + name + '(t *testing.T) {\n\tt.Parallel()\n\tbegin' + package.title() + 'Unit(t)\n\t' + helper + '(t, ' + package + 'CorpusPaths[' + str(index) + '])\n}\n\n'
    # Written through gofmt, so the generated file is as gofmt -l expects it.
    formatted = subprocess.run(['gofmt'], input=text, capture_output=True, text=True, check=True).stdout
    (root / 'internal' / package / 'corpus_units_test.go').write_text(formatted)
(root/'review/test-split-flow/units.json').write_text(json.dumps(manifest,indent=2)+'\n')
print('Generated', len(manifest), 'program units')
