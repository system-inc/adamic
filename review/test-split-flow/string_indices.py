"""Regenerate isolated String indices and primitive conversion corpus units."""
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess

def generate(root, package, families):
    rows = []
    text = '// Code generated by review/test-split-flow/generate.py; DO NOT EDIT.\n'
    text += 'package ' + ('flow' if package == 'flow' else 'fresh_test') + '\n\nimport "testing"\n\n'
    for source in sorted((root/'internal/oracle/testdata/string_indices').glob('*.a')):
        relative = Path(os.path.relpath(source, root/'internal'/package)).as_posix()
        name = 'Test' + package.title() + ('Program' if package == 'flow' else 'Writes') + '_' + re.sub('[^A-Za-z0-9]', '_', relative) + '_' + hashlib.sha256(relative.encode()).hexdigest()[:12]
        helper = 'checkAllFlowProgram' if package == 'flow' else 'checkFreshProgram'
        text += 'func ' + name + '(t *testing.T) {\n\tt.Parallel()\n\tbegin' + package.title() + 'Unit(t)\n\t' + helper + '(t, ' + json.dumps(relative) + ')\n}\n\n'
        for kind, _ in (families if package == 'flow' else [('Writes', helper)]):
            rows.append({'package':package,'family':kind,'test':name,'program':str(source.relative_to(root)), 'path':relative,'sha256':hashlib.sha256(source.read_bytes()).hexdigest()})
    text = subprocess.run(['gofmt'], input=text, text=True, capture_output=True, check=True).stdout
    (root/'internal'/package/'corpus_string_indices_units_test.go').write_text(text)
    return rows
