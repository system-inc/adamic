// Package javascript compiles Adamic's IR to JavaScript: the second backend, and half of the oracle.
//
// It mirrors the native backend's model rather than borrowing JavaScript's: a captured variable is an
// explicit cell, a closure is its code and its cells, a global is checked against the temporal dead
// zone by the same ready flag. That makes it a test of the IR itself. If lowering got a capture, an
// evaluation order or a scope wrong, this program's output differs from Node running the source, with
// nothing of C involved. Counting references has no meaning here, so it's the one thing left out.
//
// It also carries every check the compiler inserts, the same ones native does, which is what lets the
// oracle hold a program whose checks fire: there, Node running the source doesn't have them.
package javascript

import (
	"fmt"
	"regexp"
	"strconv"
	"strings"

	"github.com/system-inc/adamic/internal/ir"
)

// JavaScript is a program as one JavaScript module, importing panic and the functions that read and
// write files from 'adamic'.
func JavaScript(program *ir.Program) string {
	return JavaScriptWith(program, Options{})
}

// Options adds to what JavaScript emits, for tests that watch a program run. The zero value adds
// nothing.
type Options struct {
	// ModuleExports exposes the entry module's functions under their source names.
	ModuleExports bool
	// RuntimeImport replaces 'adamic'; empty keeps the ordinary backend contract.
	RuntimeImport string
	// ExternalFunctions replaces a definition with a call to an imported JS function.
	ExternalFunctions map[int]string

	// Mark, when set, is called for each point internal/flow's graph has an instruction for: a
	// statement (by its address in its slice) and a part of it, as flow.Instruction.Part numbers them.
	// The JavaScript expression it returns is evaluated each time the program reaches that point,
	// just before the point itself runs.
	Mark func(at *ir.Statement, part int) string

	// Enter and Leave, when set, are JavaScript expressions evaluated as each call of a function
	// starts and as it ends, however it ends short of a panic.
	Enter           func(function int) string
	Leave           func(function int) string
	Suspend, Resume func() string
}

// JavaScriptWith is JavaScript with options.
func JavaScriptWith(program *ir.Program, options Options) string {
	emitter := &emitter{program: program, options: options}
	var builder strings.Builder
	runtimeImport := "'adamic'"
	if options.RuntimeImport != "" {
		runtimeImport = quote(options.RuntimeImport)
	}
	fmt.Fprintf(
		&builder,
		"// Generated by adamic from %s. Do not edit.\n\nimport { encodeJson, decodeJson, fileStatus, panic, programArguments, readDirectory, readTextFile, utf8At, utf8Length, writeTextFile } from %s;\n\n",
		program.Source,
		runtimeImport,
	)
	jsonDescriptorPosition := builder.Len()
	// A closure is its code and its cells, an instance of its own class so typeof can tell it from an
	// object that happens to have fields of those names.
	builder.WriteString(
		"class AdamicClosure {\n\tconstructor(code, cells, receiver = false, length = 0) {\n\t\tthis.code = code;\n\t\tthis.cells = cells;\n\t\tthis.receiver = receiver;\n\t\tthis.length = length;\n\t}\n}\n",
	)
	builder.WriteString(
		"const adamicCanonical = (identity, code, cells, length) => { const values = identity.functions ??= new Map(); if (!values.has(code)) values.set(code, new AdamicClosure(code, cells, false, length)); return values.get(code); };\n",
	)
	builder.WriteString("const adamicTypeOf = (value) => value instanceof AdamicClosure ? 'function' : typeof value;\n")
	builder.WriteString(fieldReadinessRuntime)
	if options.RuntimeImport == "" {
		builder.WriteString("import { createHash as adamicNodeCreateHash } from 'node:crypto';\n")
	}
	builder.WriteString(iteratorClassRuntime)
	builder.WriteString(hostMemoryUsageRuntime)
	builder.WriteString(collectionIteratorRuntime)
	builder.WriteString(stringIteratorRuntime)
	builder.WriteString(jsonStringifyRuntime)
	counted := false
	for _, function := range program.Functions {
		counted = counted || function.ArgumentsCount != 0
	}
	if counted {
		builder.WriteString(
			"const adamicDirect = (fn, values, count = values.length - (fn.adamicReceiver ? 1 : 0)) => fn(...(fn.adamicCount ? [count] : []), ...values);\n",
		)
	}
	builder.WriteString(recordRuntime)
	builder.WriteString("const adamicCall = (closure, values) => closure.code(closure, values);\n")
	// A static constructor's live parent prototype carries inherited fields. Keep its
	// named method map separately, keyed by the actual constructor function.
	builder.WriteString("const adamicStaticMethods = new WeakMap();\n")
	// object.name(...) through an interface: the object's own function value, or else its class's
	// method (on the prototype its constructor gave it), called with the object as this.
	if counted {
		builder.WriteString(
			"const adamicCallee = (object, name) => { if (Object.hasOwn(object, name)) { const fn = object[name]; return fn.receiver ? { code: (closure, values) => adamicCall(fn, [object, ...values]) } : fn; } const methods = adamicStaticMethods.get(object); const fn = methods && Object.hasOwn(methods, name) ? methods[name] : object[name]; return { code: (closure, values) => adamicDirect(fn, [object, ...values]) }; };\n",
		)
	} else {
		builder.WriteString(
			"const adamicCallee = (object, name) => { if (Object.hasOwn(object, name)) { const fn = object[name]; return fn.receiver ? { code: (closure, values) => adamicCall(fn, [object, ...values]) } : fn; } const methods = adamicStaticMethods.get(object); const fn = methods && Object.hasOwn(methods, name) ? methods[name] : object[name]; return { code: (closure, values) => fn(object, ...values) }; };\n",
		)
	}
	builder.WriteString(
		"const adamicOptionalCall = (object, name, values) => object === undefined ? undefined : adamicCall(adamicCallee(object, name), values());\n",
	)
	builder.WriteString(
		"const adamicParallelMap = (items, work) => items.map((item, index) => adamicCall(work, [item, index]));\n",
	)
	// The array and the callback are each evaluated once, in that order, before the first call.
	builder.WriteString(
		"const adamicVisit = (array, method, callback) => array[method]((element, index, all) => adamicCall(callback, [element, index, all]));\n",
	)
	// map reads the length once, as JavaScript's does; an array the callback shrinks would leave a hole,
	// which 0.1 has no way to hold, so it's a panic, the same one native's map has.
	builder.WriteString(
		"const adamicMap = (array, callback) => {\n\tconst count = array.length;\n\tconst mapped = [];\n\tfor (let index = 0; index < count; index++) {\n\t\tif (index >= array.length) panic('map: the array shrank while it was being mapped');\n\t\tmapped.push(adamicCall(callback, [array[index], index, array]));\n\t}\n\treturn mapped;\n};\n",
	)
	// Searches Get removed indices as undefined and check the callback's declared
	// admission before passing the value, as the native backend does.
	builder.WriteString(
		"const adamicFind = (array, method, callback, admitsUndefined, elementType) => {\n\tconst count = array.length;\n\tconst last = method === 'findLast' || method === 'findLastIndex';\n\tconst valueResult = method === 'find' || method === 'findLast';\n\tfor (let step = 0; step < count; step++) {\n\t\tconst index = last ? count - 1 - step : step;\n\t\tif (index >= array.length && !admitsUndefined) panic(`${method}: index ${index} is undefined; element type ${elementType} does not admit undefined`);\n\t\tconst element = array[index];\n\t\tif (adamicCall(callback, [element, index, array])) return valueResult ? element : index;\n\t}\n\treturn valueResult ? undefined : -1;\n};\n",
	)
	// A Map's forEach gives value, key and the map; a Set's gives its element twice and the set.
	builder.WriteString(
		"const adamicCollectionVisit = (collection, callback) => collection.forEach((value, key, all) => adamicCall(callback, [value, key, all]));\n",
	)
	builder.WriteString(
		"const adamicFrom = (length, callback) => Array.from({ length }, (element, index) => adamicCall(callback, [element, index]));\n",
	)
	builder.WriteString("const adamicDefinedNull = (value, message) => value === null ? panic(message) : value;\n")
	builder.WriteString("const adamicDefined = (value, message) => value === undefined ? panic(message) : value;\n")
	builder.WriteString(
		"const adamicSort = (array, callback) => array.sort((left, right) => adamicCall(callback, [left, right]));\n",
	)
	builder.WriteString(
		"const adamicReduce =(array, callback, initial) => array.reduce((carried, element, index, all) => adamicCall(callback, [carried, element, index, all]), initial);\n",
	)
	builder.WriteString(
		"const adamicSetIndex = (array, index, value) => {\n\tif (!(Number.isInteger(index) && index >= 0 && index < array.length)) panic(`index ${index} is outside an array of length ${array.length}`);\n\tarray[index] = value;\n};\n",
	)
	builder.WriteString(
		"const adamicCast = (object, field, allowed, message) => allowed.includes(object[field]) ? object : panic(message);\n",
	)
	builder.WriteString(
		"const adamicUnready = (name) => { throw new ReferenceError(`Cannot access '${name}' before initialization`); };\n\n",
	)
	if program.HasGenerators() {
		// A step and its done test are two nodes (ir/generator.go): the step keeps what next() said.
		builder.WriteString(
			"const adamicGeneratorSteps = new WeakMap();\nconst adamicGeneratorNext = (generator) => { const step = generator.next(); adamicGeneratorSteps.set(generator, step.done === true); return step.value; };\nconst adamicGeneratorDone = (generator) => adamicGeneratorSteps.get(generator);\n",
		)
		// An iterable view's dispatch reads the kind from the prototype chain every generator object
		// has, %GeneratorPrototype%, never from a name a program's object could also carry
		// (Symbol.toStringTag), and closes a generator as a for-of's exit does.
		builder.WriteString(
			"const adamicGeneratorPrototype = Object.getPrototypeOf((function* () {}).prototype);\nconst adamicIsGenerator = (value) => value !== null && typeof value === 'object' && adamicGeneratorPrototype.isPrototypeOf(value);\nconst adamicIteratorClose = (value) => { if (adamicIsGenerator(value)) value.return(undefined); };\n\n",
		)
	}
	if len(program.Classes) > 0 {
		builder.WriteString(classCountRuntime(
			"const adamicClassIdentities = new WeakMap();\nconst adamicClass = (value, id) => { const metadata = adamicClasses[id - 1]; if (metadata.literal) { const result = {}; for (const name of metadata.publicKeys) { const descriptor = Object.hasOwn(metadata.accessors, name) ? metadata.accessors[name] : undefined; if (descriptor) Object.defineProperty(result, name, {enumerable: true, get: descriptor.get === undefined ? undefined : () => adamicGetAccessor(result, name), set: descriptor.set === undefined ? undefined : (next) => adamicSetAccessor(result, name, next)}); else result[name] = value[name]; } for (const name of metadata.privateFields) Object.defineProperty(result, name, {value: value[name], enumerable: false}); value = result; } else for (const name of metadata.privateFields) Object.defineProperty(value, name, {enumerable: false}); if (metadata.static) { const storage = value; value = function () {}; adamicStaticMethods.set(value, Object.getPrototypeOf(storage)); if (metadata.parent) Object.setPrototypeOf(value, storage[metadata.parent]); for (const name of metadata.privateFields) Object.defineProperty(value, name, {value: storage[name], writable: true, configurable: true}); } adamicClassIdentities.set(value, id); return value; };\nconst adamicInstanceOf = (value, wanted) => { for (let id = adamicClassIdentities.get(value); id; id = adamicClasses[id - 1].base) { if (id === wanted || (adamicClasses[wanted - 1].definition && adamicClasses[id - 1].definition === adamicClasses[wanted - 1].definition)) return true; } return false; };\nconst adamicVirtual = (value, slot, ...args) => adamicDirect(adamicClasses[adamicClassIdentities.get(value) - 1].methods[slot], [value, ...args]);\n",
			counted,
		))
		// A class's accessors are an object literal, so only its own entries are accessors: indexed bare, an
		// Object.prototype name (valueOf, toString, constructor) finds Object's own member, which the walk
		// took for an accessor without a getter, so a base class's getter of that name read through a
		// subclass called undefined, and an object literal's data member of that name was defined as an
		// accessor without a getter, where native's class->accessors holds only each class's own (#76y1mth).
		builder.WriteString(classCountRuntime(
			"const adamicFindAccessor = (value, name) => { for (let id = adamicClassIdentities.get(value); id; id = adamicClasses[id - 1].base) { const accessors = adamicClasses[id - 1].accessors; if (Object.hasOwn(accessors, name)) return accessors[name]; } };\nconst adamicGetAccessor = (value, name) => { const get = adamicFindAccessor(value, name).get; return typeof get === 'string' ? adamicCall(value[get], [value]) : adamicDirect(get, [value]); };\nconst adamicSetAccessor = (value, name, next) => { const set = adamicFindAccessor(value, name).set; return typeof set === 'string' ? adamicCall(value[set], [value, next]) : adamicDirect(set, [value, next]); };\n",
			counted,
		))
		classes := []string{}
		for _, class := range program.Classes {
			methods := []string{}
			for _, method := range class.Methods {
				methods = append(methods, functionName(program, method))
			}
			hidden := []string{}
			for _, field := range class.Fields {
				if field.Private {
					hidden = append(hidden, quote(field.Name))
				}
			}
			publicKeys := []string{}
			for _, field := range class.PublicFields {
				publicKeys = append(publicKeys, quote(field.Name))
			}
			accessors := []string{}
			for _, accessor := range class.Accessors {
				getter, setter := "undefined", "undefined"
				if accessor.Getter >= 0 {
					getter = functionName(program, accessor.Getter)
					if program.Functions[accessor.Getter].Closure {
						getter = quote(fmt.Sprintf("#accessor:%d", accessor.Getter))
					}
				}
				if accessor.Setter >= 0 {
					setter = functionName(program, accessor.Setter)
					if program.Functions[accessor.Setter].Closure {
						setter = quote(fmt.Sprintf("#accessor:%d", accessor.Setter))
					}
				}
				accessors = append(
					accessors,
					fmt.Sprintf("[%s]: {get: %s, set: %s}", quote(accessor.Name), getter, setter),
				)
			}
			parent := ""
			if class.StaticParent != 0 {
				parent = class.Fields[class.StaticParent-1].Name
			}
			classes = append(classes, fmt.Sprintf(
				"{static: %t, parent: %s, base: %d, methods: [%s], definition: %d, privateFields: [%s], literal: %t, publicKeys: [%s], accessors: {%s}}",
				class.Static,
				quote(parent),
				class.Base,
				strings.Join(methods, ", "),
				class.Definition,
				strings.Join(hidden, ", "),
				class.Literal,
				strings.Join(publicKeys, ", "),
				strings.Join(accessors, ", "),
			))
		}
		fmt.Fprintf(&builder, "const adamicClasses = [%s];\n", strings.Join(classes, ", "))
	}
	for index, local := range program.Locals {
		if local.Global {
			fmt.Fprintf(&builder, "let %s;\nlet %s = false;\n", emitter.name(index), readyName(index))
			if local.Uninitialized {
				fmt.Fprintf(&builder, "let %s_declared = false;\n", readyName(index))
			}
		}
	}
	for index, function := range program.Functions {
		emitter.indent = 1
		emitter.function = &program.Functions[index]
		parameters := []string{}
		if function.Closure {
			parameters = []string{"self", "values"}
		} else {
			for _, parameter := range function.Parameters {
				name := emitter.name(parameter)
				if function.RestElement != 0 && parameter == function.Parameters[len(function.Parameters)-1] {
					name = "..." + name
				}
				parameters = append(parameters, name)
			}
		}
		if function.ArgumentsCount != 0 && !function.Closure {
			parameters = append([]string{emitter.name(function.ArgumentsCount - 1)}, parameters...)
		}
		prefix, star := "", ""
		if function.Async {
			prefix = "async "
		}
		if function.Generator {
			star = "*"
		}
		fmt.Fprintf(
			&builder,
			"\n"+prefix+"function%s %s(%s) {\n",
			star,
			functionName(program, index),
			strings.Join(parameters, ", "),
		)
		if external, ok := options.ExternalFunctions[index]; ok {
			if function.Closure {
				panic("javascript: external function cannot be a closure")
			}
			fmt.Fprintf(&builder, "\treturn %s(%s);\n}\n", external, strings.Join(parameters, ", "))
			continue
		}

		if function.Closure {
			if function.ArgumentsCount != 0 {
				count := "values.length"
				if function.Receiver {
					count += " - 1"
				}
				emitter.line("let %s = %s;", emitter.name(function.ArgumentsCount-1), count)
			}
			for position, parameter := range function.Parameters {
				if function.RestElement != 0 && position == len(function.Parameters)-1 {
					emitter.line("let %s = values.slice(%d);", emitter.name(parameter), position)
				} else {
					emitter.line("let %s = values[%d];", emitter.name(parameter), position)
				}
			}
		}
		emitter.allocateEnvironment(function.FrameEnvironment)
		for _, parameter := range function.Parameters {
			if program.Locals[parameter].EnvironmentCell {
				emitter.line("%s.value = %s;", emitter.cellName(parameter), emitter.name(parameter))
				emitter.line("%s.ready = true;", emitter.cellName(parameter))
			} else if program.Locals[parameter].Captured {
				emitter.line(
					"const %s = { value: %s, ready: true };",
					emitter.cellName(parameter),
					emitter.name(parameter),
				)
			}
		}
		if options.Enter != nil {
			if function.Async && options.Suspend != nil {
				emitter.line("const adamicActivation = %s;", options.Enter(index))
			} else {
				emitter.line("%s;", options.Enter(index))
			}
			emitter.line("try {")
			emitter.indent++
		}
		emitter.statements(function.Body)
		if options.Leave != nil {
			emitter.indent--
			emitter.line("} finally {")
			emitter.line("\tif (!adamicProcessExiting()) { %s; }", options.Leave(index))
			emitter.line("}")
		}
		builder.WriteString(emitter.out.String())
		emitter.out.Reset()
		builder.WriteString("}\n")
	}
	emitter.function = nil
	emitter.indent = 0
	builder.WriteString("\n")
	for index, function := range program.Functions {
		if function.ArgumentsCount != 0 && !function.Closure {
			fmt.Fprintf(&builder, "%s.adamicCount = true;\n", functionName(program, index))
		}
		if function.Receiver && function.ArgumentsCount != 0 {
			fmt.Fprintf(&builder, "%s.adamicReceiver = true;\n", functionName(program, index))
		}
	}
	// Each class's methods, the prototype of the objects its constructor makes, declared before the
	// program runs; a class's methods are functions, hoisted, so each is there to name.
	emitter.statements(program.Main)
	for _, prototype := range emitter.prototypes {
		builder.WriteString(prototype)
	}
	if program.AsyncEntry != 0 {
		emitter.line("await %s();", functionName(program, program.AsyncEntry-1))
	}
	builder.WriteString(emitter.out.String())
	if options.ModuleExports {
		for index, exported := range program.Exports {
			name := ""
			if exported.Function >= 0 {
				name = functionName(program, exported.Function)
			}
			if exported.Function < 0 {
				name = fmt.Sprintf("exported_%d", index)
				fmt.Fprintf(
					&builder,
					"const %s = (...values) => adamicCall(%s, values);\n",
					name,
					emitter.variable(exported.Local),
				)
			}
			fmt.Fprintf(&builder, "export { %s as %s };\n", name, quote(exported.Name))
		}
	}

	code := builder.String()
	if len(emitter.jsonDescriptors) != 0 {
		code = code[:jsonDescriptorPosition] + strings.Join(emitter.jsonDescriptors, "") + code[jsonDescriptorPosition:]
	}
	if emitter.hostCalleeUsed {
		const callee = "const adamicCallee = (object, name) => { "
		code = strings.Replace(
			code,
			callee,
			callee+
				"if (object === performance || object === process.stdout._handle) return { code: (closure, values) => object[name](...values) }; ",
			1,
		)
	}
	if emitter.processExitUsed {
		code = "import { processExit as adamicProcessExit, processExiting as adamicProcessExiting } from " +
			runtimeImport +
			";\n" +
			code
	} else if strings.Contains(code, "adamicProcessExiting()") {
		// A custom runtime need not expose Node exit helpers for programs without exit.
		code = "const adamicProcessExiting = () => false;\n" + code
	}
	if strings.Contains(code, "adamicWatchFileListener(") {
		code = nodeWatchFileRuntime + code
	}
	if strings.Contains(code, "adamicHostEnvironment(") {
		code = nodeEnvironmentRuntime() + code
	}
	if strings.Contains(code, "adamicDynamicGet(") {
		code = dynamicKeyedRuntime(program) + code
	}
	if strings.Contains(code, "adamicDynamicHas(") ||
		strings.Contains(code, "adamicDynamicRead(") ||
		strings.Contains(code, "adamicHostKeys(") ||
		strings.Contains(code, "adamicHostHasOwn(") ||
		strings.Contains(code, "adamicHostCheck(") {
		code = dynamicHostRuntime(program) + code
	}
	if strings.Contains(code, "adamicUnknownKind(") {
		code = unknownKindRuntime(program) + code
	}
	if strings.Contains(code, "adamicArrayOfScalars(") || strings.Contains(code, "adamicJoinEnter(") {
		code = joinRuntime + code
	}
	if strings.Contains(code, "adamicNodeTmpdir()") {
		code = "import { tmpdir as adamicNodeTmpdir } from 'node:os';\n" + code
	}
	if strings.Contains(code, "adamicNodeFS.") {
		code = "import * as adamicNodeFS from 'node:fs';\n" + code
	}
	if strings.Contains(code, "adamicNodeFSFile.") {
		code = "import * as adamicNodeFSFile from 'node:fs';\n" + code
	}
	for _, module := range []struct{ name, path string }{
		{"adamicNodePath", "node:path"},
		{"adamicNodeOS", "node:os"},
		{"adamicNodeProcess", "node:process"},
	} {
		if strings.Contains(code, module.name+".") {
			code = "import * as " + module.name + " from '" + module.path + "';\n" + code
		}
	}
	return code
}

// Only compiler runtime text is rewritten; source literals are emitted later.
func classCountRuntime(runtime string, counted bool) string {
	if counted {
		return runtime
	}
	runtime = strings.ReplaceAll(
		runtime,
		"adamicDirect(adamicClasses[adamicClassIdentities.get(value) - 1].methods[slot], [value, ...args])",
		"adamicClasses[adamicClassIdentities.get(value) - 1].methods[slot](value, ...args)",
	)
	runtime = strings.ReplaceAll(runtime, "adamicDirect(get, [value])", "get(value)")
	return strings.ReplaceAll(runtime, "adamicDirect(set, [value, next])", "set(value, next)")
}

type emitter struct {
	processExitUsed     bool
	hostCalleeUsed      bool
	program             *ir.Program
	options             Options
	function            *ir.Function
	out                 strings.Builder
	indent              int
	labels              int
	jsonDescriptorNames map[string]string
	jsonDescriptors     []string

	// prototypes declares each class's methods, in the order the constructors that make them are
	// emitted, and prototypeNames names each by its constructor's literal.
	prototypes     []string
	prototypeNames map[string]string

	// continues holds, innermost last, each open loop's continue label.
	continues  []string
	breakables []string
}

func (javascriptEmitter *emitter) line(format string, arguments ...any) {
	javascriptEmitter.out.WriteString(strings.Repeat("\t", javascriptEmitter.indent))
	fmt.Fprintf(&javascriptEmitter.out, format, arguments...)
	javascriptEmitter.out.WriteString("\n")
}

var identifier = regexp.MustCompile(`[^A-Za-z0-9_]`)

func (javascriptEmitter *emitter) name(local int) string {
	return Name(javascriptEmitter.program, local)
}

// Name is the JavaScript name of a local that isn't captured (a captured one lives in a cell), for a
// test that reads it through Options.Mark.
func Name(program *ir.Program, local int) string {
	return fmt.Sprintf("local_%d_%s", local, identifier.ReplaceAllString(program.Locals[local].Name, ""))
}

func (javascriptEmitter *emitter) cellName(local int) string {
	return javascriptEmitter.name(local) + "_cell"
}

// ready reads the same captured readiness cell as the binding it guards.
func (javascriptEmitter *emitter) ready(local int) string {
	if binding := javascriptEmitter.program.Locals[local].Ready; binding != 0 {
		return javascriptEmitter.variable(binding - 1)
	}
	if javascriptEmitter.program.Locals[local].Captured && !javascriptEmitter.program.Locals[local].Global {
		return javascriptEmitter.cell(local) + ".ready"
	}
	return readyName(local)
}

func readyName(local int) string {
	return fmt.Sprintf("ready_%d", local)
}

func functionName(program *ir.Program, function int) string {
	return fmt.Sprintf("function_%d_%s", function, identifier.ReplaceAllString(program.Functions[function].Name, ""))
}

// prototype names the object holding a class's methods by name, declaring it the first time.
func (javascriptEmitter *emitter) prototype(methods []ir.Method) string {
	entries := []string{}
	for _, method := range methods {
		entries = append(entries, quote(method.Name)+": "+functionName(javascriptEmitter.program, method.Function))
	}
	key := strings.Join(entries, ", ")
	if name, isDeclared := javascriptEmitter.prototypeNames[key]; isDeclared {
		return name
	}
	if javascriptEmitter.prototypeNames == nil {
		javascriptEmitter.prototypeNames = map[string]string{}
	}
	name := fmt.Sprintf("methods_%d", len(javascriptEmitter.prototypes))
	javascriptEmitter.prototypeNames[key] = name
	// Class prototypes inherit Object methods, just as the source classes do.
	javascriptEmitter.prototypes = append(
		javascriptEmitter.prototypes,
		fmt.Sprintf("const %s = { __proto__: Object.prototype, %s };\n", name, key),
	)
	return name
}

// variable is where a local's value is, from the current function: a cell of its environment, a cell
// it declared, or the plain name.
func (javascriptEmitter *emitter) variable(local int) string {
	declared := javascriptEmitter.program.Locals[local]
	if declared.Captured && !declared.Global {
		if javascriptEmitter.function != nil {
			for position, captured := range javascriptEmitter.function.Environment {
				if captured == local {
					return fmt.Sprintf("self.cells[%d].value", position)
				}
			}
		}
		return javascriptEmitter.cellName(local) + ".value"
	}
	return javascriptEmitter.name(local)
}

func (javascriptEmitter *emitter) cell(local int) string {
	if javascriptEmitter.function != nil {
		for position, captured := range javascriptEmitter.function.Environment {
			if captured == local {
				return fmt.Sprintf("self.cells[%d]", position)
			}
		}
	}
	return javascriptEmitter.cellName(local)
}

// statements emits each statement where it stands in its slice, the address Options.Mark names it by.
func (javascriptEmitter *emitter) statements(statements []ir.Statement) {
	for index := range statements {
		javascriptEmitter.statement(&statements[index])
	}
}

// mark is the JavaScript Options.Mark gives for a point, or "" with no Mark.
func (javascriptEmitter *emitter) mark(at *ir.Statement, part int) string {
	if javascriptEmitter.options.Mark == nil {
		return ""
	}
	return javascriptEmitter.options.Mark(at, part)
}

// markLine marks a point with a statement of its own.
func (javascriptEmitter *emitter) markLine(at *ir.Statement, part int) {
	if mark := javascriptEmitter.mark(at, part); mark != "" {
		javascriptEmitter.line("%s;", mark)
	}
}

// marked is an expression that marks a point as it's evaluated, and is value.
func (javascriptEmitter *emitter) marked(at *ir.Statement, part int, value string) string {
	if mark := javascriptEmitter.mark(at, part); mark != "" {
		return fmt.Sprintf("(%s, %s)", mark, value)
	}
	return value
}

func (javascriptEmitter *emitter) nested(statements []ir.Statement) {
	javascriptEmitter.indent++
	javascriptEmitter.statements(statements)
	javascriptEmitter.indent--
}

func (javascriptEmitter *emitter) declare(local int, value string) {
	declared := javascriptEmitter.program.Locals[local]
	if declared.IterationCell && !declared.Preallocated {
		javascriptEmitter.line("%s = { value: %s, ready: true };", javascriptEmitter.cellName(local), value)
		return
	}
	if declared.Captured && declared.Preallocated {
		javascriptEmitter.line("%s.value = %s;", javascriptEmitter.cell(local), value)
		javascriptEmitter.line("%s.ready = true;", javascriptEmitter.cell(local))
		return
	}
	if declared.Captured {
		javascriptEmitter.line("let %s = { value: %s, ready: true };", javascriptEmitter.cellName(local), value)
		return
	}
	javascriptEmitter.line("let %s = %s;", javascriptEmitter.name(local), value)
}

func (javascriptEmitter *emitter) statement(at *ir.Statement) {
	switch (*at).(type) {
	case ir.Labeled, ir.Block, ir.Loop, ir.ForOf, ir.Switch, ir.Break, ir.Continue, ir.Try, ir.Debugger, ir.SourceLine:
		// Marked inside, where their parts run, or not at all: a block, a break and a continue run
		// nothing of their own.
	default:
		javascriptEmitter.markLine(at, 0)
	}
	switch statement := (*at).(type) {
	case ir.SourceLine:
		// Native source metadata has no JavaScript effect.
	case ir.Debugger:
		javascriptEmitter.line("debugger;")
	case ir.WriteLine:
		stream := "log"
		if statement.Stream == ir.Stderr {
			stream = "error"
		}
		javascriptEmitter.line("console.%s(%s);", stream, javascriptEmitter.value(statement.Value))
	case ir.AllocateEnvironment:
		// Emitted at function entry before parameter cells are initialized.
	case ir.Declare:
		if statement.CopyCell {
			javascriptEmitter.line(
				"%s = { value: %s.value, ready: true };",
				javascriptEmitter.cellName(statement.Local),
				javascriptEmitter.cellName(statement.Local),
			)
			return
		}
		if wait, ok := statement.Value.(ir.Await); ok && javascriptEmitter.options.Suspend != nil {
			javascriptEmitter.tracedAwait(at, wait, statement.Local)
			return
		}
		if statement.Uninitialized && !javascriptEmitter.program.Locals[statement.Local].Uninitialized {
			if javascriptEmitter.program.Locals[statement.Local].IterationCell {
				javascriptEmitter.line(
					"%s = { value: undefined, ready: false };",
					javascriptEmitter.cellName(statement.Local),
				)
				return
			}
			if javascriptEmitter.program.Locals[statement.Local].EnvironmentCell {
				return
			}
			if javascriptEmitter.program.Locals[statement.Local].Captured {
				javascriptEmitter.line(
					"let %s = { value: undefined, ready: false };",
					javascriptEmitter.cellName(statement.Local),
				)
			}
			return
		}
		value := "undefined"
		if statement.Value != nil {
			value = javascriptEmitter.value(statement.Value)
		} else {
			value = zero(javascriptEmitter.program.Locals[statement.Local].Type)
		}
		if javascriptEmitter.program.Locals[statement.Local].Global {
			javascriptEmitter.line("%s = %s;", javascriptEmitter.name(statement.Local), value)
			javascriptEmitter.line("%s = %t;", readyName(statement.Local), !statement.Uninitialized &&
				(!javascriptEmitter.program.Locals[statement.Local].NamespaceState || statement.Value != nil))
			if javascriptEmitter.program.Locals[statement.Local].Uninitialized {
				javascriptEmitter.line("%s_declared = true;", readyName(statement.Local))
			}
			return
		}
		javascriptEmitter.declare(statement.Local, value)
		if javascriptEmitter.program.Locals[statement.Local].Uninitialized {
			if javascriptEmitter.program.Locals[statement.Local].Captured {
				javascriptEmitter.line(
					"%s = %t;",
					javascriptEmitter.localReady(statement.Local),
					!statement.Uninitialized,
				)
			} else {
				javascriptEmitter.line("let %s = %t;", readyName(statement.Local), !statement.Uninitialized)
			}
		}
	case ir.Assign:
		value := javascriptEmitter.value(statement.Value)
		if javascriptEmitter.program.Locals[statement.Local].Uninitialized &&
			javascriptEmitter.program.Locals[statement.Local].Global &&
			!javascriptEmitter.program.Locals[statement.Local].Hoisted {
			temporary := javascriptEmitter.temporary()
			javascriptEmitter.line("const %s = %s;", temporary, value)
			javascriptEmitter.line(
				"if (!%s_declared) adamicUnready(%s);",
				readyName(statement.Local),
				quote(javascriptEmitter.program.Locals[statement.Local].Name),
			)
			value = temporary
		}
		if statement.Checked {
			// After the value, as JavaScript does: the right side runs, then the write throws.
			temporary := javascriptEmitter.temporary()
			javascriptEmitter.line("const %s = %s;", temporary, value)
			javascriptEmitter.line(
				"if (!%s) adamicUnready(%s);",
				javascriptEmitter.ready(statement.Local),
				quote(javascriptEmitter.program.Locals[statement.Local].Name),
			)
			value = temporary
		}
		javascriptEmitter.line("%s = %s;", javascriptEmitter.variable(statement.Local), value)
		if javascriptEmitter.program.Locals[statement.Local].Uninitialized {
			javascriptEmitter.line("%s = %t;", javascriptEmitter.localReady(statement.Local), !statement.Uninitialized)
		} else if javascriptEmitter.program.Locals[statement.Local].NamespaceState {
			javascriptEmitter.line("%s = true;", readyName(statement.Local))
		}
	case ir.Evaluate:
		if wait, ok := statement.Value.(ir.Await); ok && javascriptEmitter.options.Suspend != nil {
			javascriptEmitter.tracedAwait(at, wait, -1)
			return
		}
		javascriptEmitter.line("%s;", javascriptEmitter.value(statement.Value))
	case ir.Panic:
		javascriptEmitter.line("panic(%s);", javascriptEmitter.value(statement.Message))
	case ir.SetProperty:
		if javascriptEmitter.program.CheckedField(statement.ViewReceiverTypeID, statement.Name) &&
			!statement.Define &&
			!statement.Uninitialized {
			javascriptEmitter.line("%s;", javascriptEmitter.checkedViewWrite(
				statement,
				javascriptEmitter.value(statement.Object),
				javascriptEmitter.value(statement.Value),
			))
			break
		}
		if statement.Define || statement.Uninitialized {
			representation := viewFieldRepresentation(statement.Value)
			if statement.Uninitialized && statement.Value.Type() == ir.Union {
				representation = int(ir.Union)
			}
			javascriptEmitter.line(
				"adamicDefineField(%s, %s, %s, %t, %t, %d);",
				javascriptEmitter.value(statement.Object),
				quote(statement.Name),
				javascriptEmitter.value(statement.Value),
				!strings.HasPrefix(statement.Name, "#"),
				!statement.Uninitialized || statement.Unset,
				representation,
			)
		} else {
			javascriptEmitter.line(
				"adamicWriteField(%s, %s, %s);",
				javascriptEmitter.value(statement.Object),
				quote(statement.Name),
				javascriptEmitter.value(statement.Value),
			)
		}
	case ir.SetIndex:
		javascriptEmitter.line(
			"adamicSetIndex(%s, %s, %s);",
			javascriptEmitter.value(statement.Array),
			javascriptEmitter.value(statement.Index),
			javascriptEmitter.value(statement.Value),
		)
	case ir.Return:
		if statement.Value == nil {
			javascriptEmitter.line("return;")
		} else {
			javascriptEmitter.line("return %s;", javascriptEmitter.value(statement.Value))
		}
	case ir.If:
		javascriptEmitter.line("if (%s) {", javascriptEmitter.value(statement.Condition))
		javascriptEmitter.nested(statement.Then)
		if len(statement.Else) > 0 {
			javascriptEmitter.line("} else {")
			javascriptEmitter.nested(statement.Else)
		}
		javascriptEmitter.line("}")
	case ir.Labeled:
		javascriptEmitter.line("source_%s: {", statement.Name)
		javascriptEmitter.nested(statement.Body)
		javascriptEmitter.line("}")
	case ir.Block:
		javascriptEmitter.line("{")
		if statement.Closes != 0 && len(statement.Body) > 1 {
			// An iterable view's dispatch: its first statement declares the local it holds, and every
			// way out of the rest closes what that holds, as a for-of's exit calls return().
			javascriptEmitter.nested(statement.Body[:1])
			javascriptEmitter.line("\ttry {")
			javascriptEmitter.indent++
			javascriptEmitter.nested(statement.Body[1:])
			javascriptEmitter.indent--
			javascriptEmitter.line("\t} finally {")
			javascriptEmitter.line(
				"\t\tadamicIteratorClose(%s);",
				javascriptEmitter.value(ir.Read{Local: statement.Closes - 1, Of: ir.Object}),
			)
			javascriptEmitter.line("\t}")
		} else {
			javascriptEmitter.nested(statement.Body)
		}
		javascriptEmitter.line("}")
	case ir.Loop:
		javascriptEmitter.loop(at, statement)
	case ir.ForOf:
		javascriptEmitter.forOf(at, statement)
	case ir.Switch:
		label := javascriptEmitter.temporary()
		javascriptEmitter.breakables = append(javascriptEmitter.breakables, label)
		javascriptEmitter.line("%s: do {", label)
		javascriptEmitter.indent++
		value := javascriptEmitter.temporary()
		javascriptEmitter.markLine(at, 0)
		javascriptEmitter.line("const %s = %s;", value, javascriptEmitter.value(statement.Value))
		part := 0
		for index, matched := range statement.Cases {
			tests := []string{}
			for _, testCase := range matched.Tests {
				part++
				tests = append(tests, javascriptEmitter.marked(
					at,
					part,
					fmt.Sprintf("%s === %s", value, javascriptEmitter.value(testCase)),
				))
			}
			prefix := "} else if"
			if index == 0 {
				prefix = "if"
			}
			javascriptEmitter.line("%s (%s) {", prefix, strings.Join(tests, " || "))
			javascriptEmitter.nested(matched.Body)
		}
		if len(statement.Cases) > 0 {
			javascriptEmitter.line("} else {")
			javascriptEmitter.nested(statement.Default)
			javascriptEmitter.line("}")
		} else {
			javascriptEmitter.statements(statement.Default)
		}
		javascriptEmitter.indent--
		javascriptEmitter.line("} while (false);")
		javascriptEmitter.breakables = javascriptEmitter.breakables[:len(javascriptEmitter.breakables)-1]
	case ir.Break:
		if statement.Label != "" {
			javascriptEmitter.line("break source_%s;", statement.Label)
		} else {
			javascriptEmitter.line(
				"break %s;",
				javascriptEmitter.breakables[len(javascriptEmitter.breakables)-1-statement.Depth],
			)
		}
	case ir.Continue:
		if statement.Label != "" {
			javascriptEmitter.line("break source_continue_%s;", statement.Label)
		} else {
			javascriptEmitter.line("break %s;", javascriptEmitter.continues[len(javascriptEmitter.continues)-1])
		}
	case ir.Throw:
		javascriptEmitter.line("throw %s;", javascriptEmitter.value(statement.Value))
	case ir.Try:
		javascriptEmitter.line("try {")
		javascriptEmitter.nested(statement.Body)
		if statement.HasCatch {
			caught := javascriptEmitter.temporary()
			javascriptEmitter.line("} catch (%s) {", caught)
			javascriptEmitter.indent++
			javascriptEmitter.line("if (adamicProcessExiting()) throw %s;", caught)
			// Stack exhaustion is terminal before user handlers or instrumentation run.
			javascriptEmitter.line(
				"if (%s instanceof RangeError && %s.message === %s) panic(%s);",
				caught,
				caught,
				quote("Maximum call stack size exceeded"),
				quote(stackOverflowMessage),
			)
			// Part 1 of a try is its catch taking the error (flow.Instruction.Part).
			javascriptEmitter.markLine(at, 1)
			if statement.CatchLocal >= 0 {
				javascriptEmitter.declare(statement.CatchLocal, caught)
			}
			javascriptEmitter.statements(statement.Catch)
			javascriptEmitter.indent--
		}
		if statement.HasFinally {
			javascriptEmitter.line("} finally {")
			javascriptEmitter.indent++
			javascriptEmitter.line("if (!adamicProcessExiting()) {")
			javascriptEmitter.nested(statement.Finally)
			javascriptEmitter.line("}")
			javascriptEmitter.indent--
		}
		javascriptEmitter.line("}")
	default:
		panic(fmt.Sprintf("javascript: no JavaScript for %T", statement))
	}
}

func (javascriptEmitter *emitter) temporary() string {
	javascriptEmitter.labels++
	return fmt.Sprintf("temporary_%d", javascriptEmitter.labels)
}

// loop emits every loop as the native backend does: for (;;), the condition as an if that breaks,
// the body in a labeled block a continue breaks out of, then the per-iteration copies and the update.
func (javascriptEmitter *emitter) loop(at *ir.Statement, statement ir.Loop) {
	javascriptEmitter.labels++
	label := fmt.Sprintf("continue_%d", javascriptEmitter.labels)
	breakLabel := javascriptEmitter.temporary()
	javascriptEmitter.breakables = append(javascriptEmitter.breakables, breakLabel)
	javascriptEmitter.line("%s: for (;;) {", breakLabel)
	javascriptEmitter.indent++
	if !statement.CheckAfter {
		javascriptEmitter.statements(statement.Test)
		javascriptEmitter.line(
			"if (!%s) break;",
			javascriptEmitter.marked(at, 0, "("+javascriptEmitter.value(statement.Condition)+")"),
		)
	}
	for _, name := range statement.Labels {
		javascriptEmitter.line("source_continue_%s: {", name)
		javascriptEmitter.indent++
	}
	javascriptEmitter.continues = append(javascriptEmitter.continues, label)
	javascriptEmitter.line("%s: {", label)
	javascriptEmitter.nested(statement.Body)
	javascriptEmitter.line("}")
	javascriptEmitter.continues = javascriptEmitter.continues[:len(javascriptEmitter.continues)-1]
	for range statement.Labels {
		javascriptEmitter.indent--
		javascriptEmitter.line("}")
	}
	for _, local := range statement.PerIteration {
		if javascriptEmitter.program.Locals[local].Captured {
			javascriptEmitter.line(
				"%s = { value: %s.value, ready: %s.ready };",
				javascriptEmitter.cellName(local),
				javascriptEmitter.cellName(local),
				javascriptEmitter.cellName(local),
			)
		}
	}
	javascriptEmitter.statements(statement.Update)
	if statement.CheckAfter {
		javascriptEmitter.statements(statement.Test)
		javascriptEmitter.line(
			"if (!%s) break;",
			javascriptEmitter.marked(at, 0, "("+javascriptEmitter.value(statement.Condition)+")"),
		)
	}
	javascriptEmitter.indent--
	javascriptEmitter.line("}")
	javascriptEmitter.breakables = javascriptEmitter.breakables[:len(javascriptEmitter.breakables)-1]
}

func (javascriptEmitter *emitter) forOf(at *ir.Statement, statement ir.ForOf) {
	javascriptEmitter.labels++
	label := fmt.Sprintf("continue_%d", javascriptEmitter.labels)
	held, index := javascriptEmitter.temporary(), javascriptEmitter.temporary()
	javascriptEmitter.line("{")
	javascriptEmitter.indent++
	javascriptEmitter.markLine(at, 0)
	javascriptEmitter.line("const %s = %s;", held, javascriptEmitter.value(statement.Iterable))
	breakLabel := javascriptEmitter.temporary()
	javascriptEmitter.breakables = append(javascriptEmitter.breakables, breakLabel)
	javascriptEmitter.line("%s:", breakLabel)
	switch {
	case statement.MapPart == "keys" || statement.MapPart == "values":
		javascriptEmitter.line("for (const %s of %s.%s()) {", index, held, statement.MapPart)
	case statement.Iterable.Type() == ir.String || statement.MapPart != "" || statement.RegexIterator:
		// A string's code points, or a map's [key, value] entries.
		javascriptEmitter.line("for (const %s of %s) {", index, held)
	default:
		javascriptEmitter.line("for (let %s_index = 0; %s_index < %s.length; %s_index++) {", index, index, held, index)
		javascriptEmitter.line("\tconst %s = %s[%s_index];", index, held, index)
	}
	javascriptEmitter.indent++
	for _, name := range statement.Labels {
		javascriptEmitter.line("source_continue_%s: {", name)
		javascriptEmitter.indent++
	}
	javascriptEmitter.continues = append(javascriptEmitter.continues, label)
	javascriptEmitter.line("%s: {", label)
	javascriptEmitter.indent++
	javascriptEmitter.markLine(at, 1)
	if statement.Pattern != nil {
		for _, binding := range statement.Pattern {
			javascriptEmitter.declare(binding.Local, fmt.Sprintf("%s[%s]", index, quote(binding.Field)))
		}
	} else {
		javascriptEmitter.declare(statement.Local, index)
	}
	javascriptEmitter.statements(statement.Body)
	javascriptEmitter.indent--
	javascriptEmitter.line("}")
	javascriptEmitter.continues = javascriptEmitter.continues[:len(javascriptEmitter.continues)-1]
	for range statement.Labels {
		javascriptEmitter.indent--
		javascriptEmitter.line("}")
	}
	javascriptEmitter.indent--
	javascriptEmitter.line("}")
	javascriptEmitter.indent--
	javascriptEmitter.line("}")
	javascriptEmitter.breakables = javascriptEmitter.breakables[:len(javascriptEmitter.breakables)-1]
}

