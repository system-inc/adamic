// Package native compiles Adamic's IR to C, and C to a native binary with clang.
//
// C is the first backend because clang already runs everywhere Adamic means to: Xcode's clang for
// macOS and iOS, the NDK's for Android, and decades of optimization come with it. The C is written
// for -Wall -Wextra -Werror, and the tests compile it under the address and undefined-behavior
// sanitizers.
package native

import (
	"embed"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"github.com/system-inc/adamic/internal/ir"
)

//go:embed runtime/adamic.c runtime/adamic.h
var runtime embed.FS

// C is a program as one C translation unit, to be compiled with the runtime.
func C(program *ir.Program) string {
	var builder strings.Builder
	fmt.Fprintf(&builder, "// Generated by adamic from %s. Do not edit.\n\n#include \"adamic.h\"\n\n", program.Source)
	for index, value := range program.Strings {
		fmt.Fprintf(&builder, "static const char adamic_string_%d[] = %s;\n", index, cString(value))
	}
	if len(program.Strings) > 0 {
		builder.WriteString("\n")
	}
	builder.WriteString("int main(void) {\n")
	for _, instruction := range program.Main {
		switch instruction := instruction.(type) {
		case ir.WriteLine:
			stream := "adamic_stdout"
			if instruction.Stream == ir.Stderr {
				stream = "adamic_stderr"
			}
			fmt.Fprintf(&builder, "\tadamic_write_line(%s, adamic_string_%d, sizeof adamic_string_%d - 1);\n", stream, instruction.String, instruction.String)
		default:
			// Lowering only produces instructions this switch knows; a new one must be taught here
			// before it can be lowered, so reaching this is a compiler bug, and it says so loudly.
			panic(fmt.Sprintf("native: no C for %T", instruction))
		}
	}
	builder.WriteString("\treturn 0;\n}\n")
	return builder.String()
}

// cString is a C string literal holding exactly value's bytes.
//
// Every byte outside printable ASCII becomes a three-digit octal escape, which can't run into the
// character after it the way \x can, and quote, backslash and question mark are escaped too, the last
// so no ?? can ever read as a trigraph.
func cString(value string) string {
	var builder strings.Builder
	builder.WriteByte('"')
	for index := 0; index < len(value); index++ {
		character := value[index]
		switch {
		case character == '"' || character == '\\' || character == '?':
			builder.WriteByte('\\')
			builder.WriteByte(character)
		case character >= 0x20 && character < 0x7f:
			builder.WriteByte(character)
		default:
			fmt.Fprintf(&builder, "\\%03o", character)
		}
	}
	builder.WriteByte('"')
	return builder.String()
}

// Options says how to compile.
type Options struct {
	// Sanitize compiles with the address and undefined-behavior sanitizers, as the tests do.
	Sanitize bool
}

// Build compiles C source and the runtime into a native binary at output.
func Build(source string, output string, options Options) error {
	directory, err := os.MkdirTemp("", "adamic-build-")
	if err != nil {
		return fmt.Errorf("native: %w", err)
	}
	defer os.RemoveAll(directory)

	files := map[string]string{"main.c": source}
	for _, name := range []string{"adamic.c", "adamic.h"} {
		contents, err := runtime.ReadFile("runtime/" + name)
		if err != nil {
			return fmt.Errorf("native: %w", err)
		}
		files[name] = string(contents)
	}
	for name, contents := range files {
		if err := os.WriteFile(filepath.Join(directory, name), []byte(contents), 0o644); err != nil {
			return fmt.Errorf("native: %w", err)
		}
	}

	arguments := []string{"-std=c11", "-Wall", "-Wextra", "-Werror", "-pedantic"}
	if options.Sanitize {
		arguments = append(arguments, "-O1", "-g", "-fsanitize=address,undefined", "-fno-sanitize-recover=all")
	} else {
		arguments = append(arguments, "-O2")
	}
	arguments = append(arguments, "-o", output, filepath.Join(directory, "main.c"), filepath.Join(directory, "adamic.c"))
	command := exec.Command("clang", arguments...)
	if combined, err := command.CombinedOutput(); err != nil {
		return fmt.Errorf("native: clang failed: %w\n%s", err, combined)
	}
	return nil
}
