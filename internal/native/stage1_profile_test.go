const profileControl = "// Generated by adamic from profile.a\n#include \"adamic.h\"\nint main(void) { return 0; }\n"

func profileProductInputs(t *testing.T, name string) buildcache.Inputs {
	t.Helper()
	profdata, err := profileDataTool()
	if err != nil {
		t.Fatal(err)
	}
	return buildcache.Inputs{Name: "stage1-profile-" + name, Files: []string{"internal/native"}, Toolchain: []string{buildcache.Tool("clang", "--version"), buildcache.Tool(profdata, "--version")}}
}
func profileTraining(t *testing.T) string {
	t.Helper()
	return buildcache.Product(t, profileProductInputs(t, "training"), func(directory string) error {
		binary := filepath.Join(directory, "generate")
		if err := Build(profileControl, binary, Options{Release: true, Split: true, ProfileGenerate: true}); err != nil {
			return err
		}
		raw := filepath.Join(directory, "train.profraw")
		command := toolchain.Command(binary)
		command.Env = append(command.Env, "LLVM_PROFILE_FILE="+raw)
		if output, err := command.CombinedOutput(); err != nil || len(output) != 0 {
			return fmt.Errorf("training: %v %s", err, output)
		}
		profdata, err := profileDataTool()
		if err != nil {
			return err
		}
		text := filepath.Join(directory, "profile.txt")
		if output, err := toolchain.Command(profdata, "merge", "--text", raw, "-o", text).CombinedOutput(); err != nil {
			return fmt.Errorf("merge: %v %s", err, output)
		}
		data, err := os.ReadFile(text)
		if err != nil {
			return err
		}
		record, err := NewStage1ProfileManifest(profileControl, data, "control-training")
		if err != nil {
			return err
		}
		data, err = json.Marshal(record)
		if err != nil {
			return err
		}
		return os.WriteFile(filepath.Join(directory, "manifest.json"), data, 0644)
	})
}
func profileBuilt(t *testing.T, name string) string {
	t.Helper()
	training := profileTraining(t)
	return buildcache.Product(t, profileProductInputs(t, name), func(directory string) error {
		old, had := os.LookupEnv("XDG_CACHE_HOME")
		defer func() {
			if had {
				os.Setenv("XDG_CACHE_HOME", old)
			} else {
				os.Unsetenv("XDG_CACHE_HOME")
			}
		}()
		scratch, err := os.MkdirTemp("", "profile-cold-")
		if err != nil {
			return err
		}
		defer os.RemoveAll(scratch)
		os.Setenv("XDG_CACHE_HOME", scratch)
		options, err := prepareStage1Profile(profileControl, Options{Release: true, Split: true, Profile: filepath.Join(training, "profile.txt")})
		if err != nil {
			return err
		}
		if !options.profileValidated {
			return fmt.Errorf("profile fell back")
		}
		return Build(profileControl, filepath.Join(directory, "binary"), options)
	})
}
