// Not parallel: may prepare cold-cache products outside the tree build.
func TestStage1ProfileDeterminism(t *testing.T) {
	a, err := os.ReadFile(filepath.Join(profileBuilt(t, "cold-a"), "binary"))
	if err != nil {
		t.Fatal(err)
	}
	b, err := os.ReadFile(filepath.Join(profileBuilt(t, "cold-b"), "binary"))
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(a, b) {
		t.Fatal("profile binaries differ across cold caches")
	}
	b = bytes.Clone(b)
	b[len(b)/2] ^= 1
	if bytes.Equal(a, b) {
		t.Fatal("binary byte mutant survived")
	}
}
