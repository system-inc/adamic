func profileMismatch(t *testing.T, change func(*Stage1ProfileManifest)) {
	t.Helper()
	record, text := stage1Record(t)
	change(&record)
	data, err := json.Marshal(record)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(filepath.Dir(text), "manifest.json"), data, 0644); err != nil {
		t.Fatal(err)
	}
	options, err := prepareStage1Profile(profileControl, Options{Release: true, Split: true, Profile: text})
	if err != nil {
		t.Fatal(err)
	}
	if options.Profile != "" || options.profileValidated {
		t.Fatal("stale profile accepted")
	}
	for _, flag := range Flags(options) {
		if strings.HasPrefix(flag, "-fprofile") {
			t.Fatal("stale profile flag", flag)
		}
	}
}
