const debugShards = 24

// FNV ownership is stable as fixtures are added, as in oracle's review family.
// Graph-region witnesses are one small solo IR test, retaining the positive
// allocator guard without requiring a class allocator in every review shard.
func debugFamilyPaths(paths []string, shard int, graphSolo bool) []string {
	var owned []string
	for _, path := range paths {
		graph := graphSolo && strings.HasPrefix(filepath.Base(path), "graph_regions")
		if graph {
			if shard == -1 {
				owned = append(owned, path)
			}
			continue
		}
		if shard == -1 {
			continue
		}
		h := fnv.New64a()
		h.Write([]byte(filepath.ToSlash(path)))
		if int(h.Sum64()%debugShards) == shard {
			owned = append(owned, path)
		}
	}
	return owned
}

func TestDebugFamiliesCoverEveryProgramOnce(t *testing.T) {
	t.Parallel()
	for _, family := range []struct {
		paths     []string
		graphSolo bool
	}{{debugByteIdentityPaths(t), false}, {reviewPrograms(t), false}, {debugCorpus(t), true}} {
		paths, graphSolo := family.paths, family.graphSolo
		if len(paths) == 0 {
			t.Fatal("empty debug corpus")
		}
		seen := map[string]int{}
		for shard := -1; shard < debugShards; shard++ {
			for _, path := range debugFamilyPaths(paths, shard, graphSolo) {
				seen[path]++
			}
		}
		for _, path := range paths {
			if seen[path] != 1 {
				t.Fatalf("%s has %d owners", path, seen[path])
			}
		}
	}
}

var updateDebugFamilies = flag.Bool("update-debug-families", false, "regenerate debug family wrappers")

func debugFamilyWrappers() ([]byte, error) {
	var text bytes.Buffer
	fmt.Fprint(&text, "// Code generated by TestDebugFamilyWrappersAreCurrent; DO NOT EDIT.\n// go test ./internal/native -run '^TestDebugFamilyWrappersAreCurrent$' -args -update-debug-families\n\npackage native\n\nimport \"testing\"\n")
	for _, family := range []struct{ name, runner string }{
		{"TestDebugStrippedIR", "runDebugStrippedIR"},
		{"TestDebugByteIdentity", "runDebugByteIdentity"},
		{"TestDebugReviewOutputAndOwnership", "runDebugReviewOutputAndOwnership"},
	} {
		for shard := 0; shard < debugShards; shard++ {
			fmt.Fprintf(&text, "\nfunc %s_%03d(t *testing.T) { t.Parallel(); %s(t,%d) }\n", family.name, shard, family.runner, shard)
		}
	}
	fmt.Fprint(&text, "\nfunc TestDebugStrippedIRGraphRegions(t *testing.T) { t.Parallel(); runDebugStrippedIR(t,-1) }\n")
	for mode, name := range []string{"Release", "Debug", "Sanitized"} {
		for shard := 0; shard < debugShards; shard++ {
			fmt.Fprintf(&text, "\nfunc TestProduct_DebugReview%s_%03d(t *testing.T) { t.Parallel(); runDebugReviewProducts(t,%d,%d) }\n", name, shard, shard, mode)
		}
	}
	return format.Source(text.Bytes())
}

// Not parallel: the update flag writes generated source.
func TestDebugFamilyWrappersAreCurrent(t *testing.T) {
	want, err := debugFamilyWrappers()
	if err != nil {
		t.Fatal(err)
	}
	if *updateDebugFamilies {
		if err := os.WriteFile("source_lines_families_generated_test.go", want, 0644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile("source_lines_families_generated_test.go")
	if err != nil || !bytes.Equal(got, want) {
		t.Fatal("debug family wrappers stale; run with -update-debug-families", err)
	}
}
