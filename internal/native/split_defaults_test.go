// Not parallel: sets the source policy's process environment.
func TestSplitSourcePolicy(t *testing.T) {
	t.Setenv("ADAMIC_NATIVE_SPLIT", "")
	generated := "// Generated by adamic from fixture.a. Do not edit.\nint main(void){return 0;}\n"
	features := ""
	for _, feature := range runtimeFeatures {
		features += "#define " + feature + " 1\n"
	}
	for _, source := range []string{generated, features + generated, "#include \"tsgo_runtime.h\"\n" + features + generated} {
		if !useSplitSource(source, Options{Sanitize: true}) {
			t.Fatal("generated preamble stayed whole")
		}
	}
	for _, source := range []string{"#define main original_main\n" + generated, "#define UNKNOWN 1\n" + generated, "#include \"adamic.h\"\nint main(void){return 0;}"} {
		if useSplitSource(source, Options{Count: true}) {
			t.Fatal("handwritten harness entered automatic splitter")
		}
	}
	if !useSplitSource("int main(void){return 0;}", Options{Split: true}) {
		t.Fatal("explicit prototype request ignored")
	}
}

// Not parallel: changes ADAMIC_NATIVE_JOBS for the scheduling policy.
func TestSplitJobsPolicy(t *testing.T) {
	t.Setenv("ADAMIC_NATIVE_JOBS", "")
	if jobs, err := splitJobs(Options{}); err != nil || jobs != 1 {
		t.Fatalf("go-test default %d %v", jobs, err)
	}
	if got := defaultSplitJobs(false); got != max(1, goruntime.GOMAXPROCS(0)) {
		t.Fatalf("CLI default %d", got)
	}
	t.Setenv("ADAMIC_NATIVE_JOBS", "2")
	if jobs, err := splitJobs(Options{}); err != nil || jobs != 2 {
		t.Fatalf("environment %d %v", jobs, err)
	}
	t.Setenv("ADAMIC_NATIVE_JOBS", "invalid")
	if jobs, err := splitJobs(Options{Jobs: 3}); err != nil || jobs != 3 {
		t.Fatalf("explicit %d %v", jobs, err)
	}
	for _, value := range []string{"invalid", "-1"} {
		t.Setenv("ADAMIC_NATIVE_JOBS", value)
		if _, err := splitJobs(Options{}); err == nil {
			t.Fatalf("accepted %q", value)
		}
	}
	if _, err := splitJobs(Options{Jobs: -1}); err == nil {
		t.Fatal("accepted negative explicit jobs")
	}
}

// Not parallel: exercises default dispatch with a process environment override.
func TestSplitFrameTypedefPreservesState(t *testing.T) {
	t.Setenv("ADAMIC_NATIVE_SPLIT", "")
	source := `// Generated by adamic from split-frame.a. Do not edit.
#include "adamic.h"
#include <stdio.h>
typedef struct { int values[2]; int (*next)(void); } adamic_generated_frame;
static int state=0;
static int next(void){return ++state;}
static adamic_generated_frame frame={{0,0},next};
int main(void){frame.values[0]=frame.next();frame.values[1]=frame.next();printf("%d %d %d\n",frame.values[0],frame.values[1],state);return 0;}
`
	binary := filepath.Join(t.TempDir(), "frame")
	if err := Build(source, binary, Options{Sanitize: true}); err != nil {
		t.Fatal(err)
	}
	data, err := os.ReadFile(binary)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(data), "adamic_unit_next") {
		t.Fatal("default dispatch did not use split units")
	}
	truth := runWithInput(t, "", "node", "-e", "let state=0;const next=()=>++state;const a=next(),b=next();console.log(a,b,state)")
	if got := runWithInput(t, "", binary); got != truth {
		t.Fatalf("shared frame %q Node %q", got, truth)
	}
}

// Not parallel: resets process-wide compiler peak counters and jobserver environment.
func TestParallelRuntimeKeepsArchiveOrderAndState(t *testing.T) {
	t.Setenv(JobserverVariable, "")
	compiler, err := toolchain.Path("clang")
	if err != nil {
		t.Fatal(err)
	}
	version, err := compilerVersion(compiler)
	if err != nil {
		t.Fatal(err)
	}
	files := []runtimeFile{{"a.c", []byte("static int state; int next(void){return ++state;}\n")}, {"b.c", []byte("int next(void);int pair(void){int a=next(),b=next();return a*10+b;}\n")}}
	flags := Flags(Options{Sanitize: true})
	directory := t.TempDir()
	cache := filepath.Join(directory, "cache")
	clangPeak.Store(0)
	library, err := cachedRuntime(files, flags, compiler, string(version), cache, 3)
	if err != nil {
		t.Fatal(err)
	}
	if got := clangPeak.Load(); got != int64(min(2, cap(clangTokens))) {
		t.Fatalf("runtime worker request ignored: peak=%d", got)
	}
	if got := runWithInput(t, "", archiverName(compiler), "t", library); got != "a.o\nb.o\n" {
		t.Fatalf("archive order %q", got)
	}
	again, err := cachedRuntime(files, flags, compiler, string(version), cache, 1)
	if err != nil || again != library {
		t.Fatalf("scheduling changed key %s %v", again, err)
	}
	source := "#include <stdio.h>\nint pair(void);int main(void){int a=pair(),b=pair();printf(\"%d %d\\n\",a,b);return 0;}\n"
	if err := os.WriteFile(filepath.Join(directory, "main.c"), []byte(source), 0600); err != nil {
		t.Fatal(err)
	}
	binary := filepath.Join(directory, "pair")
	command := toolchain.CommandIn(directory, compiler, append(flags, "main.c", library, "-o", binary)...)
	if err := withCompilerToken(func() error {
		out, err := command.CombinedOutput()
		if err != nil {
			return fmt.Errorf("clang: %w\n%s", err, out)
		}
		return nil
	}); err != nil {
		t.Fatal(err)
	}
	truth := runWithInput(t, "", "node", "-e", "let state=0;const pair=()=>{const a=++state,b=++state;return a*10+b};console.log(pair(),pair())")
	if got := runWithInput(t, "", binary); got != truth {
		t.Fatalf("runtime state %q Node %q", got, truth)
	}
}
func TestExternalPrototypeStructure(t *testing.T) {
	t.Parallel()
	header, _, err := splitC("int unrelated_runtime_entry(int value);\nint main(void){return unrelated_runtime_entry(1);}\n")
	if err != nil || !strings.Contains(header, "int unrelated_runtime_entry(int value);") {
		t.Fatalf("external ABI lost: %v", err)
	}
	for _, source := range []string{"int unrelated_runtime_entry(int value){return value;}", "int unrelated_runtime_entry=1;", "int (*unrelated_runtime_pointer)(int);", "int (*unrelated_runtime_pointer)(int callback(int));", "inline static int unrelated_runtime_entry(int value);"} {
		if _, _, err := splitC(source); err == nil {
			t.Fatalf("accepted external storage or definition %s", source)
		}
	}
}
