// C is a program as one C translation unit, to be compiled with the runtime.
//
// Expressions are evaluated in JavaScript's order. Each one yields a C expression that stays valid
// to the end of its statement: a constant, a local nothing can change mid-statement, or a temporary.
// A global is copied before anything after it runs, since a call may change it. &&, || and ?: become
// real branches whenever their later operands have work to do, so what JavaScript doesn't evaluate,
// Adamic doesn't either.
//
// Every string reference is released exactly once. A string made mid-statement lives in a temporary
// released when the statement ends; a variable takes its own reference (retain) and gives it back
// when reassigned or when its scope ends, by break, continue or return included. Stage 0 pays a
// retain and a release on every assignment for that simplicity; removing them where they cancel is
// the memory model's work, measured against this.
func C(program *ir.Program) string {
	emitter := &emitter{program: program, reuse: planReuse(program)}
	var builder strings.Builder
	fmt.Fprintf(&builder, "// Generated by adamic from %s. Do not edit.\n\n#include \"adamic.h\"\n\n#include <math.h>\n#include <stdbool.h>\n\n", program.Source)
	for index, value := range program.Strings {
		if len(value) <= longestLiteral {
			fmt.Fprintf(&builder, "static adamic_string adamic_string_%d = ADAMIC_STRING(%s);\n", index, cString(value))
			continue
		}
		// Longer than a C string literal may be under -pedantic: its bytes as an array instead.
		fmt.Fprintf(&builder, "static const char adamic_bytes_%d[%d] = {%s};\n", index, len(value), cBytes(value))
		fmt.Fprintf(&builder, "static adamic_string adamic_string_%d = ADAMIC_STRING_BYTES(adamic_bytes_%d, %d);\n", index, index, len(value))
	}
	if len(program.Strings) > 0 {
		builder.WriteString("\n")
	}

	globals := false
	for index, local := range program.Locals {
		if !local.Global {
			continue
		}
		globals = true
		fmt.Fprintf(&builder, "static %s %s = %s;\n", cType(local.Type), emitter.localName(index), zero(local.Type))
		fmt.Fprintf(&builder, "static bool %s = false;\n", readyName(index))
	}
	if globals {
		builder.WriteString("\n")
	}

	// Bodies first: the shapes and field caches they use are found while they're emitted.
	bodies := strings.Builder{}
	for index, function := range program.Functions {
		fmt.Fprintf(&bodies, "static %s {\n", emitter.signature(index))
		emitter.indent = 1
		emitter.functionBody(function)
		bodies.WriteString(emitter.out.String())
		emitter.out.Reset()
		bodies.WriteString("}\n\n")
	}
	bodies.WriteString("int main(int argc, char **argv) {\n\tadamic_start(argc, argv);\n")
	emitter.indent = 1
	emitter.block(program.Main, nil)
	emitter.releaseGlobals()
	bodies.WriteString(emitter.out.String())
	bodies.WriteString("\treturn 0;\n}\n")

	for index := range program.Functions {
		fmt.Fprintf(&builder, "static %s;\n", emitter.signature(index))
	}
	if len(program.Functions) > 0 {
		builder.WriteString("\n")
	}
	// After the prototypes: a sort's comparator adapter calls one of the program's functions.
	for _, declaration := range emitter.declarations {
		builder.WriteString(declaration)
		builder.WriteString("\n")
	}
	if len(emitter.declarations) > 0 {
		builder.WriteString("\n")
	}
	builder.WriteString(bodies.String())
	return builder.String()
}

// fieldSlot is the adamic_value * of an object's field, for object a C name the statement holds. A
// field of a class (class is its constructor plus one) is where the class's layout puts it, the
// layout the constructor's object literal has, for an object of that shape: a compare and a load,
// inline. Any other object is looked up by name through the field cache, as is every other field:
// an object literal can be seen through a class's type, since tsc lets one through and only cohere's
// adamic/nominal-class refuses it, so the shape is checked, never assumed.
func (e *emitter) fieldSlot(object string, name string, class int) string {
	lookup := fmt.Sprintf("adamic_object_field(%s, %s, &%s)", object, cString(name), e.cache())
	if class == 0 || !cName.MatchString(object) {
		return lookup
	}
	body := e.program.Functions[class-1].Body
	if len(body) == 0 {
		return lookup
	}
	declare, isDeclare := body[0].(ir.Declare)
	if !isDeclare {
		return lookup
	}
	literal, isLiteral := declare.Value.(ir.ObjectLiteral)
	if !isLiteral || literal.Spread != nil {
		return lookup
	}
	for index, field := range literal.Fields {
		if field.Name == name {
			return fmt.Sprintf("(%s->shape == &%s ? &%s->slots[%d] : %s)", object, e.shape(literal.Fields), object, index, lookup)
		}
	}
	return lookup
}

// cName is a C name alone, which a C expression can repeat without evaluating anything twice.
var cName = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

// longestLiteral is the longest string literal C11 promises to compile (5.2.4.1: 4,095 characters),
// which clang holds a program to under -pedantic. A longer string is written as bytes (cBytes).
const longestLiteral = 4095

// cBytes is a string's bytes as an array initializer, as many as it has, with no terminator.
func cBytes(value string) string {
	var builder strings.Builder
	for index := 0; index < len(value); index++ {
		if index > 0 {
			builder.WriteString(",")
			if index%32 == 0 {
				builder.WriteString("\n\t")
			}
		}
		fmt.Fprintf(&builder, "%d", value[index])
	}
	return builder.String()
}

type emitter struct {
	program *ir.Program
	out     strings.Builder
	indent  int

	// reuse is where objects are reused in place (reuse.go), at names the statement being emitted,
	// where it stands in its slice, and taking is the spread whose replaced fields are being
	// evaluated, if any.
	reuse  *reusePlan
	at     *ir.Statement
	taking *taking

	// depth is how deep value is in the expression being emitted, lendAt the depth whose reads a
	// consumer lends without a count, lendable whether the expression being evaluated is one of
	// them, self whether its own value was lent, and lent whether one of the current expression's
	// operands was (borrow.go).
	depth    int
	lendAt   int
	lendable bool
	self     bool
	lent     bool

	// temporaries counts the C temporaries made so far, for unique names.
	temporaries int

	// owned is the string temporaries the statement being emitted releases when it ends.
	owned []string

	// scopes holds, innermost last, the references (C names) each open scope releases when it ends.
	scopes [][]string

	// loops holds, innermost last, each open loop's scope depth and continue label, and whether
	// anything jumps to that label.
	loops []*loop

	// breakables holds, innermost last, the scope depth of each open loop or switch: what a break
	// leaves.
	breakables []int

	// declarations are file-scope lines the bodies need: object shapes and field caches.
	declarations []string

	// shapes names each object layout already declared, by its fields.
	shapes map[string]string

	// initialized is every global main declares, in the order their declarations run: modules in
	// ECMAScript's order, and each module's from the top.
	initialized []int

	// handlers are the tries open in the function being emitted, innermost last, and outerOwned what
	// the statement owned outside each aside being emitted (exceptions.go).
	handlers   []*handler
	outerOwned [][]string

	// function is the function being emitted, and functionDepth the scope depth its body starts at.
	function      *ir.Function
	functionDepth int
}

type loop struct {
	depth     int
	label     string
	continued bool
}

func (e *emitter) line(format string, arguments ...any) {
	e.out.WriteString(strings.Repeat("\t", e.indent))
	fmt.Fprintf(&e.out, format, arguments...)
	e.out.WriteString("\n")
}

func (e *emitter) temporary() string {
	e.temporaries++
	return fmt.Sprintf("adamic_temporary_%d", e.temporaries)
}

// localName is a local's C name: its index, which is unique, and its name as written, for reading.
func (e *emitter) localName(local int) string {
	prefix := "adamic_local"
	if e.program.Locals[local].Global {
		prefix = "adamic_global"
	}
	return fmt.Sprintf("%s_%d_%s", prefix, local, cIdentifier.ReplaceAllString(e.program.Locals[local].Name, ""))
}

// readyName is the flag that says a global's declaration has run.
func readyName(local int) string {
	return fmt.Sprintf("adamic_ready_%d", local)
}

var cIdentifier = regexp.MustCompile(`[^A-Za-z0-9_]`)

func (e *emitter) functionName(function int) string {
	return fmt.Sprintf("adamic_function_%d_%s", function, cIdentifier.ReplaceAllString(e.program.Functions[function].Name, ""))
}

func (e *emitter) signature(function int) string {
	declared := e.program.Functions[function]
	if declared.Closure {
		// Every closure's code is called the same way (adamic_code): its arguments and result as
		// adamic_value, whatever their types.
		return fmt.Sprintf("adamic_value %s(adamic_closure *self, adamic_value *arguments)", e.functionName(function))
	}
	returns := "void"
	if declared.Returns != 0 {
		returns = cType(declared.Returns)
	}
	parameters := []string{}
	for _, parameter := range declared.Parameters {
		parameters = append(parameters, cType(e.program.Locals[parameter].Type)+" "+e.localName(parameter))
	}
	if len(parameters) == 0 {
		parameters = append(parameters, "void")
	}
	return fmt.Sprintf("%s %s(%s)", returns, e.functionName(function), strings.Join(parameters, ", "))
}

// functionBody emits a function's body. A string parameter is retained on entry and released on
// every way out, like any local, so a function may reassign it without touching its caller's.
func (e *emitter) functionBody(function ir.Function) {
	e.function = &function
	e.functionDepth = len(e.scopes)
	e.scopes = append(e.scopes, nil)
	// Recursion that runs out of stack panics, as Node's does, rather than crashing (stack.c).
	e.line("ADAMIC_CHECK_STACK();")
	if function.Closure {
		e.line("(void)self;")
		e.line("(void)arguments;")
		for index, parameter := range function.Parameters {
			local := e.program.Locals[parameter]
			value := unslotted(local.Type, fmt.Sprintf("arguments[%d].%s", index, member(local.Type)))
			if local.Type.IsReference() {
				value = fmt.Sprintf("(%s)%s", cType(local.Type), value)
			}
			e.line("%s %s = %s;", cType(local.Type), e.localName(parameter), value)
		}
	}
	for _, parameter := range function.Parameters {
		switch {
		case e.reuse.consumed[parameter]:
			// Its caller handed over a reference (reuse.go): it's the callee's to let go of.
			e.hold(e.localName(parameter))
		case e.program.Locals[parameter].Type.IsReference() && !e.program.Locals[parameter].Borrowed:
			// A borrowed parameter is its caller's, kept alive for the whole call.
			e.line("adamic_retain(%s);", e.localName(parameter))
			e.hold(e.localName(parameter))
		}
		if e.program.Locals[parameter].Captured {
			// A closure captured this parameter: from here on it lives in a cell.
			e.makeCell(parameter, e.localName(parameter), false)
		}
	}
	for index := range function.Body {
		e.statementAt(&function.Body[index])
	}
	if function.Returns == 0 {
		e.releaseScopes(e.functionDepth)
		if function.Closure {
			e.line("return (adamic_value){.number = 0};")
		}
	} else {
		// The checker proved every path returns (noImplicitReturns), so this is never reached; C
		// can't see that, and if it ever is reached it's a compiler bug, said out loud.
		e.line("adamic_unreachable();")
	}
	e.scopes = e.scopes[:e.functionDepth]
	e.function = nil
}

// block emits statements in a scope of their own.
func (e *emitter) block(statements []ir.Statement, after func()) {
	e.scopes = append(e.scopes, nil)
	for index := range statements {
		e.statementAt(&statements[index])
	}
	if after != nil {
		after()
	}
	e.releaseScopes(len(e.scopes) - 1)
	e.scopes = e.scopes[:len(e.scopes)-1]
}

// releaseScopes releases the string locals of every scope from depth inward.
func (e *emitter) releaseScopes(depth int) {
	for scope := len(e.scopes) - 1; scope >= depth; scope-- {
		for index := len(e.scopes[scope]) - 1; index >= 0; index-- {
			e.line("adamic_release(%s);", e.scopes[scope][index])
		}
	}
}

// hold makes the innermost scope release a reference when it ends.
func (e *emitter) hold(name string) {
	e.scopes[len(e.scopes)-1] = append(e.scopes[len(e.scopes)-1], name)
}

// end releases what the statement just emitted owned.
func (e *emitter) end() {
	for index := len(e.owned) - 1; index >= 0; index-- {
		e.line("adamic_release(%s);", e.owned[index])
	}
	e.owned = nil
}

// decide evaluates a condition and releases its temporaries before anything branches on it,
// returning the C expression holding the answer.
func (e *emitter) decide(condition ir.Expression) string {
	value := e.value(condition)
	if len(e.owned) == 0 {
		return value
	}
	name := e.temporary()
	e.line("bool %s = %s;", name, value)
	e.end()
	return name
}

// statementAt emits a statement where it stands in its slice, the address the reuse plan names it by.
func (e *emitter) statementAt(at *ir.Statement) {
	outer := e.at
	e.at = at
	e.statement(*at)
	e.at = outer
}

func (e *emitter) statement(statement ir.Statement) {
	switch statement := statement.(type) {
	case ir.WriteLine:
		stream := "adamic_stdout"
		if statement.Stream == ir.Stderr {
			stream = "adamic_stderr"
		}
		value := e.value(statement.Value)
		e.line("adamic_write_line(%s, %s);", stream, value)
		e.end()
	case ir.Declare:
		local := e.program.Locals[statement.Local]
		value := zero(local.Type)
		if statement.Value != nil {
			value = e.value(statement.Value)
		}
		if local.Global {
			e.store(statement.Local, value)
			e.line("%s = true;", readyName(statement.Local))
			e.initialized = append(e.initialized, statement.Local)
		} else {
			e.declareLocal(statement.Local, value, false)
		}
		e.end()
	case ir.Assign:
		if e.program.Locals[statement.Local].Counter {
			// The loop's update, counter + 1, is the only write a counter has (lower/counters.go).
			sum, isSum := statement.Value.(ir.Binary)
			if one, isOne := sum.Right.(ir.NumberConstant); !isSum || sum.Operator != ir.Add || !isOne || one.Value != 1 {
				panic(fmt.Sprintf("native: compiler bug: counter %s written other than by + 1", e.program.Locals[statement.Local].Name))
			}
			e.line("%s += 1;", e.localName(statement.Local))
			return
		}
		value := e.value(statement.Value)
		if statement.Checked {
			// After the value, as JavaScript does: the right side runs, then the write throws.
			e.checkReady(statement.Local)
		}
		e.store(statement.Local, value)
		e.end()
	case ir.Evaluate:
		if splice, isSplice := statement.Value.(ir.ArraySplice); isSplice {
			// What a splice removes, nothing here uses: it's let go of, and no array is made for it.
			e.line("adamic_array_remove(%s);", e.spliceArguments(splice))
			e.end()
			break
		}
		if call, isCall := statement.Value.(ir.Call); isCall && call.Returns == 0 {
			e.line("%s(%s);", e.functionName(call.Function), strings.Join(e.arguments(call), ", "))
			if e.program.Functions[call.Function].MayThrow {
				e.checkThrown()
			}
		} else {
			// The value goes, but whatever making it did stays: a push's append is its effect.
			e.line("(void)%s;", e.value(statement.Value))
		}
		e.end()
	case ir.Return:
		e.returnStatement(statement)
	case ir.SetIndex:
		array := e.value(statement.Array)
		index := e.value(statement.Index)
		value := e.value(statement.Value)
		if statement.Element.IsReference() {
			value = "adamic_retain(" + value + ")"
		}
		e.line("adamic_array_set(%s, %s, (adamic_value){.%s = %s});", array, index, member(statement.Element), slotted(statement.Element, value))
		e.end()
	case ir.SetProperty:
		object := e.value(statement.Object)
		value := e.value(statement.Value)
		// The object may be undefined where the checker narrowed it away and a call since put it back
		// (ir.Defined): JavaScript throws at the write, after the value, and so does this.
		e.line("if (%s == NULL) {", object)
		e.line("\tstatic const char message[] = %s;", cString("TypeError: Cannot set properties of undefined (setting '"+statement.Name+"')"))
		e.line("\tadamic_panic(message, sizeof message - 1);")
		e.line("}")
		slot := e.temporary()
		e.line("adamic_value *%s = %s;", slot, e.fieldSlot(object, statement.Name, statement.Class))
		if statement.Value.Type().IsReference() {
			// The new reference is taken before the old is let go: they may be the same.
			old := e.temporary()
			e.line("void *%s = %s->reference;", old, slot)
			e.line("%s->reference = adamic_retain(%s);", slot, value)
			e.line("adamic_release(%s);", old)
		} else {
			e.line("%s->%s = %s;", slot, member(statement.Value.Type()), slotted(statement.Value.Type(), value))
		}
		e.end()
	case ir.Panic:
		// The program ends here, so nothing it holds needs letting go.
		message := e.value(statement.Message)
		e.line("adamic_panic((%s)->bytes, (%s)->length);", message, message)
		e.owned = nil
	case ir.If:
		condition := e.decide(statement.Condition)
		e.line("if (%s) {", unwrap(condition))
		e.nested(statement.Then, nil)
		if len(statement.Else) > 0 {
			e.line("} else {")
			e.nested(statement.Else, nil)
		}
		e.line("}")
	case ir.Block:
		e.line("{")
		e.nested(statement.Body, nil)
		e.line("}")
	case ir.Loop:
		e.loop(statement)
	case ir.ForOf:
		e.forOf(statement)
	case ir.Switch:
		e.switchStatement(statement)
	case ir.Break:
		// A try inside the loop or switch is left: its finally runs first.
		e.finallies(e.innerHandlers(e.breakables[len(e.breakables)-1]))
		e.releaseScopes(e.breakables[len(e.breakables)-1])
		e.line("break;")
	case ir.Continue:
		current := e.loops[len(e.loops)-1]
		current.continued = true
		e.finallies(e.innerHandlers(current.depth))
		e.releaseScopes(current.depth)
		e.line("goto %s;", current.label)
	case ir.Throw:
		e.throwStatement(statement)
	case ir.Try:
		e.tryStatement(statement)
	default:
		// Lowering only produces statements this switch knows. Reaching this is a compiler bug.
		panic(fmt.Sprintf("native: no C for %T", statement))
	}
}

// store gives a local a value; a string's new reference is taken before the old one is let go,
// since they may be the same string.
func (e *emitter) store(local int, value string) {
	if e.program.Locals[local].Borrowed {
		// Storing would release the old value, which is the caller's. Lowering never borrows a
		// parameter anything assigns, so reaching this is a compiler bug, said out loud.
		panic(fmt.Sprintf("native: a store into the borrowed parameter %s", e.program.Locals[local].Name))
	}
	name := e.localName(local)
	if slot := e.cellSlot(local); slot != "" {
		if !e.program.Locals[local].Type.IsReference() {
			e.line("%s.%s = %s;", slot, member(e.program.Locals[local].Type), slotted(e.program.Locals[local].Type, value))
			return
		}
		old := e.temporary()
		e.line("void *%s = %s.reference;", old, slot)
		e.line("%s.reference = adamic_retain(%s);", slot, value)
		e.line("adamic_release(%s);", old)
		return
	}
	if !e.program.Locals[local].Type.IsReference() {
		e.line("%s = %s;", name, value)
		return
	}
	old := e.temporary()
	e.line("%s %s = %s;", cType(e.program.Locals[local].Type), old, name)
	e.line("%s = adamic_retain(%s);", name, value)
	e.line("adamic_release(%s);", old)
}

// releaseGlobals lets go of every global main declared, the last declared first, once main has run
// to its end. Nothing reads them after that, and a program that let go of everything is one the leak
// check can hold to account: a reference still held at exit, or still written in a global, hides
// whatever it reaches. A panic exits
// where it stands, as Node does, and never gets here.
func (e *emitter) releaseGlobals() {
	for index := len(e.initialized) - 1; index >= 0; index-- {
		if e.program.Locals[e.initialized[index]].Type.IsReference() {
			// And forgotten: the leak check counts what a global points at as alive, so a count the
			// global's own object never gave back, or a cycle the global led into, would hide.
			e.line("adamic_release(%s);", e.localName(e.initialized[index]))
			e.line("%s = NULL;", e.localName(e.initialized[index]))
		}
	}
}

// checkReady panics as JavaScript throws when a global is touched before its declaration has run.
func (e *emitter) checkReady(local int) {
	message := fmt.Sprintf("ReferenceError: Cannot access '%s' before initialization", e.program.Locals[local].Name)
	e.line("if (!%s) {", readyName(local))
	e.line("\tstatic const char message[] = %s;", cString(message))
	e.line("\tadamic_panic(message, sizeof message - 1);")
	e.line("}")
}

func (e *emitter) returnStatement(statement ir.Return) {
	if statement.Value == nil {
		e.end()
		e.finallies(0)
		e.releaseScopes(e.functionDepth)
		if e.function != nil && e.function.Closure {
			e.line("return (adamic_value){.number = 0};")
		} else {
			e.line("return;")
		}
		return
	}
	value := e.value(statement.Value)
	result := e.temporary()
	if statement.Value.Type().IsReference() {
		e.line("%s %s = adamic_retain(%s);", cType(statement.Value.Type()), result, value)
	} else {
		e.line("%s %s = %s;", cType(statement.Value.Type()), result, value)
	}
	e.end()
	if len(e.handlers) > 0 {
		// Every finally open runs before the function returns. The result waits in a scope of its
		// own, so a throw from a finally, which replaces the return, lets go of it.
		held := []string{}
		if statement.Value.Type().IsReference() {
			held = append(held, result)
		}
		e.scopes = append(e.scopes, held)
		e.finallies(0)
		e.scopes = e.scopes[:len(e.scopes)-1]
	}
	e.releaseScopes(e.functionDepth)
	if e.function != nil && e.function.Closure {
		e.line("return (adamic_value){.%s = %s};", member(statement.Value.Type()), slotted(statement.Value.Type(), result))
	} else {
		e.line("return %s;", result)
	}
}

// nested emits statements one level in, in a scope of their own.
func (e *emitter) nested(statements []ir.Statement, after func()) {
	e.indent++
	e.block(statements, after)
	e.indent--
}

// loop emits every loop the same way: for (;;), the condition checked as an if that breaks, the
// body in its own scope, then a continue label and the update. A continue releases the body's
// locals and jumps to the label, so it runs the update and the check, as JavaScript's does.
func (e *emitter) loop(statement ir.Loop) {
	e.temporaries++
	current := &loop{label: fmt.Sprintf("adamic_continue_%d", e.temporaries)}
	check := func() {
		condition := e.decide(statement.Condition)
		e.line("if (!(%s)) {", unwrap(condition))
		e.line("\tbreak;")
		e.line("}")
	}
	e.line("for (;;) {")
	e.indent++
	if !statement.CheckAfter {
		check()
	}
	// The body is emitted aside first, since only then is it known whether anything continues.
	saved := e.out
	e.out = strings.Builder{}
	current.depth = len(e.scopes)
	e.loops = append(e.loops, current)
	e.breakables = append(e.breakables, current.depth)
	e.line("{")
	e.nested(statement.Body, nil)
	e.line("}")
	e.breakables = e.breakables[:len(e.breakables)-1]
	e.loops = e.loops[:len(e.loops)-1]
	body := e.out.String()
	e.out = saved
	e.out.WriteString(body)
	if current.continued {
		e.line("%s:;", current.label)
	}
	// Each iteration's let bindings are its own (ECMA-262, CreatePerIterationEnvironment): a captured
	// one gets a fresh cell holding the current value before the update runs, so a closure made in
	// this iteration keeps this iteration's.
	for _, local := range statement.PerIteration {
		if !e.program.Locals[local].Captured {
			continue
		}
		cell := e.cellName(local)
		fresh := e.temporary()
		e.line("adamic_cell *%s = adamic_cell_new(%s->value, %s->references);", fresh, cell, cell)
		e.line("if (%s->references) {", fresh)
		e.line("\tadamic_retain(%s->value.reference);", fresh)
		e.line("}")
		e.line("adamic_release(%s);", cell)
		e.line("%s = %s;", cell, fresh)
	}
	for index := range statement.Update {
		e.statementAt(&statement.Update[index])
	}
	if statement.CheckAfter {
		check()
	}
	e.indent--
	e.line("}")
}

// value emits what an expression needs evaluated first, in JavaScript's order, and returns a C
// expression that stays valid to the end of the statement.
func (e *emitter) evaluate(expression ir.Expression) string {
	switch expression := expression.(type) {
	case ir.NumberConstant:
		return cNumber(expression.Value)
	case ir.BooleanConstant:
		return strconv.FormatBool(expression.Value)
	case ir.StringConstant:
		return fmt.Sprintf("&adamic_string_%d", expression.Index)
	case ir.Read:
		return e.read(expression)
	case ir.Unary:
		operand := e.value(expression.Operand)
		switch expression.Operator {
		case ir.Negate:
			return "(-" + operand + ")"
		case ir.Plus:
			return "(+" + operand + ")"
		case ir.Not:
			return "(!" + operand + ")"
		}
	case ir.Binary:
		if expression.Operator == ir.And || expression.Operator == ir.Or {
			return e.logical(expression)
		}
		return e.binary(expression.Operator, expression.Left.Type(), e.value(expression.Left), e.value(expression.Right))
	case ir.Call:
		arguments := e.arguments(expression)
		call := fmt.Sprintf("%s(%s)", e.functionName(expression.Function), strings.Join(arguments, ", "))
		var result string
		if expression.Returns.IsReference() {
			result = e.own(expression.Returns, call)
		} else {
			result = e.temporary()
			e.line("%s %s = %s;", cType(expression.Returns), result, call)
		}
		if e.program.Functions[expression.Function].MayThrow {
			// A throw left the call: the result is the zero value it returned, owned like any.
			e.checkThrown()
		}
		return result
	case ir.NumberToString:
		return e.own(ir.String, fmt.Sprintf("adamic_string_from_number(%s)", e.value(expression.Value)))
	case ir.BooleanToString:
		return fmt.Sprintf("((%s) ? &adamic_string_true : &adamic_string_false)", e.value(expression.Value))
	case ir.Concat:
		parts := make([]string, 0, len(expression.Parts))
		for _, part := range expression.Parts {
			parts = append(parts, e.value(part))
		}
		return e.own(ir.String, fmt.Sprintf("adamic_string_concat(%d, (adamic_string *const[]){%s})", len(parts), strings.Join(parts, ", ")))
	case ir.Conditional:
		return e.conditional(expression)
	case ir.ObjectLiteral:
		return e.objectLiteral(expression)
	case ir.Property:
		if taken, ok := e.take(expression); ok {
			return taken
		}
		lent := e.lendable && lendable(expression.Of) && !expression.Optional
		object := e.value(expression.Object)
		field := unslotted(expression.Of, fmt.Sprintf("%s->%s", e.fieldSlot(object, expression.Name, expression.Class), member(expression.Of)))
		if expression.Of == ir.MaybeNumber && expression.Optional {
			return e.snapshot(ir.MaybeNumber, fmt.Sprintf("(%s == NULL ? %s : %s)", object, zero(ir.MaybeNumber), field))
		}
		if expression.Of.IsReference() {
			// A field holds a reference as void *; read through the type the checker proved.
			field = fmt.Sprintf("((%s)%s)", cType(expression.Of), field)
		}
		if expression.Optional && expression.Type().IsMaybe() {
			return e.snapshot(expression.Type(), fmt.Sprintf("(%s == NULL ? %s : %s)", object, zero(expression.Type()), maybe(expression.Type(), field)))
		}
		if expression.Optional {
			field = fmt.Sprintf("(%s == NULL ? NULL : %s)", object, field)
		}
		// Read now, when JavaScript reads it: a call later in the statement may write the field. A
		// reference is retained, so that write can't free it from under its reader, unless nothing
		// can run before it's used (borrow.go).
		if lent {
			e.self = true
			return e.snapshot(expression.Of, field)
		}
		if expression.Of.IsReference() {
			return e.own(expression.Of, fmt.Sprintf("adamic_retain(%s)", field))
		}
		return e.snapshot(expression.Of, field)
	case ir.Undefined:
		return "NULL"
	case ir.IsUndefined:
		if expression.Value.Type().IsMaybe() {
			return fmt.Sprintf("(!(%s).present)", e.value(expression.Value))
		}
		return fmt.Sprintf("(%s == NULL)", e.value(expression.Value))
	case ir.Unwrap:
		// The checker narrowed undefined away, but a call since may have put it back (ir.Unwrap).
		value := e.snapshot(expression.Value.Type(), e.value(expression.Value))
		e.line("if (!%s.present) {", value)
		e.line("\tstatic const char message[] = %s;", cString(narrowedAwayMessage))
		e.line("\tadamic_panic(message, sizeof message - 1);")
		e.line("}")
		return fmt.Sprintf("(%s).%s", value, member(expression.Type()))
	case ir.Defined:
		value := e.value(expression.Value)
		e.checkDefined(value, expression.Message)
		return value
	case ir.MaybeOf:
		if expression.Value == nil {
			return zero(expression.Of)
		}
		return maybe(expression.Of, e.value(expression.Value))
	case ir.MaybeToString:
		return e.maybeToString(expression.Value)
	case ir.Box:
		return e.box(expression.Value)
	case ir.MakeError:
		return e.own(ir.Object, fmt.Sprintf("adamic_error_new(%s)", e.value(expression.Message)))
	case ir.WeakOf:
		return e.own(ir.Weak, fmt.Sprintf("adamic_weak_of(%s)", e.value(expression.Value)))
	case ir.WeakTarget:
		target := "adamic_weak_target"
		if expression.Present {
			target = "adamic_weak_target_present"
		}
		// Retained, as any reference read out of a slot is: a call later in the statement may let go
		// of the last strong holder.
		return e.own(expression.To, fmt.Sprintf("(%s)adamic_retain(%s(%s))", cType(expression.To), target, e.value(expression.Value)))
	case ir.Narrow:
		return e.narrow(expression)
	case ir.TypeOf:
		return e.typeOf(expression.Value)
	case ir.UnionToString:
		return e.own(ir.String, fmt.Sprintf("adamic_union_to_string(%s)", e.value(expression.Value)))
	case ir.Coalesce:
		return e.coalesce(expression)
	case ir.StringLength:
		return fmt.Sprintf("adamic_string_length(%s)", e.value(expression.Value))
	case ir.CharCodeAt:
		value := e.value(expression.Value)
		index := e.value(expression.Index)
		return fmt.Sprintf("adamic_string_char_code_at(%s, %s)", value, index)
	case ir.MakeClosure:
		environment := e.program.Functions[expression.Function].Environment
		closure := e.own(ir.Closure, fmt.Sprintf("adamic_closure_new(%s, %d)", e.functionName(expression.Function), len(environment)))
		for index, local := range environment {
			e.line("%s->cells[%d] = adamic_retain(%s);", closure, index, e.cellReference(local))
		}
		return closure
	case ir.CallClosure:
		closure := e.value(expression.Closure)
		arguments := []string{}
		for _, argument := range expression.Arguments {
			arguments = append(arguments, fmt.Sprintf("{.%s = %s}", member(argument.Type()), slotted(argument.Type(), e.value(argument))))
		}
		packed := "NULL"
		if len(arguments) > 0 {
			packed = "(adamic_value[]){" + strings.Join(arguments, ", ") + "}"
		}
		call := fmt.Sprintf("%s->code(%s, %s)", closure, closure, packed)
		if expression.Returns == 0 {
			e.line("%s;", call)
			e.closureThrown()
			return "0"
		}
		result := e.temporary()
		e.line("adamic_value %s = %s;", result, call)
		// A throw gives back a zero value, nothing to let go.
		e.closureThrown()
		if expression.Returns.IsReference() {
			// A closure's result comes back owned.
			return e.own(expression.Returns, fmt.Sprintf("(%s)%s.reference", cType(expression.Returns), result))
		}
		return e.snapshot(expression.Returns, unslotted(expression.Returns, result+"."+member(expression.Returns)))
	case ir.ArrayMap:
		if mapped, ok := e.mapped(expression); ok {
			return mapped
		}
		source := e.temporary()
		e.line("adamic_array *%s = %s;", source, e.value(expression.Array))
		callback := e.value(expression.Callback)
		mapped := e.own(ir.Array, fmt.Sprintf("adamic_array_new(%s->length, %t)", source, expression.Result.IsReference()))
		count, index := e.temporary(), e.temporary()
		// The length is read once, as JavaScript's map does; an array the callback shrinks is a
		// panic here rather than JavaScript's holes, which 0.1 has no way to hold.
		e.line("size_t %s = %s->length;", count, source)
		e.line("for (size_t %s = 0; %s < %s; %s++) {", index, index, count, index)
		e.line("\tif (%s >= %s->length) {", index, source)
		e.line("\t\tstatic const char message[] = \"map: the array shrank while it was being mapped\";")
		e.line("\t\tadamic_panic(message, sizeof message - 1);")
		e.line("\t}")
		e.indent++
		element := e.temporary()
		e.line("adamic_value %s = %s->code(%s, (adamic_value[]){%s->elements[%s], {.number = (double)%s}, {.reference = %s}});", element, callback, callback, source, index, index, source)
		// What's mapped so far is the statement's, let go with its temporaries.
		e.closureThrown()
		e.line("adamic_array_push(%s, %s);", mapped, element)
		e.indent--
		e.line("}")
		return mapped
	case ir.ArrayVisit:
		return e.arrayVisit(expression)
	case ir.ArrayReduce:
		return e.arrayReduce(expression)
	case ir.ArraySearch:
		array := e.value(expression.Array)
		value := e.value(expression.Value)
		found := fmt.Sprintf("adamic_array_index_of(%s, %s, %s, %t)", array, borrowed(expression.Element, value), equality(expression.Element), expression.Includes)
		if expression.Includes {
			return e.snapshot(ir.Boolean, found+" != -1")
		}
		return e.snapshot(ir.Number, found)
	case ir.ArrayFill:
		if expression.Array == nil {
			length := e.value(expression.Length)
			value := e.value(expression.Value)
			return e.own(ir.Array, fmt.Sprintf("adamic_array_filled(%s, %s, %t)", length, borrowed(expression.Element, value), expression.Element.IsReference()))
		}
		array := e.value(expression.Array)
		value := e.value(expression.Value)
		start, end := "0.0", "0.0"
		if expression.Start != nil {
			start = e.value(expression.Start)
		}
		if expression.End != nil {
			end = e.value(expression.End)
		}
		e.line("adamic_array_fill(%s, %s, %s, %s, %t, %t);", array, borrowed(expression.Element, value), start, end, expression.Start != nil, expression.End != nil)
		return array
	case ir.ArraySplice:
		return e.own(ir.Array, fmt.Sprintf("adamic_array_splice(%s)", e.spliceArguments(expression)))
	case ir.ArrayFrom:
		return e.arrayFrom(expression)
	case ir.ArrayReverse:
		array := e.value(expression.Array)
		e.line("adamic_array_reverse(%s);", array)
		return array
	case ir.ArrayConcat:
		arrays := []string{e.value(expression.Array)}
		for _, other := range expression.Others {
			arrays = append(arrays, e.value(other))
		}
		return e.own(ir.Array, fmt.Sprintf("adamic_array_concat(%d, (adamic_array *const[]){%s})", len(arrays), strings.Join(arrays, ", ")))
	case ir.CheckedCast:
		object := e.temporary()
		e.line("adamic_object *%s = %s;", object, e.value(expression.Value))
		field := fmt.Sprintf("adamic_object_field(%s, %s, &%s)->%s", object, cString(expression.Field), e.cache(), member(expression.FieldType))
		if expression.FieldType.IsReference() {
			field = fmt.Sprintf("((%s)%s)", cType(expression.FieldType), field)
		}
		tests := []string{}
		for _, allowed := range expression.Allowed {
			tests = append(tests, e.binary(ir.Equal, expression.FieldType, field, e.value(allowed)))
		}
		e.line("if (!(%s)) {", strings.Join(tests, " || "))
		e.line("\tstatic const char message[] = %s;", cString(expression.Message))
		e.line("\tadamic_panic(message, sizeof message - 1);")
		e.line("}")
		return object
	case ir.ArrayIndex:
		array := e.value(expression.Array)
		index := e.value(expression.Index)
		slot := e.temporary()
		lookup := "adamic_array_at"
		if expression.Relative {
			lookup = "adamic_array_at_relative"
		} else if read, isRead := expression.Index.(ir.Read); isRead && e.program.Locals[read.Local].Counter {
			// A counter is a whole number already: only the bounds are left to check.
			lookup, index = "adamic_array_at_integer", e.localName(read.Local)
		}
		e.line("adamic_value *%s = %s(%s, %s);", slot, lookup, array, index)
		if expression.Type().IsMaybe() {
			return e.snapshot(expression.Type(), maybeSlot(expression.Element, slot))
		}
		// Retained, so a write later in the statement can't free it from under its reader.
		return e.own(expression.Element, fmt.Sprintf("%s == NULL ? NULL : (%s)adamic_retain(%s->reference)", slot, cType(expression.Element), slot))
	case ir.ArrayPop:
		array := e.temporary()
		e.line("adamic_array *%s = %s;", array, e.value(expression.Array))
		if expression.Type().IsMaybe() {
			popped := fmt.Sprintf("%s->elements[--%s->length].%s", array, array, member(expression.Element))
			if expression.Element == ir.MaybeNumber {
				popped = unslotted(ir.MaybeNumber, popped)
			} else {
				popped = maybe(expression.Type(), popped)
			}
			return e.snapshot(expression.Type(), fmt.Sprintf("%s->length == 0 ? %s : %s", array, zero(expression.Type()), popped))
		}
		// The array's reference to the element becomes the statement's.
		return e.own(expression.Element, fmt.Sprintf("%s->length == 0 ? NULL : %s->elements[--%s->length].%s", array, array, array, member(expression.Element)))
	case ir.MapEntries:
		pair := e.shapeOf([]string{"0", "1"}, []ir.Type{expression.KeyType, expression.ValueType})
		return e.own(ir.Array, fmt.Sprintf("adamic_map_entries(%s, &%s)", e.value(expression.Map), pair))
	case ir.ArraySlice:
		array := e.value(expression.Array)
		arguments := []string{"0.0", "0.0"}
		for index, argument := range expression.Arguments {
			arguments[index] = e.value(argument)
		}
		return e.own(ir.Array, fmt.Sprintf("adamic_array_slice(%s, %s, %s, %t)", array, arguments[0], arguments[1], len(expression.Arguments) == 2))
	case ir.ArraySort:
		array := e.value(expression.Array)
		sort := "adamic_array_sort"
		if expression.Element == ir.MaybeNumber {
			sort = "adamic_array_sort_undefined_last"
		}
		// A comparator that throws stops the sort, which leaves the array as it was, as V8's does
		// (sort.c), and the throw goes on from here.
		if expression.Callback != nil {
			e.line("%s(%s, adamic_compare_closure, %s);", sort, array, e.value(expression.Callback))
			e.closureThrown()
			return array
		}
		e.line("%s(%s, %s, NULL);", sort, array, e.comparator(expression))
		if e.program.Functions[expression.Comparator].MayThrow {
			e.checkThrown()
		}
		return array
	case ir.CodePoints:
		return e.own(ir.Array, fmt.Sprintf("adamic_string_code_points(%s)", e.value(expression.Value)))
	case ir.StringIndex:
		value := e.value(expression.Value)
		index := e.value(expression.Index)
		return e.own(ir.String, fmt.Sprintf("adamic_string_at(%s, %s)", value, index))
	case ir.StringCall:
		return e.stringCall(expression)
	case ir.Trim:
		return e.own(ir.String, fmt.Sprintf("adamic_string_trim(%s)", e.value(expression.Value)))
	case ir.MapNew:
		entries := make([][2]string, 0, len(expression.Entries))
		for _, entry := range expression.Entries {
			entries = append(entries, [2]string{e.value(entry[0]), e.value(entry[1])})
		}
		var pairs string
		if expression.Pairs != nil {
			pairs = e.value(expression.Pairs)
		}
		created := e.own(ir.Map, newMap(expression.Key, expression.Value.IsReference()))
		for _, entry := range entries {
			e.line("adamic_map_set(%s, %s, %s);", created, held(expression.Key, entry[0]), held(expression.Value, entry[1]))
		}
		if expression.Pairs != nil {
			e.line("adamic_map_add_pairs(%s, %s);", created, pairs)
		}
		return created
	case ir.MapKeys:
		return e.own(ir.Array, fmt.Sprintf("adamic_map_keys(%s)", e.value(expression.Map)))
	case ir.MapValues:
		return e.own(ir.Array, fmt.Sprintf("adamic_map_values(%s)", e.value(expression.Map)))
	case ir.MapClear:
		e.line("adamic_map_clear(%s);", e.value(expression.Map))
		return "0"
	case ir.MapForEach:
		return e.mapForEach(expression)
	case ir.SetNew:
		var values string
		if expression.Values != nil {
			values = e.value(expression.Values)
		}
		created := e.own(ir.Map, newMap(expression.Element, false))
		if expression.Values != nil {
			e.line("adamic_set_add_all(%s, %s);", created, values)
		}
		return created
	case ir.SetAdd:
		set := e.value(expression.Set)
		value := e.value(expression.Value)
		e.line("adamic_map_set(%s, %s, (adamic_value){.number = 0});", set, held(expression.Element, value))
		return set
	case ir.SetValues:
		return e.own(ir.Array, fmt.Sprintf("adamic_set_values(%s)", e.value(expression.Set)))
	case ir.MapGet:
		object := e.value(expression.Map)
		key := e.value(expression.Key)
		slot := e.temporary()
		e.line("adamic_value *%s = adamic_map_get(%s, %s);", slot, object, borrowed(expression.KeyType, key))
		if expression.Type().IsMaybe() {
			return e.snapshot(expression.Type(), maybeSlot(expression.ValueType, slot))
		}
		// Retained, so a set later in the same statement can't free it from under its reader.
		return e.own(expression.ValueType, fmt.Sprintf("%s == NULL ? NULL : adamic_retain(%s->%s)", slot, slot, member(expression.ValueType)))
	case ir.MapSet:
		object := e.value(expression.Map)
		key := e.value(expression.Key)
		value := e.value(expression.Value)
		e.line("adamic_map_set(%s, %s, %s);", object, held(expression.KeyType, key), held(expression.ValueType, value))
		return object
	case ir.MapHas:
		object := e.value(expression.Map)
		key := e.value(expression.Key)
		return e.snapshot(ir.Boolean, fmt.Sprintf("(adamic_map_get(%s, %s) != NULL)", object, borrowed(expression.KeyType, key)))
	case ir.MapDelete:
		object := e.value(expression.Map)
		key := e.value(expression.Key)
		result := e.temporary()
		e.line("bool %s = adamic_map_delete(%s, %s);", result, object, borrowed(expression.KeyType, key))
		return result
	case ir.MapSize:
		return e.snapshot(ir.Number, fmt.Sprintf("(double)%s->count", e.value(expression.Map)))
	case ir.ReadTextFile:
		return e.own(ir.Object, fmt.Sprintf("adamic_read_text_file(%s)", e.value(expression.Path)))
	case ir.ProgramArguments:
		return e.own(ir.Array, "adamic_program_arguments()")
	case ir.ReadDirectory:
		return e.own(ir.Object, fmt.Sprintf("adamic_read_directory(%s)", e.value(expression.Path)))
	case ir.FileStatus:
		return e.own(ir.Object, fmt.Sprintf("adamic_file_status(%s)", e.value(expression.Path)))
	case ir.WriteTextFile:
		path := e.value(expression.Path)
		text := e.value(expression.Text)
		return e.own(ir.Object, fmt.Sprintf("adamic_write_text_file(%s, %s)", path, text))
	case ir.ArrayPush:
		array := e.value(expression.Array)
		value := e.value(expression.Value)
		if expression.Element.IsReference() {
			value = "adamic_retain(" + value + ")"
		}
		// The append happens here, in JavaScript's order, and the new length is the value.
		e.line("adamic_array_push(%s, (adamic_value){.%s = %s});", array, member(expression.Element), slotted(expression.Element, value))
		length := e.temporary()
		e.line("double %s = (double)%s->length;", length, array)
		return length
	case ir.ArrayJoin:
		array := e.value(expression.Array)
		separator := e.value(expression.Separator)
		return e.own(ir.String, fmt.Sprintf("adamic_array_join(%s, %s, %s)", array, separator, joinKind(expression.Element)))
	case ir.ArrayLiteral:
		if spread, ok := e.spreadArray(expression); ok {
			return spread
		}
		if expression.Spread != nil {
			// A spread is iterated where it stands, before the elements after it are evaluated, so the
			// array is made first (which nothing can see) and each element appended as it comes.
			array := e.own(ir.Array, fmt.Sprintf("adamic_array_new(0, %t)", expression.Element.IsReference()))
			for index, element := range expression.Elements {
				value := e.value(element)
				switch {
				case expression.Spread[index]:
					e.line("adamic_array_append(%s, %s);", array, value)
				case expression.Element.IsReference():
					e.line("adamic_array_push(%s, (adamic_value){.reference = adamic_retain(%s)});", array, value)
				default:
					e.line("adamic_array_push(%s, (adamic_value){.%s = %s});", array, member(expression.Element), slotted(expression.Element, value))
				}
			}
			return array
		}
		elements := make([]string, 0, len(expression.Elements))
		for _, element := range expression.Elements {
			elements = append(elements, e.value(element))
		}
		array := e.own(ir.Array, fmt.Sprintf("adamic_array_new(%d, %t)", len(elements), expression.Element.IsReference()))
		for _, element := range elements {
			if expression.Element.IsReference() {
				element = "adamic_retain(" + element + ")"
			}
			e.line("adamic_array_push(%s, (adamic_value){.%s = %s});", array, member(expression.Element), slotted(expression.Element, element))
		}
		return array
	case ir.Length:
		return e.snapshot(ir.Number, fmt.Sprintf("(double)%s->length", e.value(expression.Array)))
	case ir.MathCall:
		return e.mathCall(expression)
	case ir.NumberCall:
		arguments := []string{}
		for _, argument := range expression.Arguments {
			arguments = append(arguments, e.value(argument))
		}
		switch expression.Function {
		case "parseInt":
			// A radix left out is undefined, which ToInt32 makes 0: detect it from the text.
			radix := "0.0"
			if len(arguments) == 2 {
				radix = arguments[1]
			}
			return e.snapshot(ir.Number, fmt.Sprintf("adamic_number_parse_int(%s, %s)", arguments[0], radix))
		case "parseFloat":
			return e.snapshot(ir.Number, fmt.Sprintf("adamic_number_parse_float(%s)", arguments[0]))
		case "isNaN":
			return fmt.Sprintf("isnan(%s)", arguments[0])
		case "isFinite":
			return fmt.Sprintf("isfinite(%s)", arguments[0])
		case "isInteger":
			return fmt.Sprintf("(isfinite(%s) && trunc(%s) == %s)", arguments[0], arguments[0], arguments[0])
		}
		return fmt.Sprintf("(isfinite(%s) && trunc(%s) == %s && fabs(%s) <= 9007199254740991.0)", arguments[0], arguments[0], arguments[0], arguments[0])
	case ir.ToFixed:
		value := e.value(expression.Value)
		digits := e.value(expression.Digits)
		return e.own(ir.String, fmt.Sprintf("adamic_number_to_fixed(%s, %s)", value, digits))
	case ir.NumberFormat:
		return e.numberFormat(expression)
	}
	panic(fmt.Sprintf("native: no C for %T", expression))
}

// arrayVisit emits forEach, filter, some, every, find and findIndex as one loop. The length is read
// once and an index the array has lost is skipped, as JavaScript does (0.1's arrays have no holes, so
// a lost index is one past a shrunken end). Each element is held across its call, since the callback
// may take it out of the array; filter and find hand that hold to what they return.
func (e *emitter) arrayVisit(visit ir.ArrayVisit) string {
	source := e.temporary()
	e.line("adamic_array *%s = %s;", source, e.value(visit.Array))
	callback := e.value(visit.Callback)
	references := visit.Element.IsReference()
	result := "0"
	switch visit.Method {
	case "filter":
		result = e.own(ir.Array, fmt.Sprintf("adamic_array_new(0, %t)", references))
	case "some", "every":
		result = e.snapshot(ir.Boolean, strconv.FormatBool(visit.Method == "every"))
	case "findIndex":
		result = e.snapshot(ir.Number, "-1.0")
	case "find":
		if visit.Type().IsMaybe() {
			result = e.snapshot(visit.Type(), zero(visit.Type()))
		} else {
			result = e.own(visit.Element, "NULL")
		}
	}
	count, index, element, answer := e.temporary(), e.temporary(), e.temporary(), e.temporary()
	e.line("size_t %s = %s->length;", count, source)
	e.line("for (size_t %s = 0; %s < %s; %s++) {", index, index, count, index)
	e.indent++
	e.line("if (%s >= %s->length) {", index, source)
	if visit.Method == "find" || visit.Method == "findIndex" {
		// The other visits skip an index the callback took away, as JavaScript's do; find and
		// findIndex call it with undefined there, which the element's type can't hold. A panic, the
		// same in both backends.
		e.line("\tstatic const char message[] = \"%s: the array shrank while it was being searched\";", visit.Method)
		e.line("\tadamic_panic(message, sizeof message - 1);")
	} else {
		e.line("\tcontinue;")
	}
	e.line("}")
	e.line("adamic_value %s = %s->elements[%s];", element, source, index)
	if references {
		e.line("adamic_retain(%s.reference);", element)
	}
	call := fmt.Sprintf("%s->code(%s, (adamic_value[]){%s, {.number = (double)%s}, {.reference = %s}})", callback, callback, element, index, source)
	if visit.Method == "forEach" && !visit.Returns.IsReference() {
		e.line("%s;", call)
	} else {
		e.line("adamic_value %s = %s;", answer, call)
	}
	// The element held across the call is let go; what the visit made so far is the statement's.
	if references {
		e.closureThrown(element + ".reference")
	} else {
		e.closureThrown()
	}
	release := func() {
		if references {
			e.line("adamic_release(%s.reference);", element)
		}
	}
	switch visit.Method {
	case "forEach":
		if visit.Returns.IsReference() {
			// A callback's result comes back owned, and forEach has no use for it.
			e.line("adamic_release(%s.reference);", answer)
		}
		release()
	case "filter":
		e.line("if (%s.boolean) {", answer)
		e.line("\tadamic_array_push(%s, %s);", result, element)
		if references {
			e.line("} else {")
			e.line("\tadamic_release(%s.reference);", element)
		}
		e.line("}")
	case "find":
		e.line("if (%s.boolean) {", answer)
		if visit.Type().IsMaybe() {
			found := element + "." + member(visit.Element)
			if visit.Element == ir.MaybeNumber {
				found = unslotted(ir.MaybeNumber, found)
			} else {
				found = maybe(visit.Type(), found)
			}
			e.line("\t%s = %s;", result, found)
		} else {
			e.line("\t%s = %s.reference;", result, element)
		}
		e.line("\tbreak;")
		e.line("}")
		release()
	default:
		release()
		found, value := answer+".boolean", "true"
		switch visit.Method {
		case "every":
			found, value = "!"+found, "false"
		case "findIndex":
			value = "(double)" + index
		}
		e.line("if (%s) {", found)
		e.line("\t%s = %s;", result, value)
		e.line("\tbreak;")
		e.line("}")
	}
	e.indent--
	e.line("}")
	return result
}

// newMap makes a map, or a Set's map, for its keys: strings by their text, numbers by
// SameValueZero, booleans as booleans, and anything else held by reference by its identity.
func newMap(key ir.Type, referenceValues bool) string {
	if key == ir.Boolean {
		return fmt.Sprintf("adamic_map_new_booleans(%t)", referenceValues)
	}
	if key.IsReference() && key != ir.String {
		return fmt.Sprintf("adamic_map_new_identity(%t)", referenceValues)
	}
	return fmt.Sprintf("adamic_map_new(%t, %t)", key == ir.String, referenceValues)
}

// mapForEach emits map.forEach and set.forEach as for...of's loop over the map, live as it is. The key
// and value are held across each call, since the callback may delete their entry; a Set's callback
// gets its element twice, as JavaScript gives it.
func (e *emitter) mapForEach(visit ir.MapForEach) string {
	collection := e.value(visit.Map)
	callback := e.value(visit.Callback)
	iterator, key, value, answer := e.temporary(), e.temporary(), e.temporary(), e.temporary()
	e.line("adamic_map_iterator *%s = adamic_map_iterate(%s);", iterator, collection)
	e.line("adamic_value %s, %s;", key, value)
	e.line("while (adamic_map_iterator_next(%s, &%s, &%s)) {", iterator, key, value)
	e.indent++
	hold := func(slot string, of ir.Type, how string) {
		if of.IsReference() {
			e.line("%s(%s.reference);", how, slot)
		}
	}
	hold(key, visit.Key, "adamic_retain")
	first := value
	if visit.Set {
		first = key
	} else {
		hold(value, visit.Value, "adamic_retain")
	}
	call := fmt.Sprintf("%s->code(%s, (adamic_value[]){%s, %s, {.reference = %s}})", callback, callback, first, key, collection)
	// A throw lets go of the key and value held across the call, and the iterator.
	holds := []string{}
	if !visit.Set && visit.Value.IsReference() {
		holds = append(holds, value+".reference")
	}
	if visit.Key.IsReference() {
		holds = append(holds, key+".reference")
	}
	holds = append(holds, iterator)
	if visit.Returns.IsReference() {
		// A callback's result comes back owned, and forEach has no use for it.
		e.line("adamic_value %s = %s;", answer, call)
		e.closureThrown(holds...)
		e.line("adamic_release(%s.reference);", answer)
	} else {
		e.line("%s;", call)
		e.closureThrown(holds...)
	}
	if !visit.Set {
		hold(value, visit.Value, "adamic_release")
	}
	hold(key, visit.Key, "adamic_release")
	e.indent--
	e.line("}")
	e.line("adamic_release(%s);", iterator)
	return "0"
}

// arrayReduce emits reduce as arrayVisit's loop, carrying what the callback last returned. The callee
// holds its own copy of each argument, so after each call the old accumulator is let go and the new
// one, which comes back owned, is taken.
func (e *emitter) arrayReduce(reduce ir.ArrayReduce) string {
	source := e.temporary()
	e.line("adamic_array *%s = %s;", source, e.value(reduce.Array))
	callback := e.value(reduce.Callback)
	initial := e.value(reduce.Initial)
	var accumulator string
	if reduce.Result.IsReference() {
		accumulator = e.own(reduce.Result, fmt.Sprintf("adamic_retain(%s)", initial))
	} else {
		accumulator = e.snapshot(reduce.Result, initial)
	}
	count, index, element, answer := e.temporary(), e.temporary(), e.temporary(), e.temporary()
	e.line("size_t %s = %s->length;", count, source)
	e.line("for (size_t %s = 0; %s < %s; %s++) {", index, index, count, index)
	e.indent++
	e.line("if (%s >= %s->length) {", index, source)
	e.line("\tcontinue;")
	e.line("}")
	e.line("adamic_value %s = %s->elements[%s];", element, source, index)
	if reduce.Element.IsReference() {
		e.line("adamic_retain(%s.reference);", element)
	}
	e.line("adamic_value %s = %s->code(%s, (adamic_value[]){{.%s = %s}, %s, {.number = (double)%s}, {.reference = %s}});",
		answer, callback, callback, member(reduce.Result), slotted(reduce.Result, accumulator), element, index, source)
	// The element held across the call is let go; the accumulator is the statement's.
	if reduce.Element.IsReference() {
		e.closureThrown(element + ".reference")
	} else {
		e.closureThrown()
	}
	if reduce.Element.IsReference() {
		e.line("adamic_release(%s.reference);", element)
	}
	if reduce.Result.IsReference() {
		e.line("adamic_release(%s);", accumulator)
		e.line("%s = (%s)%s.reference;", accumulator, cType(reduce.Result), answer)
	} else {
		e.line("%s = %s;", accumulator, unslotted(reduce.Result, answer+"."+member(reduce.Result)))
	}
	e.indent--
	e.line("}")
	return accumulator
}

// equality tells the runtime how indexOf and includes compare elements.
func equality(element ir.Type) string {
	switch element {
	case ir.Number:
		return "adamic_equal_numbers"
	case ir.Boolean:
		return "adamic_equal_booleans"
	case ir.String:
		return "adamic_equal_strings"
	case ir.MaybeNumber:
		return "adamic_equal_maybe_numbers"
	}
	return "adamic_equal_identity"
}

// objectLiteral makes an object. Its fields' values are evaluated in order first; making the object
// itself can't be observed, so it may come after them.
func (e *emitter) objectLiteral(literal ir.ObjectLiteral) string {
	if reused, ok := e.reused(literal); ok {
		return reused
	}
	if literal.Spread != nil {
		// A copy of the source's object, whatever its shape, with the named fields replaced. The copy
		// is made the moment the spread is evaluated, before any field's value: JavaScript reads the
		// spread's fields first, so a field's expression that writes one of them (a call that sets
		// it) must not show in the result.
		source := e.value(literal.Spread)
		object := e.own(ir.Object, e.spreadCopy(literal, source))
		e.emptySpread(literal, source, object)
		values := make([]string, 0, len(literal.Fields))
		for _, field := range literal.Fields {
			values = append(values, e.value(field.Value))
		}
		for index, field := range literal.Fields {
			slot := e.temporary()
			e.line("adamic_value *%s = adamic_object_field(%s, %s, &%s);", slot, object, cString(field.Name), e.cache())
			if field.Value.Type().IsReference() {
				e.line("adamic_release(%s->reference);", slot)
				e.line("%s->reference = adamic_retain(%s);", slot, values[index])
			} else {
				e.line("%s->%s = %s;", slot, member(field.Value.Type()), slotted(field.Value.Type(), values[index]))
			}
		}
		return object
	}
	values := make([]string, 0, len(literal.Fields))
	for _, field := range literal.Fields {
		values = append(values, e.value(field.Value))
	}
	object := e.own(ir.Object, fmt.Sprintf("adamic_object_new(&%s)", e.shape(literal.Fields)))
	for index, field := range literal.Fields {
		value := values[index]
		if field.Value.Type().IsReference() {
			value = "adamic_retain(" + value + ")"
		}
		e.line("%s->slots[%d].%s = %s;", object, index, member(field.Value.Type()), slotted(field.Value.Type(), value))
	}
	return object
}

// shape declares an object literal's layout once, at file scope, and names it.
func (e *emitter) shape(fields []ir.Field) string {
	names, types := []string{}, []ir.Type{}
	for _, field := range fields {
		names = append(names, field.Name)
		types = append(types, field.Value.Type())
	}
	return e.shapeOf(names, types)
}

// shapeOf declares a layout by its field names and types.
func (e *emitter) shapeOf(fieldNames []string, fieldTypes []ir.Type) string {
	names, references := []string{}, []string{}
	for index, name := range fieldNames {
		names = append(names, cString(name))
		references = append(references, strconv.FormatBool(fieldTypes[index].IsReference()))
	}
	fields := fieldNames
	key := strings.Join(names, ",") + "|" + strings.Join(references, ",")
	if e.shapes == nil {
		e.shapes = map[string]string{}
	}
	if name, isDeclared := e.shapes[key]; isDeclared {
		return name
	}
	name := fmt.Sprintf("adamic_shape_%d", len(e.shapes))
	e.shapes[key] = name
	if len(fields) == 0 {
		e.declarations = append(e.declarations, fmt.Sprintf("static const adamic_shape %s = {0, NULL, NULL};", name))
	} else {
		e.declarations = append(e.declarations,
			fmt.Sprintf("static const char *const %s_names[] = {%s};", name, strings.Join(names, ", ")),
			fmt.Sprintf("static const bool %s_references[] = {%s};", name, strings.Join(references, ", ")),
			fmt.Sprintf("static const adamic_shape %s = {%d, %s_names, %s_references};", name, len(fields), name, name))
	}
	return name
}

// cache declares a field cache for one place in the program that finds a field.
func (e *emitter) cache() string {
	e.temporaries++
	name := fmt.Sprintf("adamic_cache_%d", e.temporaries)
	e.declarations = append(e.declarations, fmt.Sprintf("static adamic_slot_cache %s;", name))
	return name
}

var cMath = map[string]string{
	"abs": "fabs", "ceil": "ceil", "floor": "floor", "trunc": "trunc", "sqrt": "sqrt",
	"round": "adamic_math_round", "sign": "adamic_math_sign", "pow": "adamic_power",
}

// numberFormat emits toExponential and toPrecision (runtime/dtoa.c) and toString with a radix
// (runtime/radix.c), the receiver before the argument, as JavaScript reads them.
func (e *emitter) numberFormat(format ir.NumberFormat) string {
	value := e.value(format.Value)
	if format.Method == "toString" {
		if format.Argument == nil {
			return e.own(ir.String, fmt.Sprintf("adamic_string_from_number(%s)", value))
		}
		return e.own(ir.String, fmt.Sprintf("adamic_number_to_radix(%s, %s)", value, e.value(format.Argument)))
	}
	argument, hasArgument := "0.0", "false"
	if format.Argument != nil {
		argument, hasArgument = e.value(format.Argument), "true"
	}
	function := map[string]string{"toExponential": "adamic_number_to_exponential", "toPrecision": "adamic_number_to_precision"}[format.Method]
	return e.own(ir.String, fmt.Sprintf("%s(%s, %s, %s)", function, value, argument, hasArgument))
}

// cIeee754 are the Math functions ported from V8 (runtime/ieee754.c), each adamic_math_<name>. C's
// own sin, exp and the rest differ from V8's in the last bit, so they're never called.
var cIeee754 = map[string]bool{
	"sin": true, "cos": true, "tan": true, "asin": true, "acos": true, "atan": true, "atan2": true,
	"sinh": true, "cosh": true, "tanh": true, "asinh": true, "acosh": true, "atanh": true,
	"exp": true, "expm1": true, "log": true, "log1p": true, "log2": true, "log10": true, "cbrt": true,
}

func (e *emitter) mathCall(call ir.MathCall) string {
	arguments := make([]string, 0, len(call.Arguments))
	for _, argument := range call.Arguments {
		arguments = append(arguments, e.value(argument))
	}
	if function, isDirect := cMath[call.Function]; isDirect {
		return fmt.Sprintf("%s(%s)", function, strings.Join(arguments, ", "))
	}
	if cIeee754[call.Function] {
		return fmt.Sprintf("adamic_math_%s(%s)", call.Function, strings.Join(arguments, ", "))
	}
	if call.Function == "hypot" {
		// Math.hypot() is +0; otherwise the values go as an array, already evaluated in order.
		if len(arguments) == 0 {
			return "0.0"
		}
		return fmt.Sprintf("adamic_math_hypot(%d, (const double[]){%s})", len(arguments), strings.Join(arguments, ", "))
	}
	// max and min take any number of arguments: none gives -Infinity (max) or Infinity (min), one
	// gives itself, and more fold pairwise, every argument already evaluated, as JavaScript does.
	switch len(arguments) {
	case 0:
		if call.Function == "max" {
			return "(-HUGE_VAL)"
		}
		return "HUGE_VAL"
	case 1:
		return "(+" + arguments[0] + ")"
	}
	folded := arguments[0]
	for _, argument := range arguments[1:] {
		folded = fmt.Sprintf("adamic_math_%s(%s, %s)", call.Function, folded, argument)
	}
	return folded
}

// forOf emits for (const element of array). The array is held (retained) for the whole loop, as
// JavaScript's iterator holds it even if the variable naming it is reassigned, and its length is read
// again before each pass. Over a map, what's held is an iterator, which holds the map and keeps it
// from compacting until every way out of the loop has let go of it.
func (e *emitter) forOf(statement ir.ForOf) {
	e.line("{")
	e.indent++
	e.scopes = append(e.scopes, nil)
	iterable := e.value(statement.Iterable)
	held := e.temporary()
	overString := statement.Iterable.Type() == ir.String
	overMap := statement.MapPart != ""
	if overMap {
		e.line("adamic_map_iterator *%s = adamic_map_iterate(%s);", held, iterable)
	} else {
		e.line("%s %s = adamic_retain(%s);", cType(statement.Iterable.Type()), held, iterable)
	}
	e.hold(held)
	e.end()
	index := e.temporary()
	size := e.temporary()
	e.temporaries++
	current := &loop{label: fmt.Sprintf("adamic_continue_%d", e.temporaries)}
	entryKey, entryValue := e.temporary(), e.temporary()
	if overMap {
		e.line("adamic_value %s, %s;", entryKey, entryValue)
		e.line("while (adamic_map_iterator_next(%s, &%s, &%s)) {", held, entryKey, entryValue)
	} else if overString {
		// A code point at a time: size is its byte length, and the element is a string of it.
		e.line("for (size_t %s = 0, %s = 0; %s < %s->length; %s += %s) {", index, size, index, held, index, size)
		e.line("\t%s = adamic_string_next(%s, %s);", size, held, index)
	} else {
		e.line("for (size_t %s = 0; %s < %s->length; %s++) {", index, index, held, index)
	}
	e.indent++
	saved := e.out
	e.out = strings.Builder{}
	current.depth = len(e.scopes)
	e.loops = append(e.loops, current)
	e.breakables = append(e.breakables, current.depth)
	e.line("{")
	e.indent++
	e.scopes = append(e.scopes, nil)
	element := unslotted(statement.Element, fmt.Sprintf("%s->elements[%s].%s", held, index, member(statement.Element)))
	// bindEntry declares a local from the step's key or value, retained, since the body may delete
	// the entry.
	bindEntry := func(local int, slot string, of ir.Type) {
		reading := unslotted(of, slot+"."+member(of))
		if of.IsReference() {
			reading = fmt.Sprintf("(%s)%s", cType(of), reading)
		}
		e.declareLocal(local, reading, false)
	}
	if overMap {
		switch statement.MapPart {
		case "keys":
			bindEntry(statement.Local, entryKey, statement.Key)
		case "values":
			bindEntry(statement.Local, entryValue, statement.Value)
		default:
			for _, binding := range statement.Pattern {
				if binding.Field == "0" {
					bindEntry(binding.Local, entryKey, statement.Key)
				} else {
					bindEntry(binding.Local, entryValue, statement.Value)
				}
			}
		}
	} else if statement.Pattern != nil {
		// Each name reads its field of the tuple, which the array holds while the body runs.
		for _, binding := range statement.Pattern {
			bound := e.program.Locals[binding.Local]
			field := unslotted(bound.Type, fmt.Sprintf("adamic_object_field(%s, %s, &%s)->%s", element, cString(binding.Field), e.cache(), member(bound.Type)))
			if bound.Type.IsReference() {
				field = fmt.Sprintf("(%s)%s", cType(bound.Type), field)
			}
			e.declareLocal(binding.Local, field, false)
		}
	} else if overString {
		e.declareLocal(statement.Local, fmt.Sprintf("adamic_string_slice_bytes(%s, %s, %s)", held, index, size), true)
	} else {
		if statement.Element.IsReference() {
			element = fmt.Sprintf("(%s)%s", cType(statement.Element), element)
		}
		e.declareLocal(statement.Local, element, false)
	}
	for index := range statement.Body {
		e.statementAt(&statement.Body[index])
	}
	e.releaseScopes(len(e.scopes) - 1)
	e.scopes = e.scopes[:len(e.scopes)-1]
	e.indent--
	e.line("}")
	e.breakables = e.breakables[:len(e.breakables)-1]
	e.loops = e.loops[:len(e.loops)-1]
	body := e.out.String()
	e.out = saved
	e.out.WriteString(body)
	if current.continued {
		e.line("%s:;", current.label)
	}
	e.indent--
	e.line("}")
	e.releaseScopes(len(e.scopes) - 1)
	e.scopes = e.scopes[:len(e.scopes)-1]
	e.indent--
	e.line("}")
}

// switchStatement emits a switch as do { if / else } while (0), so a break inside a case leaves the
// switch exactly as JavaScript's does: the do is the innermost thing a C break leaves.
func (e *emitter) switchStatement(statement ir.Switch) {
	e.line("{")
	e.indent++
	e.scopes = append(e.scopes, nil)
	value := e.value(statement.Value)
	held := e.temporary()
	if statement.Value.Type().IsReference() {
		e.line("%s %s = adamic_retain(%s);", cType(statement.Value.Type()), held, value)
		e.hold(held)
	} else {
		e.line("%s %s = %s;", cType(statement.Value.Type()), held, value)
	}
	e.end()
	e.line("do {")
	e.indent++
	e.breakables = append(e.breakables, len(e.scopes))
	depth := 0
	for _, matched := range statement.Cases {
		tests := []string{}
		for _, test := range matched.Tests {
			tests = append(tests, e.binary(ir.Equal, statement.Value.Type(), held, e.value(test)))
		}
		e.line("if (%s) {", unwrap(strings.Join(tests, " || ")))
		e.nested(matched.Body, nil)
		e.line("} else {")
		e.indent++
		depth++
	}
	e.block(statement.Default, nil)
	for ; depth > 0; depth-- {
		e.indent--
		e.line("}")
	}
	e.breakables = e.breakables[:len(e.breakables)-1]
	e.indent--
	e.line("} while (0);")
	e.releaseScopes(len(e.scopes) - 1)
	e.scopes = e.scopes[:len(e.scopes)-1]
	e.indent--
	e.line("}")
}

// read reads a local. A global may change under a later call in the same statement, so its value is
// copied (a string retained) the moment JavaScript would read it; and from inside a function it's
// checked against the temporal dead zone first.
func (e *emitter) read(read ir.Read) string {
	name := e.localName(read.Local)
	if e.program.Locals[read.Local].Counter {
		// Read as the double it stands for, which every value it can hold is exactly.
		return "((double)" + name + ")"
	}
	// A reference its consumer lends needs no count: nothing can run before it's used (borrow.go).
	lent := e.lendable && lendable(read.Of)
	if slot := e.cellSlot(read.Local); slot != "" {
		// A captured variable may change under a call later in the statement (a closure that
		// writes it), so, like a global, it's copied the moment JavaScript reads it.
		value := unslotted(read.Of, slot+"."+member(read.Of))
		if lent {
			e.self = true
			return e.snapshot(read.Of, fmt.Sprintf("(%s)%s", cType(read.Of), value))
		}
		if read.Of.IsReference() {
			return e.own(read.Of, fmt.Sprintf("adamic_retain((%s)%s)", cType(read.Of), value))
		}
		snapshot := e.temporary()
		e.line("%s %s = %s;", cType(read.Of), snapshot, value)
		return snapshot
	}
	if !e.program.Locals[read.Local].Global {
		return name
	}
	if read.Checked {
		e.checkReady(read.Local)
	}
	if lent {
		e.self = true
		return e.snapshot(read.Of, name)
	}
	if read.Of.IsReference() {
		return e.own(read.Of, fmt.Sprintf("adamic_retain(%s)", name))
	}
	snapshot := e.temporary()
	e.line("%s %s = %s;", cType(read.Of), snapshot, name)
	return snapshot
}

// arguments evaluates a call's arguments in order, each fitted to its parameter: a number or undefined
// made number | undefined's two words. An optional parameter the call leaves out gets undefined. This
// is done here, not in lowering, since only here is every function's signature known: lowering may
// meet a call before the function it calls.
func (e *emitter) arguments(call ir.Call) []string {
	parameters := e.program.Functions[call.Function].Parameters
	arguments := make([]string, 0, len(parameters))
	handed := []string{}
	defer func() { e.handedOver(handed) }()
	for index, argument := range call.Arguments {
		if index < len(parameters) && e.reuse.consumed[parameters[index]] {
			value := e.handOver(argument)
			handed = append(handed, value)
			arguments = append(arguments, value)
			continue
		}
		value := e.value(argument)
		if index < len(parameters) && e.program.Locals[parameters[index]].Type.IsMaybe() {
			of := e.program.Locals[parameters[index]].Type
			if _, isUndefined := argument.(ir.Undefined); isUndefined {
				value = zero(of)
			} else if argument.Type() == of.Present() {
				value = maybe(of, value)
			}
		}
		if index < len(parameters) && (e.program.Locals[parameters[index]].Type == ir.Union || e.program.Locals[parameters[index]].Type == ir.Weak) && argument.Type() != e.program.Locals[parameters[index]].Type {
			// A number, a boolean or a reference where a union goes, boxed here, where the signature
			// is known; a reference where a Weak goes, its handle.
			takes := e.program.Locals[parameters[index]].Type
			boxed, fresh := converted(argument.Type(), takes, value)
			if fresh {
				boxed = e.own(takes, boxed)
			}
			value = boxed
		}
		arguments = append(arguments, value)
	}
	for _, parameter := range parameters[min(len(call.Arguments), len(parameters)):] {
		if of := e.program.Locals[parameter].Type; of.IsMaybe() {
			arguments = append(arguments, zero(of))
		} else {
			arguments = append(arguments, "NULL")
		}
	}
	return arguments
}

// aside emits work into a buffer of its own, one level in, with temporaries of its own, and returns
// the text, the value, and what it owns, so the caller can decide where the work belongs.
func (e *emitter) aside(expression ir.Expression) (string, string, []string) {
	savedOut, savedOwned := e.out, e.owned
	e.out, e.owned = strings.Builder{}, nil
	// A throw from inside lets go of what the statement owned before the aside too.
	e.outerOwned = append(e.outerOwned, savedOwned)
	e.indent++
	value := e.value(expression)
	e.indent--
	e.outerOwned = e.outerOwned[:len(e.outerOwned)-1]
	text, owned := e.out.String(), e.owned
	e.out, e.owned = savedOut, savedOwned
	return text, value, owned
}

// logical emits && and ||. When the right operand has nothing to run first, C's own operator
// short-circuits the same way; otherwise the right side runs only on the branch JavaScript takes.
func (e *emitter) logical(binary ir.Binary) string {
	left := e.value(binary.Left)
	text, right, owned := e.aside(binary.Right)
	operator := "&&"
	if binary.Operator == ir.Or {
		operator = "||"
	}
	if text == "" && len(owned) == 0 {
		return fmt.Sprintf("(%s %s %s)", left, operator, right)
	}
	result := e.temporary()
	e.line("bool %s = %s;", result, left)
	if binary.Operator == ir.And {
		e.line("if (%s) {", result)
	} else {
		e.line("if (!%s) {", result)
	}
	e.out.WriteString(text)
	e.indent++
	e.line("%s = %s;", result, right)
	for index := len(owned) - 1; index >= 0; index-- {
		e.line("adamic_release(%s);", owned[index])
	}
	e.indent--
	e.line("}")
	return result
}

// conditional emits ?:, evaluating only the branch JavaScript takes.
func (e *emitter) conditional(conditional ir.Conditional) string {
	condition := e.value(conditional.Condition)
	trueText, whenTrue, trueOwned := e.aside(conditional.WhenTrue)
	notText, whenNot, notOwned := e.aside(conditional.WhenNot)
	if trueText == "" && notText == "" && len(trueOwned) == 0 && len(notOwned) == 0 {
		return fmt.Sprintf("(%s ? %s : %s)", condition, whenTrue, whenNot)
	}
	valueType := conditional.Type()
	result := e.temporary()
	e.line("%s %s;", cType(valueType), result)
	branch := func(text string, value string, owned []string) {
		e.out.WriteString(text)
		e.indent++
		if valueType.IsReference() {
			e.line("%s = adamic_retain(%s);", result, value)
		} else {
			e.line("%s = %s;", result, value)
		}
		for index := len(owned) - 1; index >= 0; index-- {
			e.line("adamic_release(%s);", owned[index])
		}
		e.indent--
	}
	e.line("if (%s) {", unwrap(condition))
	branch(trueText, whenTrue, trueOwned)
	e.line("} else {")
	branch(notText, whenNot, notOwned)
	e.line("}")
	if valueType.IsReference() {
		e.owned = append(e.owned, result)
	}
	return result
}

// snapshot reads a value that something later in the statement could change (a field, a length, a
// map's size) into a temporary, at the moment JavaScript reads it.
func (e *emitter) snapshot(valueType ir.Type, value string) string {
	name := e.temporary()
	e.line("%s %s = %s;", cType(valueType), name, value)
	return name
}

// own puts a reference the statement owns in a temporary, released when the statement ends.
func (e *emitter) own(valueType ir.Type, value string) string {
	name := e.temporary()
	e.line("%s %s = %s;", cType(valueType), name, value)
	e.owned = append(e.owned, name)
	return name
}

var cOperators = map[ir.Operator]string{
	ir.Add: "+", ir.Subtract: "-", ir.Multiply: "*", ir.Divide: "/",
	ir.Less: "<", ir.LessOrEqual: "<=", ir.Greater: ">", ir.GreaterOrEqual: ">=",
	ir.Equal: "==", ir.NotEqual: "!=",
}

func (e *emitter) binary(operator ir.Operator, operandType ir.Type, left string, right string) string {
	switch {
	case operator == ir.Remainder:
		// JavaScript's % is C's fmod: truncated, with the sign of the dividend.
		return fmt.Sprintf("fmod(%s, %s)", left, right)
	case operator == ir.Power:
		return fmt.Sprintf("adamic_power(%s, %s)", left, right)
	case operandType == ir.String && (operator == ir.Less || operator == ir.LessOrEqual || operator == ir.Greater || operator == ir.GreaterOrEqual):
		return fmt.Sprintf("(adamic_string_compare(%s, %s) %s 0)", left, right, cOperators[operator])
	case operandType == ir.String && operator == ir.Equal:
		return fmt.Sprintf("adamic_string_equal(%s, %s)", left, right)
	case operandType == ir.String && operator == ir.NotEqual:
		return fmt.Sprintf("(!adamic_string_equal(%s, %s))", left, right)
	case operandType.IsMaybe() && (operator == ir.Equal || operator == ir.NotEqual):
		return pairEquality(operator, operandType, left, right)
	case operandType == ir.Union && operator == ir.Equal:
		return fmt.Sprintf("adamic_union_equal(%s, %s)", left, right)
	case operandType == ir.Union && operator == ir.NotEqual:
		return fmt.Sprintf("(!adamic_union_equal(%s, %s))", left, right)
	}
	return fmt.Sprintf("(%s %s %s)", left, cOperators[operator], right)
}

// unwrap drops one pair of parentheses around a whole expression, so a condition reads if (a == b)
// rather than if ((a == b)), which clang's -Wparentheses-equality rightly flags. It drops them only
// when the opening one closes at the very end, never from (a) == (b).
func unwrap(expression string) string {
	if !strings.HasPrefix(expression, "(") || !strings.HasSuffix(expression, ")") {
		return expression
	}
	depth := 0
	for index, character := range expression {
		switch character {
		case '(':
			depth++
		case ')':
			depth--
			if depth == 0 && index != len(expression)-1 {
				return expression
			}
		}
	}
	return expression[1 : len(expression)-1]
}

func cType(valueType ir.Type) string {
	switch valueType {
	case ir.Number:
		return "double"
	case ir.Boolean:
		return "bool"
	case ir.Object:
		return "adamic_object *"
	case ir.Array:
		return "adamic_array *"
	case ir.Map:
		return "adamic_map *"
	case ir.Closure:
		return "adamic_closure *"
	case ir.MaybeNumber:
		return "adamic_maybe_number"
	case ir.MaybeBoolean:
		return "adamic_maybe_boolean"
	case ir.Union:
		return "adamic_heap *"
	case ir.Weak:
		return "adamic_weak *"
	}
	return "adamic_string *"
}

// member is the adamic_value member that holds a value of the type.
func member(valueType ir.Type) string {
	switch valueType {
	case ir.Number, ir.MaybeNumber:
		return "number"
	case ir.Boolean:
		return "boolean"
	}
	return "reference"
}

// zero is a declared local's value before its first assignment. The checker proves no read comes
// first, so it's never seen; a string still needs a real one, since assigning releases the old.
func zero(valueType ir.Type) string {
	switch valueType {
	case ir.Number:
		return "0.0"
	case ir.Boolean:
		return "false"
	case ir.String:
		return "&adamic_string_empty"
	case ir.MaybeNumber:
		return "(adamic_maybe_number){false, 0.0}"
	case ir.MaybeBoolean:
		return "(adamic_maybe_boolean){false, false}"
	}
	return "NULL"
}

// cNumber is a double as a C literal that reads back as exactly the same bits: hexadecimal floating
// point, which C99 reads exactly, unlike decimal.
func cNumber(value float64) string {
	switch {
	case value != value:
		return "NAN"
	case value > 1.7976931348623157e308:
		return "HUGE_VAL"
	case value < -1.7976931348623157e308:
		return "(-HUGE_VAL)"
	}
	return "(" + strconv.FormatFloat(value, 'x', -1, 64) + ")"
}

// held is a value as an adamic_value whose reference, if it has one, the receiver keeps.
func held(valueType ir.Type, value string) string {
	if valueType.IsReference() {
		return fmt.Sprintf("(adamic_value){.reference = adamic_retain(%s)}", value)
	}
	return fmt.Sprintf("(adamic_value){.%s = %s}", member(valueType), slotted(valueType, value))
}

// borrowed is a value as an adamic_value the receiver only looks at.
func borrowed(valueType ir.Type, value string) string {
	return fmt.Sprintf("(adamic_value){.%s = %s}", member(valueType), slotted(valueType, value))
}

// coalesce emits value ?? fallback, the fallback evaluated only when the value is missing, and
// value ?? panic(message), which ends the program there.
func (e *emitter) coalesce(coalesce ir.Coalesce) string {
	value := e.value(coalesce.Value)
	present, unwrapped := value+" != NULL", value
	if coalesce.Value.Type().IsMaybe() {
		present, unwrapped = value+".present", value+"."+member(coalesce.Value.Type().Present())
	}
	// What's present is made what ?? makes: text ?? count boxes a present number into the union.
	unwrapped, fresh := converted(coalesce.Value.Type().Present(), coalesce.Of, unwrapped)
	if coalesce.Panic != nil {
		text, message, _ := e.aside(coalesce.Panic)
		e.line("if (!(%s)) {", present)
		e.out.WriteString(text)
		e.line("\tadamic_panic((%s)->bytes, (%s)->length);", message, message)
		e.line("}")
		if fresh {
			return e.own(coalesce.Of, unwrapped)
		}
		return unwrapped
	}
	text, fallback, owned := e.aside(coalesce.Fallback)
	result := e.temporary()
	e.line("%s %s;", cType(coalesce.Of), result)
	e.line("if (%s) {", present)
	if coalesce.Of.IsReference() && !fresh {
		e.line("\t%s = adamic_retain(%s);", result, unwrapped)
	} else {
		e.line("\t%s = %s;", result, unwrapped)
	}
	e.line("} else {")
	e.out.WriteString(text)
	e.indent++
	if coalesce.Of.IsReference() {
		e.line("%s = adamic_retain(%s);", result, fallback)
	} else {
		e.line("%s = %s;", result, fallback)
	}
	for index := len(owned) - 1; index >= 0; index-- {
		e.line("adamic_release(%s);", owned[index])
	}
	e.indent--
	e.line("}")
	if coalesce.Of.IsReference() {
		e.owned = append(e.owned, result)
	}
	return result
}

// joinKind tells the runtime how join writes an element.
func joinKind(element ir.Type) string {
	switch element {
	case ir.Number:
		return "adamic_join_numbers"
	case ir.Boolean:
		return "adamic_join_booleans"
	case ir.MaybeNumber:
		return "adamic_join_maybe_numbers"
	}
	return "adamic_join_strings"
}

func (e *emitter) stringCall(call ir.StringCall) string {
	value := e.value(call.Value)
	arguments := make([]string, 0, len(call.Arguments))
	for _, argument := range call.Arguments {
		arguments = append(arguments, e.value(argument))
	}
	switch call.Method {
	case "slice":
		start, end, hasEnd := "0.0", "0.0", false
		if len(arguments) > 0 {
			start = arguments[0]
		}
		if len(arguments) > 1 {
			end, hasEnd = arguments[1], true
		}
		return e.own(ir.String, fmt.Sprintf("adamic_string_slice(%s, %s, %s, %t)", value, start, end, hasEnd))
	case "codePointAt":
		result := e.temporary()
		e.line("adamic_maybe_number %s = adamic_string_code_point_at(%s, %s);", result, value, arguments[0])
		return result
	case "padStart", "padEnd":
		return e.own(ir.String, fmt.Sprintf("adamic_string_pad(%s, %s, %s, %t)", value, arguments[0], arguments[1], call.Method == "padStart"))
	case "repeat":
		return e.own(ir.String, fmt.Sprintf("adamic_string_repeat(%s, %s)", value, arguments[0]))
	case "split":
		return e.own(ir.Array, fmt.Sprintf("adamic_string_split(%s, %s)", value, arguments[0]))
	case "indexOf":
		return fmt.Sprintf("adamic_string_index_of(%s, %s)", value, arguments[0])
	case "lastIndexOf":
		return e.snapshot(ir.Number, fmt.Sprintf("adamic_string_last_index_of(%s, %s)", value, arguments[0]))
	case "trimStart", "trimEnd":
		return e.own(ir.String, fmt.Sprintf("adamic_string_trim_sides(%s, %t, %t)", value, call.Method == "trimStart", call.Method == "trimEnd"))
	case "at":
		return e.own(ir.String, fmt.Sprintf("adamic_string_at_relative(%s, %s)", value, arguments[0]))
	case "toUpperCase":
		return e.own(ir.String, fmt.Sprintf("adamic_string_to_upper(%s)", value))
	case "toLowerCase":
		return e.own(ir.String, fmt.Sprintf("adamic_string_to_lower(%s)", value))
	case "normalize":
		return e.own(ir.String, fmt.Sprintf("adamic_string_normalize(%s, %s)", value, arguments[0]))
	case "replace", "replaceAll":
		return e.own(ir.String, fmt.Sprintf("adamic_string_replace(%s, %s, %s, %t)", value, arguments[0], arguments[1], call.Method == "replaceAll"))
	case "includes":
		return fmt.Sprintf("(adamic_string_index_of(%s, %s) != -1)", value, arguments[0])
	case "startsWith":
		return fmt.Sprintf("adamic_string_starts_with(%s, %s)", value, arguments[0])
	}
	return fmt.Sprintf("adamic_string_ends_with(%s, %s)", value, arguments[0])
}

// comparator declares, once per sort, an adapter from the runtime's comparison to the program's
// comparator: JavaScript reads its result's sign, and NaN as 0.
func (e *emitter) comparator(sort ir.ArraySort) string {
	e.temporaries++
	name := fmt.Sprintf("adamic_compare_%d", e.temporaries)
	argument := unslotted(sort.Element, "left."+member(sort.Element)) + ", " + unslotted(sort.Element, "right."+member(sort.Element))
	e.declarations = append(e.declarations, fmt.Sprintf(
		"static int %s(adamic_value left, adamic_value right, void *context) {\n\t(void)context;\n\tdouble result = %s(%s);\n\treturn result < 0 ? -1 : result > 0 ? 1 : 0;\n}",
		name, e.functionName(sort.Comparator), argument))
	return name
}

// declareLocal declares a local with its first value. A reference is retained unless owned says the
// value is already the local's. A captured local is declared straight into a cell.
func (e *emitter) declareLocal(local int, value string, owned bool) {
	declared := e.program.Locals[local]
	if declared.Counter {
		// A whole-number constant within 2^53, which an integer holds exactly (lower/counters.go).
		e.line("int64_t %s = (int64_t)%s;", e.localName(local), value)
		return
	}
	if declared.Captured {
		e.makeCell(local, value, owned)
		return
	}
	name := e.localName(local)
	if declared.Type.IsReference() {
		if !owned {
			value = "adamic_retain(" + value + ")"
		}
		e.line("%s %s = %s;", cType(declared.Type), name, value)
		e.hold(name)
		return
	}
	e.line("%s %s = %s;", cType(declared.Type), name, value)
}

// makeCell declares a captured local's cell, holding value (retained unless owned).
func (e *emitter) makeCell(local int, value string, owned bool) {
	declared := e.program.Locals[local]
	if declared.Type.IsReference() && !owned {
		value = "adamic_retain(" + value + ")"
	}
	cell := e.cellName(local)
	e.line("adamic_cell *%s = adamic_cell_new((adamic_value){.%s = %s}, %t);", cell, member(declared.Type), slotted(declared.Type, value), declared.Type.IsReference())
	e.hold(cell)
}

func (e *emitter) cellName(local int) string {
	return e.localName(local) + "_cell"
}

// cellSlot is the adamic_value a captured local lives in, from the current function: a cell of its
// environment, or a cell it declared. It's "" for a local that isn't in a cell.
func (e *emitter) cellSlot(local int) string {
	if reference := e.cellReference(local); reference != "" {
		return reference + "->value"
	}
	return ""
}

// cellReference is the cell a captured local lives in, from the current function, or "".
func (e *emitter) cellReference(local int) string {
	declared := e.program.Locals[local]
	if declared.Global || !declared.Captured {
		return ""
	}
	if e.function != nil {
		for index, captured := range e.function.Environment {
			if captured == local {
				return fmt.Sprintf("self->cells[%d]", index)
			}
		}
	}
	return e.cellName(local)
}

// narrowedAwayMessage is the panic of a number or a boolean the checker narrowed undefined out of,
// read where a call since put it back (ir.Unwrap). JavaScript would go on computing with undefined.
const narrowedAwayMessage = "undefined where the checker narrowed it away: a call since the narrowing put it back"

// spliceArguments evaluates a splice's operands, in order, as the runtime's splice takes them.
func (e *emitter) spliceArguments(splice ir.ArraySplice) string {
	array := e.value(splice.Array)
	start := e.value(splice.Start)
	count := "0.0"
	if splice.Count != nil {
		count = e.value(splice.Count)
	}
	items := []string{}
	for _, item := range splice.Items {
		items = append(items, held(splice.Element, e.value(item)))
	}
	packed := "NULL"
	if len(items) > 0 {
		packed = "(adamic_value[]){" + strings.Join(items, ", ") + "}"
	}
	return fmt.Sprintf("%s, %s, %s, %t, %d, %s", array, start, count, splice.Count != nil, len(items), packed)
}
