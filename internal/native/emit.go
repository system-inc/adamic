package native

import (
	"fmt"
	"github.com/system-inc/adamic/internal/ir"
	"strings"
)

// C is a program as one C translation unit, to be compiled with the runtime.
//
// Expressions are evaluated in JavaScript's order. Each one yields a C expression that stays valid
// to the end of its statement: a constant, a local nothing can change mid-statement, or a temporary.
// A global is copied before anything after it runs, since a call may change it. &&, || and ?: become
// real branches whenever their later operands have work to do, so what JavaScript doesn't evaluate,
// Adamic doesn't either.
//
// Every string reference is released exactly once. A string made mid-statement lives in a temporary
// released when the statement ends; a variable takes its own reference (retain) and gives it back
// when reassigned or when its scope ends, by break, continue or return included. Stage 0 pays a
// retain and a release on every assignment for that simplicity; removing them where they cancel is
// the memory model's work, measured against this.
func C(program *ir.Program) string { return cProgram(program, -1, mainLines) }

func cProgram(program *ir.Program, handler, lines int) string {
	emitter := &emitter{program: program}
	if program.HasPromises() {
		// Suspension ownership is conservative until the shared analyses prove it.
		emitter.reuse = &reusePlan{}
		emitter.regions = &regionPlan{program: program}
	} else {
		elementBorrows, lending := planElementBorrows(program)
		emitter.elementBorrows = elementBorrows
		emitter.reuse = planReuse(program, lending)
		emitter.regions = planRegions(program)
	}
	var builder strings.Builder
	regexCallbacks, nodeHost := false, false
	// A void call whose targets are Unknown or disagree reads the closure's discard, which only a
	// program that makes a closure returning a reference needs: anywhere else every closure's is nothing.
	flaggedDiscard, referenceClosure := false, false
	walkExpressions(program, func(expression ir.Expression) {
		switch call := expression.(type) {
		case ir.RegExpCall:
			regexCallbacks = regexCallbacks || call.Replacement != nil
		case ir.NodeFSFile:
			nodeHost = nodeHost || strings.HasPrefix(call.Operation, "host_") || call.Operation == "mkdtemp" || call.Operation == "rm"
		case ir.CallClosure:
			flaggedDiscard = flaggedDiscard || call.Returns == 0 && program.ClosureDiscard(call) == ir.DiscardFlagged
		case ir.ArrayVisit:
			flaggedDiscard = flaggedDiscard || call.Method == "forEach" && call.Returns == 0 && program.ClosureDiscard(call) == ir.DiscardFlagged
		case ir.MapForEach:
			flaggedDiscard = flaggedDiscard || call.Returns == 0 && program.ClosureDiscard(call) == ir.DiscardFlagged
		case ir.MakeClosure:
			referenceClosure = referenceClosure || program.Functions[call.Function].Returns.IsReference()
		case ir.CollectionIterator:
			// Its next is a closure the runtime makes, whose IteratorResult comes back owned (map_set.c).
			referenceClosure = true
		}
	})
	emitter.closureDiscards = flaggedDiscard && referenceClosure
	if regexCallbacks {
		builder.WriteString("#define ADAMIC_REGEXP_REPLACE_CALLBACK 1\n")
	}
	if nodeHost {
		builder.WriteString("#define ADAMIC_NODE_HOST 1\n")
	}
	if program.ClosureReceiversNeeded() {
		builder.WriteString("#define ADAMIC_CLOSURE_RECEIVERS 1\n")
	}
	if program.CanonicalClosuresNeeded() || program.HasAsync() {
		builder.WriteString("#define ADAMIC_CANONICAL_CLOSURES 1\n")
	}
	if program.ClosureConventionNeeded() {
		builder.WriteString("#define ADAMIC_CLOSURE_CONVENTION 1\n")
	}
	if emitter.closureDiscards {
		builder.WriteString("#define ADAMIC_CLOSURE_DISCARDS 1\n")
	}
	fmt.Fprintf(&builder, "// Generated by adamic from %s. Do not edit.\n\n#include \"adamic.h\"\n\n#include <math.h>\n#include <stdbool.h>\n\n", program.Source)
	if program.HasPromises() {
		builder.WriteString("#include \"async.h\"\n#include <string.h>\n")
	}
	for index, value := range program.Strings {
		if len(value) <= longestLiteral {
			fmt.Fprintf(&builder, "static adamic_string adamic_string_%d = ADAMIC_STRING_UNITS(%s, %d);\n", index, cLiteral(value), utf16Units(value))
			continue
		}
		// Longer than a C string literal may be under -pedantic: its bytes as an array instead.
		fmt.Fprintf(&builder, "static const unsigned char adamic_bytes_%d[%d] = {%s};\n", index, len(value), cBytes(value))
		fmt.Fprintf(&builder, "static adamic_string adamic_string_%d = ADAMIC_STRING_BYTES_UNITS(adamic_bytes_%d, %d, %d);\n", index, index, len(value), utf16Units(value))
	}
	if len(program.Strings) > 0 {
		builder.WriteString("\n")
	}

	for _, regex := range program.Regexps {
		builder.WriteString(regex.Declarations)
	}
	globals := false
	for index, local := range program.Locals {
		if !local.Global {
			continue
		}
		globals = true
		fmt.Fprintf(&builder, "static %s %s = %s;\n", cType(local.Type), emitter.localName(index), zeroInitializer(local.Type))
		fmt.Fprintf(&builder, "static bool %s = false;\n", readyName(index))
		if local.Uninitialized {
			fmt.Fprintf(&builder, "static bool %s_declared = false;\n", readyName(index))
		}
	}
	if globals {
		builder.WriteString("\n")
	}

	// Bodies first: the shapes and field caches they use are found while they're emitted.
	bodies := strings.Builder{}
	for index, function := range program.Functions {
		if function.Async {
			bodies.WriteString(emitter.asyncFunction(index))
			continue
		}
		for _, inRegion := range emitter.regionVariants(index) {
			emitter.inRegion = inRegion
			fmt.Fprintf(&bodies, "static %s {\n", emitter.signature(index))
			emitter.indent = 1
			emitter.functionIndex = index
			emitter.functionBody(function)
			bodies.WriteString(emitter.out.String())
			emitter.out.Reset()
			bodies.WriteString("}\n\n")
		}
	}
	emitter.inRegion = false
	var parts []string
	if program.HasPromises() {
		// Promise modules stay in one part because a cut could cross the module frame's suspension.
		emitter.indent = 1
		emitter.asyncMain()
		emitter.block(program.Main, nil)
		if program.AsyncEntry == 0 {
			emitter.line("adamic_async_run();")
		}
		parts = []string{emitter.out.String()}
		emitter.out.Reset()
	} else {
		// main's top-level code, one statement at a time, as block emits it, so it can be cut into parts.
		emitter.indent = 1
		emitter.scopes = append(emitter.scopes, nil)
		statements := make([]string, 0, len(program.Main)+1)
		for index := range program.Main {
			emitter.statementAt(&program.Main[index])
			statements = append(statements, emitter.out.String())
			emitter.out.Reset()
		}
		emitter.releaseScopes(len(emitter.scopes) - 1)
		emitter.scopes = emitter.scopes[:len(emitter.scopes)-1]
		statements = append(statements, emitter.out.String())
		emitter.out.Reset()
		parts = mainParts(statements, lines)
	}
	if len(parts) > 1 {
		for index, part := range parts {
			fmt.Fprintf(&bodies, "static void adamic_main_%d(void) {\n%s}\n\n", index, part)
		}
	}
	bodies.WriteString("int main(int argc, char **argv) {\n")
	bodies.WriteString("\tadamic_start(argc, argv);\n")
	if len(parts) > 1 {
		for index := range parts {
			fmt.Fprintf(&bodies, "\tadamic_main_%d();\n", index)
		}
	} else {
		bodies.WriteString(parts[0])
	}
	if handler < 0 {
		emitter.releaseGlobals()
	}
	bodies.WriteString(emitter.out.String())
	emitter.out.Reset()
	bodies.WriteString("\treturn adamic_host_exit_status();\n}\n")
	if handler >= 0 {
		bodies.WriteString(emitter.requestABI(handler))
	}

	for index := range program.Functions {
		for _, inRegion := range emitter.regionVariants(index) {
			emitter.inRegion = inRegion
			if program.Functions[index].Closure {
				shape := "adamic_code_function"
				if program.PackedCountNeeded(index) {
					shape = "adamic_counted_code_function"
				}
				fmt.Fprintf(&builder, "static %s %s;\n", shape, emitter.functionName(index))
			} else {
				fmt.Fprintf(&builder, "static %s;\n", emitter.signature(index))
			}
		}
	}
	emitter.inRegion = false
	if len(program.Functions) > 0 {
		builder.WriteString("\n")
	}
	emitter.prepareClassShapes()
	// After the prototypes: a sort's comparator adapter calls one of the program's functions.
	for _, declaration := range emitter.declarations {
		builder.WriteString(declaration)
		builder.WriteString("\n")
	}
	if len(emitter.declarations) > 0 {
		builder.WriteString("\n")
	}
	emitter.classDeclarations(&builder)
	builder.WriteString(bodies.String())
	return builder.String()
}

// mainLines is about the most lines of C main's top-level code is given in one function. clang -O2
// spends time superlinear in a function's size once it passes about 12,500 lines, and every module's
// top-level code runs in main, so a long main is cut into parts that main calls in order
// (docs/tsc-generated-c.md). A part can be longer only by holding one statement that is.
const mainLines = 4000

// mainParts groups main's statements, each one top-level statement's C (the last what main's scope
// releases at its end), into parts of about lines lines, in order. A cut falls only between two
// statements that share no name either one declares: a local, a temporary or a label lives in the
// function that declares it, so one used past a cut would leave the part after it without it. Every
// statement's own names are within it, its temporaries released where it ends, except what main's
// scope holds, which the last statement releases, so that keeps whatever holds it in the last part.
// main's own parameters stay in main: a statement that reads them is never cut away.
func mainParts(statements []string, lines int) []string {
	total := 0
	for _, statement := range statements {
		total += strings.Count(statement, "\n")
	}
	if total <= lines {
		return []string{strings.Join(statements, "")}
	}
	// declared is the statement each name is declared in, first and last the first and last
	// statements that use each identifier.
	declared, first, last := map[string]int{}, map[string]int{}, map[string]int{}
	for index, statement := range statements {
		for _, line := range strings.Split(statement, "\n") {
			tokens, err := cTokens(line)
			if err != nil {
				// A literal or comment that spans lines isn't what the emitter writes: no cut.
				return []string{strings.Join(statements, "")}
			}
			for _, token := range tokens {
				if !identifierByte(token.text[0]) {
					continue
				}
				if _, seen := first[token.text]; !seen {
					first[token.text] = index
				}
				last[token.text] = index
				if _, seen := declared[token.text]; !seen && emittedLocal(token.text) {
					declared[token.text] = index
				}
			}
			if name := declaredName(line, tokens); name != "" {
				if _, seen := declared[name]; !seen {
					declared[name] = index
				}
			}
		}
	}
	// A name's span opens where it's first used, which only reaches back further than its
	// declaration for a label a goto names before it (adamic_done_N and its kin), whose own
	// statement would otherwise start the span and let a cut fall between the goto and the label.
	for name := range declared {
		declared[name] = first[name]
	}
	if _, read := last["argc"]; read {
		return []string{strings.Join(statements, "")}
	}
	if _, read := last["argv"]; read {
		return []string{strings.Join(statements, "")}
	}
	// held[index] says a name declared at or before statement index is used after it: each name
	// opens a span where it's declared and closes it where it's last used.
	spans := make([]int, len(statements)+1)
	for name, first := range declared {
		if last[name] > first {
			spans[first]++
			spans[last[name]]--
		}
	}
	held := make([]bool, len(statements))
	for index, open := 0, 0; index < len(statements); index++ {
		open += spans[index]
		held[index] = open > 0
	}
	parts := []string{}
	var part strings.Builder
	partLines := 0
	for index, statement := range statements {
		if statement == "" {
			continue
		}
		count := strings.Count(statement, "\n")
		if partLines > 0 && partLines+count > lines && !held[index-1] {
			parts = append(parts, part.String())
			part.Reset()
			partLines = 0
		}
		part.WriteString(statement)
		partLines += count
	}
	return append(parts, part.String())
}

// emittedLocal says a name is one the emitter gives only a function's own C variables: a temporary
// (labels among them) or a local that isn't a global. Each is unique in the program, so wherever it's
// first seen in main is where main declares it, however deep.
func emittedLocal(name string) bool {
	return strings.HasPrefix(name, "adamic_temporary_") || strings.HasPrefix(name, "adamic_local_")
}

// declaredName is the name a line of main declares, or "": a label (`name:;`, how the emitter writes
// every one), or a declaration at main's own depth, a type then the name, then `=`, `;` or `[`. A
// line that isn't a declaration may read as one (`return x;`), which only keeps a cut from falling
// where x is used on both sides of it.
func declaredName(line string, tokens []cToken) string {
	if len(tokens) == 3 && tokens[1].text == ":" && tokens[2].text == ";" && identifierByte(tokens[0].text[0]) {
		return tokens[0].text
	}
	for index, token := range tokens {
		switch token.text {
		case "(":
			return ""
		case "=", ";", "[":
			if index < 2 || !identifierByte(tokens[0].text[0]) || !identifierByte(tokens[index-1].text[0]) {
				return ""
			}
			if before := tokens[index-2].text; before != "*" && !identifierByte(before[0]) {
				return ""
			}
			if !strings.HasPrefix(line, "\t") || strings.HasPrefix(line, "\t\t") {
				// Inside a statement's own braces: its scope ends with it.
				return ""
			}
			return tokens[index-1].text
		}
	}
	return ""
}

// longestLiteral is the longest string literal C11 promises to compile (5.2.4.1: 4,095 characters),
// which clang holds a program to under -pedantic. A longer string is written as bytes (cBytes).
const longestLiteral = 4095

// cBytes is a string's bytes as an array initializer, as many as it has, with no terminator.
func cBytes(value string) string {
	var builder strings.Builder
	for index := 0; index < len(value); index++ {
		if index > 0 {
			builder.WriteString(",")
			if index%32 == 0 {
				builder.WriteString("\n\t")
			}
		}
		fmt.Fprintf(&builder, "%d", value[index])
	}
	return builder.String()
}

type emitter struct {
	counterModes      map[int]bool
	doubleCounterPath bool
	// objectMetadata holds program-wide facts for this emission, never another program.
	objectMetadata *objectMetadataNeeds
	program        *ir.Program
	out            strings.Builder
	indent         int

	// closureDiscards is ADAMIC_CLOSURE_DISCARDS: every closure made says how a void call lets go of
	// its result, for the calls whose targets are Unknown (discard).
	closureDiscards bool

	// reuse is where objects are reused in place (reuse.go), at names the statement being emitted,
	// where it stands in its slice, and taking is the spread whose replaced fields are being
	// evaluated, if any.
	reuse  *reusePlan
	at     *ir.Statement
	taking *taking

	// regions is where values are allocated in a statement's region (region.go). functionIndex is
	// the function being emitted, inRegion whether it's the version of a fresh function that makes
	// its result in a region, regionValues the C names of values known to be in one, statementRegion the C name of the region of the statement being
	// emitted, if it has one, regionCallDepth and regionCallArgument the depth of the call a parent
	// hands a region and that region, and regionLiteralDepth the depth of the object literal a fresh
	// function's return allocates in its region.
	regions            *regionPlan
	elementBorrows     map[*ir.Statement]bool
	mostlyNull         map[string]bool
	functionIndex      int
	inRegion           bool
	regionValues       map[string]bool
	statementRegion    string
	regionCallDepth    int
	regionCallArgument string
	regionLiteralDepth int

	// depth is how deep value is in the expression being emitted, lendAt the depth whose reads a
	// consumer lends without a count, lendable whether the expression being evaluated is one of
	// them, self whether its own value was lent, and lent whether one of the current expression's
	// operands was (borrow.go).
	depth    int
	lendAt   int
	lendable bool
	self     bool
	lent     bool

	// temporaries counts the C temporaries made so far, for unique names.
	temporaries int

	// owned is the string temporaries the statement being emitted releases when it ends.
	owned []string

	// scopes holds, innermost last, the references (C names) each open scope releases when it ends.
	scopes [][]string

	// loops holds, innermost last, each open loop's scope depth and continue label, and whether
	// anything jumps to that label.
	loops []*loop

	// breakables holds, innermost last, each open loop or switch and its cleanup depth.
	breakables []*breakable

	// declarations are file-scope lines the bodies need: object shapes and field caches.
	declarations []string

	// shapes names each object layout already declared, by its fields.
	shapes map[string]string
	// thunks are the methods whose adamic_method is declared (methodThunk).
	thunks map[int]bool

	// fieldOffsets proves uniform named slots across the program (fields.go).
	fieldOffsets map[string]int

	// initialized is every global main declares, in the order their declarations run: modules in
	// ECMAScript's order, and each module's from the top.
	initialized []int

	// handlers are the tries open in the function being emitted, innermost last, and outerOwned what
	// the statement owned outside each aside being emitted (exceptions.go).
	handlers   []*handler
	outerOwned [][]string

	// function is the function being emitted, and functionDepth the scope depth its body starts at.
	asyncSlots    map[int]int
	asyncBorrows  map[int]bool
	asyncHandler  string
	function      *ir.Function
	functionDepth int
}

func (e *emitter) line(format string, arguments ...any) {
	e.out.WriteString(strings.Repeat("\t", e.indent))
	fmt.Fprintf(&e.out, format, arguments...)
	e.out.WriteString("\n")
}

func (e *emitter) temporary() string {
	e.temporaries++
	return fmt.Sprintf("adamic_temporary_%d", e.temporaries)
}

// utf16Units is a literal's length in UTF-16 units, counted as the runtime counts it
// (string_index.c's adamic_string_units): a four-byte UTF-8 sequence is two units, any other one.
func utf16Units(value string) int {
	units := 0
	for offset := 0; offset < len(value); {
		lead := value[offset]
		size := 4
		switch {
		case lead < 0x80:
			size = 1
		case lead < 0xe0:
			size = 2
		case lead < 0xf0:
			size = 3
		}
		if size == 4 {
			units += 2
		} else {
			units++
		}
		offset += size
	}
	return units
}
