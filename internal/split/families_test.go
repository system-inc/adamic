package split_test

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"hash/fnv"
	"os"
	"path/filepath"
	"testing"
)

const oracleFixtureShards = 64

func oracleFixtureShard(path string) int {
	h := fnv.New64a()
	h.Write([]byte(filepath.ToSlash(path)))
	return int(h.Sum64() % oracleFixtureShards)
}

var updateSplitFamilies = flag.Bool("update-split-families", false, "regenerate split corpus wrappers")

// Not parallel: the update flag rewrites the checked-in family wrappers.
func TestSplitFamilyWrappersAreCurrent(t *testing.T) {
	var text bytes.Buffer
	fmt.Fprint(&text, "// Code generated by TestSplitFamilyWrappersAreCurrent; DO NOT EDIT.\npackage split_test\nimport \"testing\"\n")
	for _, family := range []struct{ name, runner string }{
		{"TestCodegenSnapshot", "runCodegenSnapshot"},
		{"TestAnalyzeOracleFixtures", "runAnalyzeOracleFixtures"},
	} {
		for i := 0; i < oracleFixtureShards; i++ {
			fmt.Fprintf(&text, "func %s_%03d(t *testing.T) { t.Parallel(); %s(t, %d) }\n", family.name, i, family.runner, i)
		}
	}
	source, err := format.Source(text.Bytes())
	if err != nil {
		t.Fatal(err)
	}
	const path = "families_generated_test.go"
	if *updateSplitFamilies {
		if err := os.WriteFile(path, source, 0644); err != nil {
			t.Fatal(err)
		}
	}
	actual, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(actual, source) {
		t.Fatal("regenerate with go test ./internal/split -run TestSplitFamilyWrappersAreCurrent -args -update-split-families")
	}
}
