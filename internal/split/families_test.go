package split_test

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"hash/fnv"
	"os"
	"path/filepath"
	"testing"
)

const oracleFixtureShards = 64

func oracleFixtureShard(path string) int {
	hash64 := fnv.New64a()
	hash64.Write([]byte(filepath.ToSlash(path)))
	return int(hash64.Sum64() % oracleFixtureShards)
}

var updateSplitFamilies = flag.Bool("update-split-families", false, "regenerate split corpus wrappers")

// Not parallel: the update flag rewrites the checked-in family wrappers.
func TestSplitFamilyWrappersAreCurrent(test *testing.T) {
	var text bytes.Buffer
	fmt.Fprint(
		&text,
		"// Code generated by TestSplitFamilyWrappersAreCurrent; DO NOT EDIT.\npackage split_test\nimport \"testing\"\n",
	)
	for _, family := range []struct{ name, runner string }{
		{"TestCodegenSnapshot", "runCodegenSnapshot"},
		{"TestAnalyzeOracleFixtures", "runAnalyzeOracleFixtures"},
	} {
		for index := 0; index < oracleFixtureShards; index++ {
			fmt.Fprintf(
				&text,
				"func %s_%03d(t *testing.T) { t.Parallel(); %s(t, %d) }\n",
				family.name,
				index,
				family.runner,
				index,
			)
		}
	}
	source, formatError := format.Source(text.Bytes())
	if formatError != nil {
		test.Fatal(formatError)
	}
	const path = "families_generated_test.go"
	if *updateSplitFamilies {
		if writeError := os.WriteFile(path, source, 0644); writeError != nil {
			test.Fatal(writeError)
		}
	}
	actual, readError := os.ReadFile(path)
	if readError != nil {
		test.Fatal(readError)
	}
	if !bytes.Equal(actual, source) {
		test.Fatal(
			"regenerate with go test ./internal/split -run TestSplitFamilyWrappersAreCurrent -args -update-split-families",
		)
	}
}
