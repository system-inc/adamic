package compilerinputs

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
)

var loweringRoots = []string{"./internal/load", "./internal/lower", "./internal/native", "./internal/javascript"}
var printerRoots = []string{"./internal/load", "./internal/lower", "./internal/native"}
var admissionRoots = []string{"./internal/load", "./internal/lower"}

// Generate derives each root set independently. The projections retain their
// existing directory coverage, but all use orderedSet's lexical order. No list of
// linked packages is maintained here: prefixes only coarsen paths actually derived.
func Generate(repositoryRoot string) (table, admissionFile []byte, err error) {
	var sets []inputSet
	for _, roots := range [][]string{loweringRoots, printerRoots, admissionRoots} {
		inputs, err := Derive(repositoryRoot, roots)
		if err != nil {
			return nil, nil, err
		}
		sets = append(sets, inputSet{orderedSet(roots), inputs})
	}
	var source bytes.Buffer
	fmt.Fprintln(&source, "// Code generated by go run ./internal/compilerinputs/generate; DO NOT EDIT.")
	fmt.Fprintln(&source, "package compilerinputs")
	writePaths := func(paths []string) {
		for _, path := range paths {
			fmt.Fprintf(&source, "%q,\n", path)
		}
	}
	fmt.Fprintln(&source, "var generatedInputs = []inputSet{")
	for _, set := range sets {
		fmt.Fprintln(&source, "{roots: []string{")
		writePaths(set.roots)
		fmt.Fprintln(&source, "}, inputs: []string{")
		writePaths(set.inputs)
		fmt.Fprintln(&source, "}},")
	}
	fmt.Fprintln(&source, "}")
	coarse := []string{"internal", "bridge/tsgo", "cohere/TypeScript-shim"}
	lowering := project(sets[0].inputs, coarse)
	markdown := project(sets[0].inputs, append(coarse, "cohere/TypeScript/tsc"))
	admission := project(append(sets[2].inputs, "cmd/adamic"), nil)
	for _, projection := range []struct {
		name  string
		paths []string
	}{
		{"lowering", lowering}, {"markdownblocks", markdown}, {"admission", admission},
	} {
		fmt.Fprintf(&source, "var %s = []string{\n", projection.name)
		writePaths(projection.paths)
		fmt.Fprintln(&source, "}")
	}
	table, err = format.Source(source.Bytes())
	if err != nil {
		return nil, nil, err
	}
	return table, admissionText(admission), nil
}

// project coarsens named directory prefixes and removes entries already covered
// by a parent. Removing overlap keeps each emitted input necessary to the key.
func project(inputs, prefixes []string) []string {
	var paths []string
	for _, input := range inputs {
		for _, prefix := range prefixes {
			if input == prefix || strings.HasPrefix(input, prefix+"/") {
				input = prefix
				break
			}
		}
		paths = append(paths, input)
	}
	var result []string
	for _, input := range orderedSet(paths) {
		covered := false
		for _, parent := range result {
			if strings.HasPrefix(input, parent+"/") {
				covered = true
				break
			}
		}
		if !covered {
			result = append(result, input)
		}
	}
	return result
}
