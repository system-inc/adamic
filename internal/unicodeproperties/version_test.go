package unicodeproperties

import (
	"os"
	"strings"
	"testing"
)

// Version is cohere's, and generate.go writes the strings and Canonicalize
// tables from that version's files, naming it on each one's first line. A
// cohere on a new Unicode leaves this red until they are regenerated from it.
func TestGeneratedTablesVersion(t *testing.T) {
	t.Parallel()
	for _, name := range []string{"tables.go", "canonicalize_tables.go"} {
		contents, err := os.ReadFile(name)
		if err != nil {
			t.Fatal(err)
		}
		if !strings.HasPrefix(string(contents), "// Code generated by generate.go from Unicode "+Version+". Do not edit.\n") {
			first, _, _ := strings.Cut(string(contents), "\n")
			t.Errorf("%s says %q, not cohere's Unicode %s", name, first, Version)
		}
	}
	if !strings.HasPrefix(Version, NodeUnicodeVersion+".") {
		t.Errorf("Version %s is not Node's Unicode %s", Version, NodeUnicodeVersion)
	}
}
