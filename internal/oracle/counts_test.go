// updateCounts rewrites counts.md with what was measured: go test ./internal/oracle -run TestCounts -args -update-counts
var updateCounts = flag.Bool("update-counts", false, "rewrite counts.md with the counts this run measured")

// countsPath is the checked-in table of every fixture's counts.
const countsPath = "counts.md"

// Extra counters register source witnesses that need an explicit frontend adapter, each a row of the table.
var additionalFixtureCounts []countCase

// A countCase is one row of counts.md: its key, the first column, and prepare, which readies the row: it returns what
// the row runs (the emitted C, and how an input fixture is run), which the row's digest is made of (countDigest), and
// measure, which builds that C counted, runs it and returns the row's counts.
type countCase struct {
	key     string
	prepare func(*testing.T) (runs string, measure func() string)
}

// countsIntroduction opens counts.md. The line naming the compiler the table was measured with (countsCompiler) comes
// after it, then countsTableHeader and the rows.
const countsIntroduction = `# Counts

Every oracle fixture, input fixtures included, built counted (` + "`adamic build --count`" + `, runtime/count.h) and run once. Counts are deterministic, so a
change to how Adamic counts references shows here as a change of numbers, in review. Allocations and frees are heap values (strings,
objects, arrays, maps, cells, closures); retains and releases are calls to adamic_retain and adamic_release; peak is the most heap
values live at once; in regions is the values let go of with their region (runtime/region.c) rather than freed one at a time, so a
finished program's allocations are its frees and its values in regions. A fixture that panics is counted where it stopped; an input
fixture runs as TestInputAgreesWithNode runs it, a directory of its own to write in included, and must finish. Every run has an
8 MiB stack (ulimit -s 8192), so a fixture's counts never depend on the stack of whoever runs it. This is the baseline borrow
inference and reuse in place are measured against (docs/memory.md).

Not counted, though the oracle runs it as it runs every fixture: internal/oracle/testdata/stack_overflow.a, which recurses until
the stack runs out, so its allocations measure how deep it got, and every change to a frame's size moves them.

Each row's digest is what it runs: its emitted C with the checkout's paths left out, how an input fixture is run and the files it
reads, the runtime's sources and the counted build's flags, the same on every machine and in every tree. A run measures a row when
its digest isn't the one recorded (a change touched it), when the row is in a fixed sample of about 1 in 10 (countsSampleSeed),
and every row when its clang isn't the one named below. Any other row runs what its counts were measured from, and counts are
deterministic, so it holds without a build.

Generated by TestCountsAreRecorded; after a change that moves them, or moves what a row runs, run
` + "`go test ./internal/oracle -run TestCountsAreRecorded -args -update-counts`" + ` on the gate's toolchain and commit the diff.

`

// countsTableHeader opens the table, after the compiler line.
const countsTableHeader = `| Fixture | Allocations | Frees | Retains | Releases | Peak live | In regions | Digest |
|---|---:|---:|---:|---:|---:|---:|---|
`

// countsCompilerLine is the line naming the clang the table was measured with, between the introduction and the table.
var countsCompilerLine = regexp.MustCompile("(?m)^Measured with `([^`\n]+)`\\.$")

// countsCompiler is the first line of the clang a counted build runs' --version: what the table was measured with, when
// -update-counts writes it. Where the clang isn't that one (a toolchain bump, or a Mac's clang), every row is measured.
var countsCompiler = sync.OnceValues(func() (string, error) {
	version, err := toolchain.Command("clang", "--version").Output()
	if err != nil {
		return "", fmt.Errorf("clang --version: %w", err)
	}
	line, _, _ := strings.Cut(string(version), "\n")
	return strings.TrimSpace(line), nil
})

// countsSampleSeed seeds the fixed tenth of rows every run measures whatever their digests say (countSampled). Changing it
// picks another tenth.
const countsSampleSeed = "counts-sample-v1"

// countSampled is whether the row keyed key is in the fixed sample: the first byte of the sha256 of the seed and the key
// under 26 of 256, the same rows on every run and every machine, about 1 in 10.
func countSampled(key string) bool {
	return cacheKey(countsSampleSeed, key)[:2] < "1a"
}

// countsHarness is how a row is built and run beyond what it runs (counted, interfaceCastCounted, pinnedStack): bump it
// when that changes, and every row's digest moves with it.
const countsHarness = "counts-harness-v1"

// countsShared is what every row's digest reads besides the row's own: the harness, the runtime's sources and the
// counted build's flags, none of them spelled by the machine.
var countsShared = sync.OnceValues(func() (string, error) {
	runtime, err := native.RuntimeSourceDigest()
	if err != nil {
		return "", err
	}
	return cacheKey(countsHarness, runtime, strings.Join(native.Flags(native.Options{Count: true}), " ")), nil
})

// countPortable is emitted C as every checkout spells it, for a row's digest: the TypeScript frontend names its source
// file by its absolute path in what a failed non-null assertion says (non_null_boolean.ts:3:17), and a scratch copy's
// path is a temporary directory, so the source file's path becomes <source> and the repository's becomes <repository>.
func countPortable(t *testing.T, source string, absolute string) string {
	t.Helper()
	root, err := filepath.Abs(repository)
	if err != nil {
		t.Fatal(err)
	}
	if absolute != "" {
		source = strings.ReplaceAll(source, absolute, "<source>")
	}
	return strings.ReplaceAll(source, root, "<repository>")
}

// countInputs is the trees an input fixture reads as it runs (inputIdentity's, testdata/reading and testdata/walking)
// as every checkout holds them, for an input row's digest: each entry by its path from the repository, what it is (a
// directory, a file, executable or not, or a link and its target) and a file by the sha256 of what it holds. Nothing
// else of its mode: a checkout's umask spells the rest, and git keeps only the executable bit.
var countInputs = sync.OnceValues(func() (string, error) {
	parts := []string{"count-inputs-v1"}
	for _, name := range []string{"reading", "walking"} {
		err := filepath.WalkDir(filepath.Join(repository, "internal", "oracle", "testdata", name), func(path string, entry os.DirEntry, err error) error {
			if err != nil {
				return err
			}
			relative, err := filepath.Rel(repository, path)
			if err != nil {
				return err
			}
			info, err := os.Lstat(path)
			if err != nil {
				return err
			}
			switch {
			case info.Mode()&os.ModeSymlink != 0:
				target, err := os.Readlink(path)
				if err != nil {
					return err
				}
				parts = append(parts, "link "+filepath.ToSlash(relative)+" "+target)
			case info.IsDir():
				parts = append(parts, "directory "+filepath.ToSlash(relative))
			default:
				contents, err := os.ReadFile(path)
				if err != nil {
					return err
				}
				parts = append(parts, fmt.Sprintf("file %s executable %v %x", filepath.ToSlash(relative), info.Mode()&0o111 != 0, sha256.Sum256(contents)))
			}
			return nil
		})
		if err != nil {
			return "", err
		}
	}
	return cacheKey(parts...), nil
})

// countDigestCell is a row's last cell: its digest, then the row's end.
var countDigestCell = regexp.MustCompile(`^[0-9a-f]{16} \|$`)

// countDigest is the digest of the row keyed key that runs runs, as its last column holds it.
func countDigest(t *testing.T, key string, runs string) string {
	t.Helper()
	shared, err := countsShared()
	if err != nil {
		t.Fatal(err)
	}
	return cacheKey(shared, key, runs)[:16]
}

// countsLine is the line a counted build writes last to stderr (runtime/count.c).
var countsLine = regexp.MustCompile(`(?m)^adamic: counts: allocations (\d+) frees (\d+) retains (\d+) releases (\d+) peak (\d+) regions (\d+)\n\z`)

// pinnedStack is a command run with an 8 MiB stack, whatever the stack of whoever runs the test: a
// fixture that recurses until the stack runs out is counted at the depth it reached, which moves with
// the stack's size (ulimit -s), and the table has to be the same on every machine. The shell's ulimit
// is POSIX's, on Linux and macOS alike; where the hard limit won't allow 8 MiB, it fails out loud.
func pinnedStack(name string, arguments ...string) (string, []string) {
	return "/bin/sh", append([]string{"-c", `ulimit -s 8192 && exec "$0" "$@"`, name}, arguments...)
}

// uncounted is the fixtures the table leaves out, each for the reason the table's header gives: a
// count that measures something other than counting.
var uncounted = map[string]bool{
	"internal/oracle/testdata/stack_overflow.a": true,
}

// counted lowers a fixture and returns what its row runs, the emitted C and how it is run, and measure, which builds
// that C counted, runs it, and returns its row of the table. An input fixture runs as TestInputAgreesWithNode runs it:
// from its own directory, with its arguments, a directory of its own to write in when it writes, and as nobody when the
// test is root. It must finish, as it must there, so its row counts the whole program and not where it stopped.
func counted(t *testing.T, path string, input bool, arguments []string, unreadable bool, writes bool) (string, func() string) {
	t.Helper()
	absolute, err := filepath.Abs(filepath.Join(repository, path))
	if err != nil {
		t.Fatal(err)
	}
	program, err := lowered(t, absolute)
	if err != nil {
		t.Fatalf("Lower: %v", err)
	}
	source := native.C(program)
	runs := fmt.Sprintf("input %v arguments %q unreadable %v writes %v\n%s", input, arguments, unreadable, writes, countPortable(t, source, absolute))
	if input {
		inputs, err := countInputs()
		if err != nil {
			t.Fatal(err)
		}
		runs = "inputs " + inputs + "\n" + runs
	}
	return runs, func() string { return countedRun(t, path, absolute, source, input, arguments, unreadable, writes) }
}

// countedRun builds counted's source counted, runs it, and returns its row.
func countedRun(t *testing.T, path string, absolute string, source string, input bool, arguments []string, unreadable bool, writes bool) string {
	t.Helper()
	given := identity(t)
	context := cacheKey(given.context, path, fmt.Sprint(input, unreadable, writes), cacheKey(arguments...))
	if input {
		context = cacheKey(context, inputIdentity(t))
	}
	key := nativeResultKey(source, given.libraries[2], given.nodeVersion, context)
	executeCounted := func() recordedRun {
		var result run
		if input {
			shared := sharedDirectory(t)
			how := inputRun{directory: filepath.Dir(absolute), arguments: arguments}
			if os.Geteuid() == 0 {
				how.credential = &syscall.Credential{Uid: 65534, Gid: 65534}
			}
			if unreadable {
				path := filepath.Join(shared, "unreadable.txt")
				if err := os.WriteFile(path, []byte("secret\n"), 0o000); err != nil {
					t.Fatal(err)
				}
				how.arguments = append(append([]string{}, how.arguments...), path)
			}
			if writes {
				how.arguments = append([]string{writable(t, shared, "counted")}, how.arguments...)
			}
			if strings.HasPrefix(path, "internal/oracle/testdata/node_fs_file_") {
				how = fsFilePrepare(t, shared, "counted")
			}
			binary := filepath.Join(shared, "program")
			if err := native.Build(source, binary, native.Options{Count: true}); err != nil {
				t.Fatal(err)
			}
			name, pinned := pinnedStack(binary, how.arguments...)
			result = executeInput(t, how, nil, name, pinned...)
			if result.exitCode != 0 {
				t.Fatalf("want an input fixture's counted run to finish, as TestInputAgreesWithNode wants it to on Node: exit %d, stderr %q", result.exitCode, result.stderr)
			}
		} else {
			binary := filepath.Join(t.TempDir(), "program")
			if err := native.Build(source, binary, native.Options{Count: true}); err != nil {
				t.Fatal(err)
			}
			name, pinned := pinnedStack(binary)
			result = execute(t, name, pinned...)
		}
		return record(result)
	}
	var result run
	if *updateCounts {
		result = executeCounted().run()
	} else {
		result = cachedResult(t, given.cache, nativeResults, key, executeCounted).run()
	}
	match := countsLine.FindSubmatch(result.stderr)
	if match == nil {
		t.Fatalf("no counts at the end of stderr (exit %d): %q", result.exitCode, result.stderr)
	}
	return fmt.Sprintf("| %s | %s | %s | %s | %s | %s | %s |", path, match[1], match[2], match[3], match[4], match[5], match[6])
}

// countCases is every row of counts.md, in the table's order: the lowered fixtures, the input fixtures, the
// node:fs file fixtures, the interface casts, then each extra counter, as registered.
func countCases() []countCase {
	var cases []countCase
	for _, fixture := range fixtures {
		if fixture.lowers && !uncounted[fixture.path] && !refusedAdamicNonNullFixture(fixture.path) {
			cases = append(cases, countCase{fixture.path, func(t *testing.T) (string, func() string) { return counted(t, fixture.path, false, nil, false, false) }})
		}
	}
	for _, fixture := range inputFixtures {
		cases = append(cases, countCase{fixture.path, func(t *testing.T) (string, func() string) {
			return counted(t, fixture.path, true, fixture.arguments, fixture.unreadable, fixture.writes)
		}})
	}
	for _, fixture := range fsFileFixtures {
		path := "internal/oracle/testdata/node_fs_file_" + fixture + ".a"
		cases = append(cases, countCase{path, func(t *testing.T) (string, func() string) { return counted(t, path, true, nil, false, false) }})
	}
	cases = append(cases, interfaceCastCountCases()...)
	return append(cases, additionalFixtureCounts...)
}

// countKeys is every row's key, the key TestCountsAreRecorded's family (families_test.go) owns it by.
func countKeys() []string {
	cases := countCases()
	keys := make([]string, len(cases))
	for index, each := range cases {
		keys[index] = each.key
	}
	return keys
}

// A countsTable is counts.md as recorded: its rows by key, and the compiler it was measured with.
type countsTable struct {
	rows     map[string]string
	compiler string
}

// recordedCounts is counts.md as recorded, read once for every shard in the process.
var recordedCounts = sync.OnceValues(func() (countsTable, error) {
	recorded, err := os.ReadFile(countsPath)
	if err != nil {
		return countsTable{}, err
	}
	table := countsTable{rows: map[string]string{}}
	if match := countsCompilerLine.FindSubmatch(recorded); match != nil {
		table.compiler = string(match[1])
	}
	for _, line := range strings.Split(string(recorded), "\n") {
		if fields := strings.Split(line, " | "); len(fields) == 8 {
			table.rows[strings.TrimPrefix(fields[0], "| ")] = line
		}
	}
	return table, nil
})

// measuredCounts is the rows this run measured under -update-counts, for TestMain to write.
var measuredCounts sync.Map

// measuredPredicateCounts is the predicate table TestCountsAreRecordedTable measured under -update-counts.
var measuredPredicateCounts sync.Map

// TestCountsAreRecorded is a family (families_test.go): TestCountsAreRecorded_000 and on each hold the rows their
// shard owns to their rows in counts.md, so a change to a fixture's counts, or to what it runs, fails until the table is
// updated. A row is measured when its digest isn't the recorded one, when it is sampled (countSampled), or when this
// clang isn't the table's; any other row runs what its counts were measured from and holds without a build. Under
// -update-counts they measure every row, and TestMain writes the table.
func runCountsShard(t *testing.T, shard int) {
	t.Helper()
	planted, probing := familyProbe("TestCountsAreRecorded")
	cases := countCases()
	keys := countKeys()
	for _, index := range familyCases(t, "TestCountsAreRecorded", shard, keys) {
		each := cases[index]
		t.Run(each.key, func(t *testing.T) {
			t.Parallel()
			runs, measure := each.prepare(t)
			digest := countDigest(t, each.key, runs)
			if *updateCounts {
				measuredCounts.Store(each.key, measure()+" "+digest+" |")
				return
			}
			recorded, err := recordedCounts()
			if err != nil {
				t.Fatalf("%v: record the counts with -update-counts", err)
			}
			compiler, err := countsCompiler()
			if err != nil {
				t.Fatal(err)
			}
			want := recorded.rows[each.key]
			fields := strings.Split(want, " | ")
			touched := len(fields) != 8 || strings.TrimSuffix(fields[7], " |") != digest
			if probing && each.key == planted {
				// TestFamiliesCatchAPlantedCase's mutant: the row as recorded, one allocation more, measured whatever its
				// digest says.
				if len(fields) == 8 {
					allocations, _ := strconv.Atoi(fields[1])
					fields[1] = strconv.Itoa(allocations + 1)
					want = strings.Join(fields, " | ")
				}
				touched = true
			}
			if !touched && !countSampled(each.key) && compiler == recorded.compiler {
				t.Logf("held without a build: not sampled, and it runs what its counts were measured from (digest %s)", digest)
				return
			}
			if row := measure() + " " + digest + " |"; row != want {
				t.Errorf("the counts changed, or what the row runs did, and %s wasn't updated with them (go test ./internal/oracle -run TestCountsAreRecorded -count=1 -args -update-counts):\nrecorded: %s\nmeasured: %s",
					countsPath, want, row)
			}
		})
	}
}

// The table is whole: the header, then exactly one row per count case in countCases' order, then the predicate table,
// which TestPredicateDirectionCountsAreRecorded holds to its measure. With each shard holding its rows to their
// measures, that is the whole file, as one comparison of it once was. Under -update-counts it measures the predicate
// table instead, for TestMain to write.
func TestCountsAreRecordedTable(t *testing.T) {
	t.Parallel()
	if *updateCounts {
		measuredPredicateCounts.Store(countsPath, predicateCountsTable(t))
		return
	}
	recorded, err := os.ReadFile(countsPath)
	if err != nil {
		t.Fatalf("%v: record the counts with -update-counts", err)
	}
	body, found := strings.CutPrefix(string(recorded), countsIntroduction)
	if !found {
		t.Fatalf("%s doesn't start with the table's introduction", countsPath)
	}
	line, body, found := strings.Cut(body, "\n\n")
	match := countsCompilerLine.FindStringSubmatch(line)
	if !found || match == nil || match[0] != line {
		t.Fatalf("%s names no compiler after its introduction: %q", countsPath, line)
	}
	if compiler, err := countsCompiler(); err != nil {
		t.Fatal(err)
	} else if compiler != match[1] {
		t.Logf("%s was measured with %s and this clang is %s, so every row is measured", countsPath, match[1], compiler)
	}
	body, found = strings.CutPrefix(body, countsTableHeader)
	if !found {
		t.Fatalf("%s's table doesn't start with its header", countsPath)
	}
	rows, _, found := strings.Cut(body, predicateCountsHeader)
	if !found {
		t.Fatalf("%s has no predicate direction table after its rows", countsPath)
	}
	lines := strings.Split(strings.TrimSuffix(rows, "\n"), "\n")
	keys := countKeys()
	for index := range max(len(lines), len(keys)) {
		line, key := "", ""
		if index < len(lines) {
			line = lines[index]
		}
		if index < len(keys) {
			key = keys[index]
		}
		if fields := strings.Split(line, " | "); len(fields) != 8 || strings.TrimPrefix(fields[0], "| ") != key || !countDigestCell.MatchString(fields[7]) {
			t.Fatalf("%s row %d is %q, want the row of %q (go test ./internal/oracle -run TestCountsAreRecorded -count=1 -args -update-counts)", countsPath, index+1, line, key)
		}
	}
}

// writeCounts writes counts.md from the rows this run measured under -update-counts, keeping each row it didn't
// measure as recorded, in countCases' order, and the predicate table measured or as recorded. It refuses a run that
// measured no row, such as one selected with an anchored ^TestCountsAreRecorded$, which names no test now.
func writeCounts() error {
	recorded, err := recordedCounts()
	if err != nil {
		recorded = countsTable{rows: map[string]string{}}
	}
	compiler, err := countsCompiler()
	if err != nil {
		return err
	}
	var table strings.Builder
	table.WriteString(countsIntroduction)
	table.WriteString("Measured with `" + compiler + "`.\n\n")
	table.WriteString(countsTableHeader)
	measured := 0
	for _, key := range countKeys() {
		row, ok := measuredCounts.Load(key)
		if ok {
			measured++
		} else if row, ok = recorded.rows[key]; !ok {
			return fmt.Errorf("no row for %s: measure it with go test ./internal/oracle -run TestCountsAreRecorded -count=1 -args -update-counts", key)
		}
		table.WriteString(row.(string))
		table.WriteString("\n")
	}
	if measured == 0 {
		return fmt.Errorf("-update-counts measured no row of %s: select the shards with -run TestCountsAreRecorded, unanchored", countsPath)
	}
	predicates, ok := measuredPredicateCounts.Load(countsPath)
	if !ok {
		file, err := os.ReadFile(countsPath)
		if err != nil {
			return err
		}
		index := strings.Index(string(file), predicateCountsHeader)
		if index < 0 {
			return fmt.Errorf("%s has no predicate direction table to keep", countsPath)
		}
		predicates = string(file[index:])
	}
	table.WriteString(predicates.(string))
	return os.WriteFile(countsPath, []byte(table.String()), 0o644)
}
