package flow

import (
	"bytes"
	"context"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"testing"
	"time"
)

var corpusGeneratedFiles = []string{
	"internal/flow/corpus_units_test.go",
	"internal/fresh/corpus_units_test.go",
	"review/test-split-flow/units.json",
}

// Compare in a fixed order and report the first differing byte's line, including
// an extra suffix or a missing final newline.
func compareCorpusGeneratedBytes(wantRoot, gotRoot string) error {
	for _, name := range corpusGeneratedFiles {
		want, err := os.ReadFile(filepath.Join(wantRoot, name))
		if err != nil {
			return err
		}
		got, err := os.ReadFile(filepath.Join(gotRoot, name))
		if err != nil {
			return err
		}
		if bytes.Equal(want, got) {
			continue
		}
		index := 0
		for index < len(want) && index < len(got) && want[index] == got[index] {
			index++
		}
		line := bytes.Count(want[:index], []byte{'\n'}) + 1
		return fmt.Errorf("%s:%d: generated bytes differ", name, line)
	}
	return nil
}

func TestCorpusGeneratedBytes(t *testing.T) {
	t.Parallel()
	python, err := exec.LookPath("python3")
	if err != nil {
		t.Skipf("corpus generation requires python3: %v", err)
	}
	if _, err := exec.LookPath("gofmt"); err != nil {
		t.Skipf("corpus generation requires gofmt: %v", err)
	}
	root, err := filepath.Abs("../..")
	if err != nil {
		t.Fatal(err)
	}
	generate := func() string {
		directory := t.TempDir()
		ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
		defer cancel()
		command := exec.CommandContext(ctx, python, filepath.Join(root, "review/test-split-flow/generate.py"), "--out", directory)
		command.Dir = root
		if output, err := command.CombinedOutput(); err != nil {
			t.Fatalf("generate corpus: %v\n%s", err, output)
		}
		return directory
	}
	first, second := generate(), generate()
	if err := compareCorpusGeneratedBytes(first, second); err != nil {
		t.Fatalf("consecutive generator runs: %v", err)
	}
	for _, edited := range corpusGeneratedFiles {
		t.Run(edited, func(t *testing.T) {
			mutant := t.TempDir()
			for _, name := range corpusGeneratedFiles {
				contents, err := os.ReadFile(filepath.Join(first, name))
				if err != nil {
					t.Fatal(err)
				}
				path := filepath.Join(mutant, name)
				if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
					t.Fatal(err)
				}
				if err := os.WriteFile(path, contents, 0644); err != nil {
					t.Fatal(err)
				}
			}
			if err := compareCorpusGeneratedBytes(first, mutant); err != nil {
				t.Fatalf("unedited copy: %v", err)
			}
			path := filepath.Join(mutant, edited)
			contents, err := os.ReadFile(path)
			if err != nil {
				t.Fatal(err)
			}
			index := len(contents) / 2
			line := bytes.Count(contents[:index], []byte{'\n'}) + 1
			contents[index] ^= 1
			if err := os.WriteFile(path, contents, 0644); err != nil {
				t.Fatal(err)
			}
			want := fmt.Sprintf("%s:%d: generated bytes differ", edited, line)
			if err := compareCorpusGeneratedBytes(first, mutant); err == nil || err.Error() != want {
				t.Fatalf("one-byte edit: got %v, want %s", err, want)
			}
			t.Logf("caught one-byte edit: %s", want)
		})
	}
	if err := compareCorpusGeneratedBytes(first, root); err != nil {
		t.Fatal(err)
	}
}
