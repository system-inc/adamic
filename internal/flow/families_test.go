type flowFamily struct {
	name, runner string
	shards       int
	product      bool
}

var flowFamilies = []flowFamily{
	{"TestFlowCorpusRemainder", "runFlowCorpusRemainderShard", 32, false},
	{"TestProduct_FlowCorpusRemainder", "runFlowCorpusRemainderProductsShard", 32, true},
}

// Preserve the old remainder's set: every runnable program not already covered
// by a generated corpus unit or an async unit. No assertions are cached.
func flowCorpusRemainderPaths(test *testing.T) []string {
	test.Helper()
	generated := map[string]bool{}
	for _, path := range flowCorpusPaths {
		generated[path] = true
	}
	for _, unit := range asyncFlowUnits {
		generated[unit.path] = true
	}
	var paths []string
	for _, path := range programs(test) {
		if !generated[filepath.ToSlash(path)] {
			paths = append(paths, path)
		}
	}
	return paths
}

func flowFamilyOwns(shard int, path string) bool {
	h := fnv.New64a()
	h.Write([]byte(filepath.ToSlash(path)))
	return int(h.Sum64()%uint64(flowFamilies[0].shards)) == shard
}

func flowCorpusRemainderShardPaths(test *testing.T, shard int) []string {
	test.Helper()
	var paths []string
	for _, path := range flowCorpusRemainderPaths(test) {
		if flowFamilyOwns(shard, path) {
			paths = append(paths, path)
		}
	}
	return paths
}

func runFlowCorpusRemainderShard(test *testing.T, shard int) {
	beginFlowUnit(test)
	paths := flowCorpusRemainderShardPaths(test, shard)
	for _, path := range paths {
		test.Run(filepath.ToSlash(path), func(test *testing.T) {
			// Only lowering is a product. Build/Construct and all three independent
			// Node observations still run through the same four checks as before.
			installFlowCorpusRemainderProduct(test, path)
			checkAllFlowProgram(test, path)
		})
	}
	test.Logf("remainder ran %d programs", len(paths))
}

func TestFlowCorpusRemainderFamiliesCoverEveryProgramOnce(test *testing.T) {
	test.Parallel()
	// Reconstruct the original set independently of the shard assignment.
	generated := map[string]bool{}
	for _, path := range flowCorpusPaths {
		generated[path] = true
	}
	for _, unit := range asyncFlowUnits {
		generated[unit.path] = true
	}
	want := map[string]bool{}
	for _, path := range programs(test) {
		path = filepath.ToSlash(path)
		if !generated[path] {
			want[path] = true
		}
	}
	seen := map[string]int{}
	counts := make([]int, flowFamilies[0].shards)
	for shard := range counts {
		for _, path := range flowCorpusRemainderShardPaths(test, shard) {
			path = filepath.ToSlash(path)
			if !want[path] {
				test.Fatalf("unexpected remainder program %s", path)
			}
			seen[path]++
			counts[shard]++
		}
	}
	for path := range want {
		if seen[path] != 1 {
			test.Errorf("%s has %d owners, want 1", path, seen[path])
		}
	}
	if flowFamilies[1].shards != len(counts) {
		test.Fatal("product and behavior shards differ")
	}
	test.Logf("%d remainder programs; programs per shard=%v", len(want), counts)
}

var updateFlowFamilyWrappers = flag.Bool("update-flow-family-wrappers", false, "regenerate families_generated_test.go")

func flowFamilyWrappers(test *testing.T) []byte {
	test.Helper()
	var text bytes.Buffer
	fmt.Fprint(
		&text,
		"// Code generated by TestFlowFamilyWrappersAreCurrent; DO NOT EDIT.\n// go test ./internal/flow -run '^TestFlowFamilyWrappersAreCurrent$' -args -update-flow-family-wrappers\n\npackage flow\n\nimport \"testing\"\n",
	)
	for _, f := range flowFamilies {
		for shard := 0; shard < f.shards; shard++ {
			if f.product {
				fmt.Fprint(&text, "\n// Not parallel: lowering products share compiler inputs.\n")
			}
			fmt.Fprintf(&text, "func %s_%03d(t *testing.T) {\n", f.name, shard)
			if !f.product {
				fmt.Fprint(&text, "t.Parallel()\n")
			}
			fmt.Fprintf(&text, "%s(t, %d)\n}\n", f.runner, shard)
		}
	}
	source, err := format.Source(text.Bytes())
	if err != nil {
		test.Fatal(err)
	}
	return source
}

// Not parallel: the update flag rewrites the checked-in family wrappers.
func TestFlowFamilyWrappersAreCurrent(test *testing.T) {
	want := flowFamilyWrappers(test)
	if *updateFlowFamilyWrappers {
		if err := os.WriteFile("families_generated_test.go", want, 0644); err != nil {
			test.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile("families_generated_test.go")
	if err != nil || !bytes.Equal(got, want) {
		test.Fatal("Flow wrappers stale; run with -update-flow-family-wrappers", err)
	}
}
