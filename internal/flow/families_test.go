type flowFamily struct {
	name, runner string
	shards       int
	product      bool
}

var flowFamilies = []flowFamily{
	{"TestFlowCorpusRemainder", "runFlowCorpusRemainderShard", 32, false},
	{"TestProduct_FlowCorpusRemainder", "runFlowCorpusRemainderProductsShard", 32, true},
}

// Preserve the old remainder's set: every runnable program not already covered
// by a generated corpus unit or an async unit. No assertions are cached.
func flowCorpusRemainderPaths(t *testing.T) []string {
	t.Helper()
	generated := map[string]bool{}
	for _, path := range flowCorpusPaths {
		generated[path] = true
	}
	for _, unit := range asyncFlowUnits {
		generated[unit.path] = true
	}
	var paths []string
	for _, path := range programs(t) {
		if !generated[filepath.ToSlash(path)] {
			paths = append(paths, path)
		}
	}
	return paths
}

func flowFamilyOwns(shard int, path string) bool {
	h := fnv.New64a()
	h.Write([]byte(filepath.ToSlash(path)))
	return int(h.Sum64()%uint64(flowFamilies[0].shards)) == shard
}

func flowCorpusRemainderShardPaths(t *testing.T, shard int) []string {
	t.Helper()
	var paths []string
	for _, path := range flowCorpusRemainderPaths(t) {
		if flowFamilyOwns(shard, path) {
			paths = append(paths, path)
		}
	}
	return paths
}

func runFlowCorpusRemainderShard(t *testing.T, shard int) {
	beginFlowUnit(t)
	paths := flowCorpusRemainderShardPaths(t, shard)
	for _, path := range paths {
		t.Run(filepath.ToSlash(path), func(t *testing.T) {
			// Only lowering is a product. Build/Construct and all three independent
			// Node observations still run through the same four checks as before.
			installFlowCorpusRemainderProduct(t, path)
			checkAllFlowProgram(t, path)
		})
	}
	t.Logf("remainder ran %d programs", len(paths))
}

func TestFlowCorpusRemainderFamiliesCoverEveryProgramOnce(t *testing.T) {
	t.Parallel()
	// Reconstruct the original set independently of the shard assignment.
	generated := map[string]bool{}
	for _, path := range flowCorpusPaths {
		generated[path] = true
	}
	for _, unit := range asyncFlowUnits {
		generated[unit.path] = true
	}
	want := map[string]bool{}
	for _, path := range programs(t) {
		path = filepath.ToSlash(path)
		if !generated[path] {
			want[path] = true
		}
	}
	seen := map[string]int{}
	counts := make([]int, flowFamilies[0].shards)
	for shard := range counts {
		for _, path := range flowCorpusRemainderShardPaths(t, shard) {
			path = filepath.ToSlash(path)
			if !want[path] {
				t.Fatalf("unexpected remainder program %s", path)
			}
			seen[path]++
			counts[shard]++
		}
	}
	for path := range want {
		if seen[path] != 1 {
			t.Errorf("%s has %d owners, want 1", path, seen[path])
		}
	}
	if flowFamilies[1].shards != len(counts) {
		t.Fatal("product and behavior shards differ")
	}
	t.Logf("%d remainder programs; programs per shard=%v", len(want), counts)
}

var updateFlowFamilyWrappers = flag.Bool("update-flow-family-wrappers", false, "regenerate families_generated_test.go")

func flowFamilyWrappers(t *testing.T) []byte {
	t.Helper()
	var text bytes.Buffer
	fmt.Fprint(&text, "// Code generated by TestFlowFamilyWrappersAreCurrent; DO NOT EDIT.\n// go test ./internal/flow -run '^TestFlowFamilyWrappersAreCurrent$' -args -update-flow-family-wrappers\n\npackage flow\n\nimport (\"encoding/gob\"; \"testing\"\n\n\"github.com/system-inc/adamic/internal/ir\")\n")
	for _, f := range flowFamilies {
		for shard := 0; shard < f.shards; shard++ {
			if f.product {
				fmt.Fprint(&text, "\n// Not parallel: lowering products share compiler inputs.\n")
			}
			fmt.Fprintf(&text, "func %s_%03d(t *testing.T) {\n", f.name, shard)
			if !f.product {
				fmt.Fprint(&text, "t.Parallel()\n")
			}
			fmt.Fprintf(&text, "%s(t, %d)\n}\n", f.runner, shard)
		}
	}
	// Gob must know concrete interface types even in a process that only reads
	// products. Enumerate the IR's Expression and Statement implementations, as
	// irExpressions already does for writes coverage, rather than keep a manual list.
	names := irExpressions(t)
	paths, err := filepath.Glob("../ir/*.go")
	if err != nil {
		t.Fatal(err)
	}
	for _, path := range paths {
		if strings.HasSuffix(path, "_test.go") {
			continue
		}
		file, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
		if err != nil {
			t.Fatal(err)
		}
		for _, decl := range file.Decls {
			method, ok := decl.(*ast.FuncDecl)
			if !ok || method.Recv == nil || method.Name.Name != "statement" {
				continue
			}
			receiver, ok := method.Recv.List[0].Type.(*ast.Ident)
			if !ok {
				t.Fatal("IR statement receiver is no longer a value type")
			}
			names[receiver.Name] = true
		}
	}
	ordered := make([]string, 0, len(names))
	for name := range names {
		ordered = append(ordered, name)
	}
	slices.Sort(ordered)
	fmt.Fprint(&text, "\nfunc registerFlowCorpusIR() {\nflowCorpusGobOnce.Do(func() {\n")
	for _, name := range ordered {
		fmt.Fprintf(&text, "gob.Register(ir.%s{})\n", name)
	}
	fmt.Fprint(&text, "})\n}\n")
	source, err := format.Source(text.Bytes())
	if err != nil {
		t.Fatal(err)
	}
	return source
}

// Not parallel: the update flag rewrites the checked-in family wrappers.
func TestFlowFamilyWrappersAreCurrent(t *testing.T) {
	want := flowFamilyWrappers(t)
	if *updateFlowFamilyWrappers {
		if err := os.WriteFile("families_generated_test.go", want, 0644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile("families_generated_test.go")
	if err != nil || !bytes.Equal(got, want) {
		t.Fatal("Flow wrappers stale; run with -update-flow-family-wrappers", err)
	}
}
