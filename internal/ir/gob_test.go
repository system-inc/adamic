var updateGobTypes = flag.Bool("update-gob-types", false, "regenerate gob_types_generated.go")

// gobSourceTypes is every type internal/ir declares behind an Expression or a Statement, from its source: each type
// with a value-receiver Type() Type (Expression's one method) or statement() (Statement's). It holds as long as no
// struct embeds a type, whose methods it would take on without declaring them, and neither interface grows a method.
func gobSourceTypes(test *testing.T) []string {
	test.Helper()
	// Reads: internal/ir/*.go
	paths, globError := filepath.Glob("*.go")
	if globError != nil {
		test.Fatal(globError)
	}
	files := token.NewFileSet()
	names := map[string]bool{}
	interfaces := 0
	for _, path := range paths {
		if strings.HasSuffix(path, "_test.go") {
			continue
		}
		file, parseFileError := parser.ParseFile(files, path, nil, 0)
		if parseFileError != nil {
			test.Fatal(parseFileError)
		}
		ast.Inspect(file, func(node ast.Node) bool {
			switch node := node.(type) {
			case *ast.TypeSpec:
				if node.Name.Name == "Expression" || node.Name.Name == "Statement" {
					interfaces++
					if methods, ok := node.Type.(*ast.InterfaceType); !ok || len(methods.Methods.List) != 1 {
						test.Fatalf(
							"%s: ir.%s is no longer one method, which this enumeration relies on",
							files.Position(node.Pos()),
							node.Name.Name,
						)
					}
				}
				if structure, ok := node.Type.(*ast.StructType); ok {
					for _, field := range structure.Fields.List {
						if len(field.Names) == 0 {
							test.Fatalf(
								"%s: ir.%s embeds a type, whose methods this enumeration can't see",
								files.Position(field.Pos()),
								node.Name.Name,
							)
						}
					}
				}
			case *ast.FuncDecl:
				if node.Recv == nil || !(node.Name.Name == "Type" &&
					node.Type.Params.NumFields() == 0 &&
					node.Type.Results.NumFields() == 1 ||
					node.Name.Name == "statement") {
					return false
				}
				if result := node.Type.Results; node.Name.Name == "Type" {
					if identifier, ok := result.List[0].Type.(*ast.Ident); !ok || identifier.Name != "Type" {
						return false
					}
				}
				identifier, ok := node.Recv.List[0].Type.(*ast.Ident)
				if !ok {
					test.Fatalf(
						"%s: a %s method on a pointer receiver: only a value receiver is enumerated",
						files.Position(node.Pos()),
						node.Name.Name,
					)
				}
				names[identifier.Name] = true
				return false
			}
			return true
		})
	}
	if interfaces != 2 || len(names) < 100 {
		test.Fatalf(
			"found %d of Expression and Statement and %d types behind them: the enumeration no longer finds the IR",
			interfaces,
			len(names),
		)
	}
	return slices.Sorted(maps.Keys(names))
}

func gobTypesSource(test *testing.T) []byte {
	test.Helper()
	var text bytes.Buffer
	fmt.Fprint(
		&text,
		"// Code generated by TestGobRegistersEveryInterfaceType; DO NOT EDIT.\n// go test ./internal/ir -run '^TestGobRegistersEveryInterfaceType$' -args -update-gob-types\n\npackage ir\n\n",
	)
	fmt.Fprint(
		&text,
		"// gobTypes is every type internal/ir declares behind an Expression or a Statement, which RegisterGob registers.\nvar gobTypes = []any{\n",
	)
	for _, name := range gobSourceTypes(test) {
		fmt.Fprintf(&text, "%s{},\n", name)
	}
	fmt.Fprint(&text, "}\n")
	source, formatError := format.Source(text.Bytes())
	if formatError != nil {
		test.Fatal(formatError)
	}
	return source
}

// RegisterGob registers every type the source declares behind an Expression or a Statement, and nothing else, so a
// type added to the IR is registered before a program holding it fails to decode. Mutant: one type dropped from the
// list.
//
// Not parallel: the update flag rewrites the checked-in gob_types_generated.go.
func TestGobRegistersEveryInterfaceType(test *testing.T) {
	want := gobTypesSource(test)
	if *updateGobTypes {
		if writeError := os.WriteFile("gob_types_generated.go", want, 0o644); writeError != nil {
			test.Fatal(writeError)
		}
		return
	}
	got, readError := os.ReadFile("gob_types_generated.go")
	if readError != nil || !bytes.Equal(got, want) {
		test.Fatal("gob_types_generated.go is stale; run with -update-gob-types", readError)
	}
	expression, statement := reflect.TypeFor[Expression](), reflect.TypeFor[Statement]()
	for _, value := range gobTypes {
		if kind := reflect.TypeOf(value); !kind.Implements(expression) && !kind.Implements(statement) {
			test.Errorf("ir.%s is registered and is neither an Expression nor a Statement", kind.Name())
		}
	}
}

// walkGobTypes visits every type gob meets writing a program, once each: Program, every type behind an Expression or
// a Statement, and what their exported fields, elements, keys and pointers hold. at is the path it was first met by.
func walkGobTypes(visit func(kind reflect.Type, at string)) {
	seen := map[reflect.Type]bool{}
	var walk func(reflect.Type, string)
	walk = func(kind reflect.Type, at string) {
		if seen[kind] {
			return
		}
		seen[kind] = true
		visit(kind, at)
		switch kind.Kind() {
		case reflect.Map:
			walk(kind.Key(), at+"[key]")
			walk(kind.Elem(), at+"[value]")
		case reflect.Pointer, reflect.Slice, reflect.Array:
			walk(kind.Elem(), at+"[]")
		case reflect.Struct:
			for index := range kind.NumField() {
				if field := kind.Field(index); field.IsExported() {
					walk(field.Type, at+"."+field.Name)
				}
			}
		}
	}
	walk(reflect.TypeFor[Program](), "Program")
	for _, value := range gobTypes {
		kind := reflect.TypeOf(value)
		walk(kind, kind.Name())
	}
}

// rebuiltWhenNil are the unexported fields gob skips that no one needs back: each is a cache its reader rebuilds when
// it finds it nil, as it does in a program gob read.
var rebuiltWhenNil = map[string]string{
	"Program.argumentFacts":       "argumentFactsOf derives it again (argument_slots.go)",
	"Program.methodTables":        "methodTablesOf walks the method tables again (call_targets.go)",
	"BoundaryStringTable.indexes": "Intern rebuilds it from Values (boundary.go)",
}

// holdsFloat says whether a field's type is a float, or holds one without a struct between.
func holdsFloat(kind reflect.Type) bool {
	switch kind.Kind() {
	case reflect.Float32, reflect.Float64:
		return true
	case reflect.Pointer, reflect.Slice, reflect.Array:
		return holdsFloat(kind.Elem())
	case reflect.Map:
		return holdsFloat(kind.Key()) || holdsFloat(kind.Elem())
	}
	return false
}

// Every type a program holds gobs back exactly: each interface is one RegisterGob covers, no field is one gob skips
// (unexported, a function or a channel) unless its type writes it itself or it's a cache rebuilt when nil, every float
// is written by a type that keeps its bits, and no such type is a plain struct field, which gob drops when it's zero (a
// -0 with it). Mutants: NumberConstant's GobEncode gone; a field of a type holding no GobEncode made unexported.
func TestEveryTypeAProgramHoldsGobsExactly(test *testing.T) {
	test.Parallel()
	encoder, decoder := reflect.TypeFor[gob.GobEncoder](), reflect.TypeFor[gob.GobDecoder]()
	expression, statement := reflect.TypeFor[Expression](), reflect.TypeFor[Statement]()
	allowed := map[string]bool{}
	writesItself := func(kind reflect.Type) bool { return kind.Implements(encoder) }
	walkGobTypes(func(kind reflect.Type, at string) {
		switch kind.Kind() {
		case reflect.Interface:
			if kind != expression && kind != statement {
				test.Errorf("%s is a %s, which RegisterGob registers nothing behind", at, kind)
			}
		case reflect.Func, reflect.Chan, reflect.UnsafePointer, reflect.Complex64, reflect.Complex128:
			test.Errorf("%s is a %s, which gob can't carry exactly", at, kind)
		}
		if kind.Kind() != reflect.Pointer && writesItself(kind) && !reflect.PointerTo(kind).Implements(decoder) {
			test.Errorf("%s has GobEncode and no GobDecode", kind)
		}
		if kind.Kind() != reflect.Struct {
			return
		}
		for index := range kind.NumField() {
			field := kind.Field(index)
			name := kind.Name() + "." + field.Name
			if field.Type.Kind() == reflect.Struct && writesItself(field.Type) {
				test.Errorf(
					"%s.%s is a %s held as a plain field, which gob drops when it's zero: hold it through a pointer, a slice or an interface",
					at,
					field.Name,
					field.Type,
				)
			}
			if writesItself(kind) {
				continue
			}
			if !field.IsExported() {
				if why, ok := rebuiltWhenNil[name]; ok && why != "" {
					allowed[name] = true
					continue
				}
				test.Errorf(
					"%s.%s is unexported, so gob skips it: give %s a GobEncode that writes it, or list it in rebuiltWhenNil with why",
					at,
					field.Name,
					kind.Name(),
				)
			}
			if holdsFloat(field.Type) {
				test.Errorf(
					"%s.%s holds a float gob writes by value, -0 read back as +0: give %s a GobEncode that keeps its bits (gob.go)",
					at,
					field.Name,
					kind.Name(),
				)
			}
		}
	})
	for name := range rebuiltWhenNil {
		if !allowed[name] {
			test.Errorf("rebuiltWhenNil lists %s, which no type a program holds has", name)
		}
	}
}

// floatProbes are floats gob by value gets wrong (-0, NaN payloads) or that a broken bit encoding would.
var floatProbes = []float64{math.Copysign(0, -1), 0, 1.5, math.Inf(-1), math.Float64frombits(0x7ff8_0000_dead_beef),
	math.Float64frombits(0xfff0_0000_0000_0001)}

// Every float a program holds reads back with its bits, -0 and every NaN payload included, each float of each type
// holding one, written alone and inside a slice, as a program holds them. Mutant: a GobDecode setting a float from
// the copy gob wrote by value.
func TestEveryFloatAProgramHoldsReadsBackByItsBits(test *testing.T) {
	test.Parallel()
	RegisterGob()
	holders := 0
	walkGobTypes(func(kind reflect.Type, at string) {
		if kind.Kind() != reflect.Struct {
			return
		}
		for index := range kind.NumField() {
			if kind.Field(index).Type.Kind() != reflect.Float64 {
				continue
			}
			holders++
			for _, probe := range floatProbes {
				value := reflect.New(kind).Elem()
				value.Field(index).SetFloat(probe)
				var encoded bytes.Buffer
				if encodeValueError := gob.NewEncoder(&encoded).EncodeValue(
					reflect.Append(reflect.MakeSlice(reflect.SliceOf(kind), 0, 1), value),
				); encodeValueError != nil {
					test.Fatalf("%s: %v", at, encodeValueError)
				}
				read := reflect.New(reflect.SliceOf(kind))
				if decodeValueError := gob.NewDecoder(&encoded).DecodeValue(read); decodeValueError != nil {
					test.Fatalf("%s: %v", at, decodeValueError)
				}
				if got := read.Elem().Index(0).Field(index).Float(); math.Float64bits(got) != math.Float64bits(probe) {
					test.Errorf(
						"%s.%s: %#x read back as %#x",
						at,
						kind.Field(index).Name,
						math.Float64bits(probe),
						math.Float64bits(got),
					)
				}
			}
		}
	})
	if holders < 4 {
		test.Fatalf(
			"found %d float fields; NumberConstant, CounterGuard, ViewLiteral and JSONDecodeNode hold one each",
			holders,
		)
	}
}

// A -0 a program holds behind an Expression, and one in a counter guard held by pointer, read back as -0, and a
// guard with nothing in it reads back as a guard, not as none. Mutant: NumberConstant's GobEncode gone.
func TestANegativeZeroReadsBackFromGob(test *testing.T) {
	test.Parallel()
	RegisterGob()
	negative := math.Copysign(0, -1)
	program := Program{
		Functions: []Function{
			{Body: []Statement{Evaluate{NumberConstant{negative}}, Return{NumberConstant{negative}}}},
		},
		Locals: []Local{{CounterGuard: &CounterGuard{MaxStep: negative}}, {CounterGuard: &CounterGuard{}}},
	}
	var encoded bytes.Buffer
	if encodeError := gob.NewEncoder(&encoded).Encode(program); encodeError != nil {
		test.Fatal(encodeError)
	}
	var read Program
	if decodeError := gob.NewDecoder(&encoded).Decode(&read); decodeError != nil {
		test.Fatal(decodeError)
	}
	for position, statement := range read.Functions[0].Body {
		var value Expression
		switch statement := statement.(type) {
		case Evaluate:
			value = statement.Value
		case Return:
			value = statement.Value
		}
		if constant, ok := value.(NumberConstant); !ok || !math.Signbit(constant.Value) || constant.Value != 0 {
			test.Errorf("statement %d's -0 read back as %#v", position, value)
		}
	}
	if guard := read.Locals[0].CounterGuard; guard == nil || !math.Signbit(guard.MaxStep) {
		test.Errorf("a guard's -0 MaxStep read back as %#v", guard)
	}
	if read.Locals[1].CounterGuard == nil {
		test.Error("a guard with nothing in it read back as none")
	}
}

// A generated type's identity, which the cycle finder reads and gob skips, reads back as the one canonical identity,
// and a type without one reads back without one. Mutant: GeneratedType without GobEncode.
func TestAGeneratedTypeReadsBackWithItsIdentity(test *testing.T) {
	test.Parallel()
	program := Program{Generated: append(AsyncGeneratedTypes(), &GeneratedType{Name: "plain"})}
	var encoded bytes.Buffer
	if encodeError := gob.NewEncoder(&encoded).Encode(program); encodeError != nil {
		test.Fatal(encodeError)
	}
	var read Program
	if decodeError := gob.NewDecoder(&encoded).Decode(&read); decodeError != nil {
		test.Fatal(decodeError)
	}
	if len(read.Generated) != len(program.Generated) {
		test.Fatalf("%d generated types read back as %d", len(program.Generated), len(read.Generated))
	}
	for index, generated := range read.Generated {
		if generated.Name != program.Generated[index].Name || generated.identity != program.Generated[index].identity ||
			generated.RuntimeBreaksCycles() != (index < 3) {
			test.Errorf(
				"%s read back as %s with identity %v",
				program.Generated[index].Name,
				generated.Name,
				generated.identity,
			)
		}
	}
}

// A boundary table gob read interns a string it already holds at the index it holds it at.
func TestABoundaryTableGobReadInternsWhatItHolds(test *testing.T) {
	test.Parallel()
	var table BoundaryStringTable
	table.Intern("first")
	table.Intern("second")
	var encoded bytes.Buffer
	if encodeError := gob.NewEncoder(&encoded).Encode(table); encodeError != nil {
		test.Fatal(encodeError)
	}
	var read BoundaryStringTable
	if decodeError := gob.NewDecoder(&encoded).Decode(&read); decodeError != nil {
		test.Fatal(decodeError)
	}
	if read.Intern("second") != 1 || read.Intern("third") != 2 || len(read.Values) != 3 {
		test.Fatalf("the table read back interns as %v", read.Values)
	}
}
