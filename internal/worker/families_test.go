// Oracle's generator is in _test.go in package oracle and cannot be imported.
// Mirror its small table/generator/FNV ownership core; keep runners and case
// lists as the sole source of truth, and audit exact-once ownership below.
type workerFamily struct {
	name, runner string
	shards       int
	keys         func() []string
	product      bool
}

var workerFamilies = []workerFamily{
	{"TestWorkerDecodeJSON", "runWorkerDecodeJSONShard", 32, workerJSONDecodeKeys, false},
	{"TestWorkerEncodeJSON", "runWorkerEncodeJSONShard", 32, workerJSONEncodeKeys, false},
	{"TestWorkerdJavaScriptCorpus", "runWorkerdJavaScriptCorpusShard", 8, workerdCorpusKeys, false},
	{"TestWorkerdWebAssemblyCorpus", "runWorkerdWebAssemblyCorpusShard", 8, workerdCorpusKeys, false},
	{"TestProduct_WorkerJSON", "runWorkerJSONProductsShard", 32, workerJSONKeys, true},
	{"TestWorkerMutants", "runWorkerMutantsShard", 8, workerMutantKeys, false},
	{"TestWasmWorkerMutants", "runWasmWorkerMutantsShard", 16, wasmMutantKeys, false},
	{"TestWasmWorkers", "runWasmWorkersShard", 5, wasmFixtureKeys, false},
	{"TestWasmWorkerMemory", "runWasmWorkerMemoryShard", 1, func() []string { return []string{"transform"} }, false},
	{
		"TestWasmMultipleFunctions",
		"runWasmMultipleFunctionsShard",
		1,
		func() []string { return []string{"multiple"} },
		false,
	},
	{"TestProduct_WorkerWasm", "runWorkerWasmProductsShard", 8, wasmProductKeys, true},
	// These sizes leave at most one compiler mutation per product unit. Behavior
	// units group only already-built checks; they never group compiler rebuilds.
	{"TestProduct_WorkerMutants", "runWorkerMutantProductsShard", 24, workerMutantKeys, true},
	{"TestProduct_WorkerWasmMutants", "runWasmWorkerMutantProductsShard", 9, wasmMutantKeys, true},
}

func workerMutantKeys() []string {
	var keys []string
	for _, workerMutant := range workerMutants {
		keys = append(keys, workerMutant.name)
	}
	return keys
}
func wasmMutantKeys() []string {
	var keys []string
	for _, wasmWorkerMutant := range wasmWorkerMutants {
		keys = append(keys, wasmWorkerMutant.name)
	}
	return keys
}
func wasmFixtureKeys() []string {
	var keys []string
	for _, wasmVariant := range wasmVariants {
		if !wasmVariant.counted && wasmVariant.name != "multiple" {
			keys = append(keys, wasmVariant.name)
		}
	}
	return keys
}
func wasmProductKeys() []string {
	var keys []string
	for _, wasmVariant := range wasmVariants {
		if wasmVariant.name != "transform" {
			keys = append(keys, wasmVariant.name)
		}
	}
	return keys
}
func familyShard(key string, shards int) int {
	hash64 := fnv.New64a()
	hash64.Write([]byte(key))
	return int(hash64.Sum64() % uint64(shards))
}
func familyNamed(name string) workerFamily {
	for _, workerFamily := range workerFamilies {
		if workerFamily.name == name {
			return workerFamily
		}
	}
	panic("unknown Worker family " + name)
}
func familyOwns(name string, shard int, key string) bool {
	return familyShard(key, familyNamed(name).shards) == shard
}
func familyCaseName(name, key string) string {
	return fmt.Sprintf("%s_%03d", name, familyShard(key, familyNamed(name).shards))
}

var updateWorkerFamilyWrappers = flag.Bool(
	"update-worker-family-wrappers",
	false,
	"regenerate families_generated_test.go",
)

func workerFamilyWrappers(test *testing.T) []byte {
	test.Helper()
	var text bytes.Buffer
	fmt.Fprint(
		&text,
		"// Code generated by TestWorkerFamilyWrappersAreCurrent; DO NOT EDIT.\n// go test ./internal/worker -run '^TestWorkerFamilyWrappersAreCurrent$' -args -update-worker-family-wrappers\n\npackage worker\n\nimport \"testing\"\n",
	)
	for _, workerFamily := range workerFamilies {
		for index := 0; index < workerFamily.shards; index++ {
			if workerFamily.product {
				fmt.Fprint(&text, "\n// Not parallel: build products share compiler and runtime inputs.\n")
			}
			fmt.Fprintf(&text, "func %s_%03d(t *testing.T) {\n", workerFamily.name, index)
			if !workerFamily.product {
				fmt.Fprint(&text, "t.Parallel()\n")
			}
			fmt.Fprintf(&text, "%s(t, %d)\n}\n", workerFamily.runner, index)
		}
	}
	source, formatError := format.Source(text.Bytes())
	if formatError != nil {
		test.Fatal(formatError)
	}
	return source
}

// Not parallel: the update flag rewrites the checked-in family wrappers.
func TestWorkerFamilyWrappersAreCurrent(test *testing.T) {
	want := workerFamilyWrappers(test)
	if *updateWorkerFamilyWrappers {
		if writeError := os.WriteFile("families_generated_test.go", want, 0644); writeError != nil {
			test.Fatal(writeError)
		}
		return
	}
	got, readError := os.ReadFile("families_generated_test.go")
	if readError != nil || !bytes.Equal(got, want) {
		test.Fatal("Worker wrappers stale; run with -update-worker-family-wrappers", readError)
	}
}
func TestWorkerFamiliesOwnEveryCaseOnce(test *testing.T) {
	test.Parallel()
	for _, workerFamily := range workerFamilies {
		seen := map[string]bool{}
		for _, key := range workerFamily.keys() {
			if seen[key] {
				test.Fatalf("%s registers %s twice", workerFamily.name, key)
			}
			seen[key] = true
			owners := 0
			for index := 0; index < workerFamily.shards; index++ {
				if familyOwns(workerFamily.name, index, key) {
					owners++
				}
			}
			if owners != 1 {
				test.Fatalf("%s/%s has %d owners", workerFamily.name, key, owners)
			}
		}
		if len(seen) == 0 {
			test.Fatalf("%s has no cases", workerFamily.name)
		}
	}
}
